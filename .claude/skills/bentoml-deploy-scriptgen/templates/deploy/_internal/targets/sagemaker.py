_AWS_CLI_VERSION_RE = re.compile(r"aws-cli/(\d+)\.(\d+)\.(\d+)")

# Endpoint statuses during which no create/update/delete may be issued.
_BUSY_STATUSES = (
    "Creating",
    "Updating",
    "SystemUpdating",
    "RollingBack",
    "Deleting",
)

# Instance provisioning + image pull budget added on top of the container's
# own startup-health-check budget to form the Python-side overall timeout
# around `aws sagemaker wait endpoint-in-service` (which itself polls every
# 30 s and gives up after 120 polls).
_PROVISION_BUDGET_SECONDS = 1500

_ROLE_HINT = (
    "provide the ARN of an existing role whose trust policy includes "
    "sagemaker.amazonaws.com — this script never creates or modifies IAM. "
    "The interactive bentoml-sagemaker-deploy skill finds candidate roles "
    "with a trust-policy scan, and its references/aws-setup.md carries a "
    "ready-to-send admin snippet when the role must be created by an "
    "account admin."
)


def _aws_sm(sm: SageMakerConfig, *args: str) -> list[str]:
    return ["aws", "sagemaker", *args, "--region", sm.region]


def _sanitize_tag(version: str) -> str:
    """Map an image tag onto SageMaker's name alphabet (alphanumerics and
    hyphens): every run of other characters becomes one hyphen."""
    return re.sub(r"[^A-Za-z0-9]+", "-", version).strip("-")


def _derived_name(sm: SageMakerConfig, version: str) -> str:
    """The per-tag name shared by the model and the endpoint config."""
    tag = _sanitize_tag(version)
    if not tag:
        raise DeployError(
            f"version tag {version!r} sanitizes to an empty SageMaker name",
            EXIT_DEPLOY,
            hint="pass a --version containing at least one alphanumeric character",
        )
    if tag != version:
        # Sanitizing is lossy (v1.2.3 and v1-2-3 both become v1-2-3); a
        # short stable hash of the raw tag keeps distinct tags distinct —
        # otherwise a redeploy of the aliasing tag would hit the
        # already-live no-op branch and silently not deploy.
        tag += "-" + hashlib.sha256(version.encode("utf-8")).hexdigest()[:6]
    name = f"{sm.endpoint_name}-{tag}"
    if len(name) > 63 or not SAGEMAKER_NAME_RE.match(name):
        raise DeployError(
            f"derived model/endpoint-config name {name!r} is not a valid "
            "SageMaker name (max 63 chars, pattern "
            f"{SAGEMAKER_NAME_RE.pattern})",
            EXIT_DEPLOY,
            hint="shorten targets.sagemaker.endpoint_name or use a shorter "
            "--version tag",
        )
    return name


def _describe_endpoint(
    sm: SageMakerConfig, exit_code: int = EXIT_DEPLOY
) -> dict | None:
    """The endpoint's describe-endpoint document, or None if it does not
    exist."""
    res = run(
        _aws_sm(
            sm,
            "describe-endpoint",
            "--endpoint-name",
            sm.endpoint_name,
            "--output",
            "json",
        ),
        capture=True,
        quiet=True,
        check=False,
        timeout=60,
    )
    if res.returncode != 0:
        err = res.stderr.strip() or res.stdout.strip()
        if "Could not find endpoint" in err:
            return None
        raise DeployError(
            f"could not describe endpoint {sm.endpoint_name!r}: {err[:300]}",
            exit_code,
            hint="check AWS credentials, targets.sagemaker.region, and that "
            "the identity may call sagemaker:DescribeEndpoint",
        )
    try:
        return json.loads(res.stdout)
    except json.JSONDecodeError:
        raise DeployError(
            "describe-endpoint returned unparseable JSON", exit_code
        ) from None


def _resource_exists(sm: SageMakerConfig, describe_args: list, kind: str) -> bool:
    res = run(
        _aws_sm(sm, *describe_args, "--output", "json"),
        capture=True,
        quiet=True,
        check=False,
        timeout=60,
    )
    if res.returncode == 0:
        return True
    err = res.stderr.strip() or res.stdout.strip()
    if "Could not find" in err:
        return False
    raise DeployError(
        f"could not describe {kind}: {err[:300]}",
        EXIT_DEPLOY,
        hint="check AWS credentials and the sagemaker:Describe* permissions",
    )


