class _SshTunnel:
    """``ssh -v -N -L`` with liveness checks and guaranteed cleanup — the
    SSH sibling of the k8s target's _PortForward.

    ssh binds the local port only AFTER authentication, so "the port
    answers" is never proof that ssh owns it. Squatter defense is therefore
    two layers: (1) the constructor bind-probes 127.0.0.1:<local_tunnel_port>
    and refuses to spawn ssh while anything already listens there —
    otherwise a pre-existing listener would answer the first probes during
    the auth window with convincing but fake results; (2) the tunnel runs
    with -v, and wait_until_forwarding() requires ssh's own "Local
    forwarding listening on 127.0.0.1 port N" line in the captured log (the
    SSH equivalent of _PortForward's 'Forwarding from' gate) before any TCP
    connect is trusted, re-checking alive() around every probe — this also
    covers a squatter that grabs the port in the gap between the bind-probe
    and ssh's own bind, because ssh then dies (ExitOnForwardFailure=yes) or
    never prints the ownership line. ExitOnForwardFailure stays
    load-bearing for exactly that reason: without it ssh keeps running when
    the forward fails; with it, process death fails fast with the captured
    stderr. The IPv4-pinned -L spec closes the variant where ssh stays
    alive on an IPv6-only bind while an IPv4 squatter answers 127.0.0.1.
    """

    def __init__(self, ec2: Ec2Config, host: str) -> None:
        self._ec2 = ec2
        self._host = host
        # Layer 1: refuse to spawn while the local port is taken. The probe
        # sets SO_REUSEADDR (like ssh's own listener) so a previous host's
        # tunnel socket lingering in TIME_WAIT does not false-positive, but
        # an ACTIVE listener still fails the bind.
        probe = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
        try:
            probe.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
            probe.bind(("127.0.0.1", ec2.local_tunnel_port))
        except OSError as exc:
            raise DeployError(
                f"local port {ec2.local_tunnel_port} is already in use "
                f"({exc}) — refusing to start the SSH tunnel: ssh binds the "
                "port only after authentication, so whatever is listening "
                "there now would answer the verification probes instead of "
                "the service (convincing but fake results)",
                EXIT_VERIFY,
                hint="free the local port, or change ec2.local_tunnel_port",
            ) from None
        finally:
            probe.close()
        # Not a context manager on purpose: the file must outlive this
        # constructor (ssh writes to it until close()).
        self._log = tempfile.NamedTemporaryFile(  # noqa: SIM115
            mode="w+", prefix="bentoml-deploy-ec2-tunnel-", suffix=".log", delete=False
        )
        self._proc = subprocess.Popen(
            [
                *_ssh_base(ec2),
                "-o",
                "ExitOnForwardFailure=yes",
                # -v is load-bearing: it makes ssh print the "Local
                # forwarding listening ..." line that wait_until_forwarding
                # requires as ownership evidence.
                "-v",
                "-N",
                "-L",
                # Explicit IPv4 bind address: without it ssh also binds ::1,
                # and an IPv4-only squatter would leave ssh alive (IPv6 bind
                # ok) while our 127.0.0.1 probes hit the squatter.
                f"127.0.0.1:{ec2.local_tunnel_port}:127.0.0.1:{ec2.host_port}",
                f"{ec2.ssh_user}@{host}",
            ],
            stdin=subprocess.DEVNULL,
            stdout=self._log,
            stderr=self._log,
            text=True,
        )

    def alive(self) -> bool:
        return self._proc.poll() is None

    def wait_until_forwarding(self, timeout_seconds: float) -> None:
        deadline = time.monotonic() + timeout_seconds
        while time.monotonic() < deadline:
            if not self.alive():
                raise DeployError(
                    f"SSH tunnel to {self._host} exited before forwarding:\n"
                    + self.captured_output(),
                    EXIT_VERIFY,
                    hint=f"is local port {self._ec2.local_tunnel_port} free "
                    "(ec2.local_tunnel_port), and does BatchMode "
                    f"SSH to {self._host} work?",
                )
            # Ownership evidence first: ssh binds the local port only AFTER
            # authentication, so a bare TCP connect during the auth window
            # could be answered by a squatter. Require ssh's own -v banner
            # before trusting any connect.
            if "Local forwarding listening" not in self.captured_output():
                time.sleep(0.2)
                continue
            try:
                conn = socket.create_connection(
                    ("127.0.0.1", self._ec2.local_tunnel_port), timeout=0.5
                )
            except OSError:
                time.sleep(0.2)
                continue
            conn.close()
            if self.alive():
                return
        raise DeployError(
            f"SSH tunnel to {self._host} did not start forwarding within "
            f"{timeout_seconds:.0f}s:\n" + self.captured_output(),
            EXIT_VERIFY,
        )

    def captured_output(self) -> str:
        try:
            with open(self._log.name, encoding="utf-8") as fh:
                return fh.read().strip()
        except OSError:
            return "(no tunnel output captured)"

    def close(self) -> None:
        if self._proc.poll() is None:
            self._proc.terminate()
            try:
                self._proc.wait(timeout=5)
            except subprocess.TimeoutExpired:
                self._proc.kill()
                self._proc.wait(timeout=5)
        self._log.close()
        try:
            Path(self._log.name).unlink()
        except OSError:
            pass


def verify(ctx: RunContext) -> None:
    ec2 = ctx.cfg.require_ec2()
    vcfg = ctx.cfg.verify
    for index, host in enumerate(ec2.hosts):
        started = time.monotonic()
        try:
            _verify_host(ec2, vcfg, host)
        except BaseException:
            ctx.summary.record_stage(
                f"ec2.verify[{host}]", False, time.monotonic() - started
            )
            for later in ec2.hosts[index + 1 :]:
                ctx.summary.record_stage(
                    f"ec2.verify[{later}]",
                    False,
                    0.0,
                    detail="not attempted (fail-fast after a previous host failed)",
                )
            raise
        ctx.summary.record_stage(
            f"ec2.verify[{host}]", True, time.monotonic() - started
        )


def _verify_host(ec2: Ec2Config, vcfg: VerifyConfig, host: str) -> None:
    if ec2.verify_via == "direct":
        base_url = f"http://{host}:{ec2.host_port}"
        section(f"verify {host}: /readyz direct on {base_url}")
        # A direct probe cannot prove WHO answered — re-check over SSH that
        # our container is the process behind the port before trusting HTTP.
        status = _container_status(ec2, host)
        if not status.startswith("Up"):
            raise DeployError(
                f"container {ec2.container_name} on {host} is not Up "
                f"(status: {status or 'gone'}) — direct HTTP results would "
                "be meaningless",
                EXIT_VERIFY,
                hint=_rollback_guidance(ec2, host),
            )
        _wait_ready(ec2, host, base_url, vcfg.readyz_timeout_seconds, None)
        if vcfg.inference is None:
            log(
                "verify.inference is not configured — verification is /readyz "
                "only (add a verify.inference block to POST a real request)"
            )
        else:
            _inference_smoke(host, base_url, vcfg.inference, None)
        return
    base_url = f"http://127.0.0.1:{ec2.local_tunnel_port}"
    section(f"verify {host}: /readyz via SSH tunnel on {base_url}")
    tunnel = _SshTunnel(ec2, host)
    try:
        tunnel.wait_until_forwarding(30)
        _wait_ready(ec2, host, base_url, vcfg.readyz_timeout_seconds, tunnel)
        if vcfg.inference is None:
            log(
                "verify.inference is not configured — verification is /readyz "
                "only (add a verify.inference block to POST a real request)"
            )
        else:
            _inference_smoke(host, base_url, vcfg.inference, tunnel)
    finally:
        tunnel.close()


def _wait_ready(
    ec2: Ec2Config,
    host: str,
    base_url: str,
    timeout_seconds: int,
    tunnel: _SshTunnel | None,
) -> None:
    deadline = time.monotonic() + timeout_seconds
    attempt = 0
    while True:
        if tunnel is not None and not tunnel.alive():
            raise DeployError(
                f"SSH tunnel to {host} exited unexpectedly:\n"
                + tunnel.captured_output(),
                EXIT_VERIFY,
                hint=f"is local port {ec2.local_tunnel_port} free "
                f"(ec2.local_tunnel_port), and is SSH to {host} stable?",
            )
        attempt += 1
        try:
            status, _ = http_get(base_url + "/readyz", timeout=3)
            if status == 200:
                if tunnel is not None and not tunnel.alive():
                    # The tunnel died — whatever answered was not our
                    # service. Never trust a probe the tunnel can't explain.
                    raise DeployError(
                        "SSH tunnel died during the readiness probe; the "
                        "200 response cannot be trusted:\n" + tunnel.captured_output(),
                        EXIT_VERIFY,
                    )
                log(f"/readyz on {host} returned 200 (attempt {attempt})")
                return
            log(f"/readyz returned {status} — retrying")
        except (urllib.error.URLError, OSError, ConnectionError) as exc:
            if attempt % 5 == 1:
                log(f"waiting for /readyz on {host} ({exc})")
        if time.monotonic() >= deadline:
            detail = ""
            if tunnel is not None:
                detail = f"; tunnel output:\n{tunnel.captured_output()}"
            else:
                detail = (
                    " (direct verify: the security group must allow port "
                    f"{ec2.host_port} from this machine's IP — set "
                    "ec2.verify_via to 'tunnel' if it does not)"
                )
            raise DeployError(
                f"service on {host} did not become ready within "
                f"{timeout_seconds}s{detail}",
                EXIT_VERIFY,
                hint=_rollback_guidance(ec2, host),
            )
        time.sleep(2)


def _inference_smoke(
    host: str, base_url: str, inference: InferenceCheck, tunnel: _SshTunnel | None
) -> None:
    url = base_url + inference.path
    log(f"inference smoke test on {host}: POST {inference.path}")
    if tunnel is not None and not tunnel.alive():
        raise DeployError(
            "SSH tunnel died before the inference request:\n"
            + tunnel.captured_output(),
            EXIT_VERIFY,
        )
    try:
        status, body = http_post_json(
            url, inference.body, timeout=inference.timeout_seconds
        )
    except (urllib.error.URLError, OSError) as exc:
        raise DeployError(
            f"inference request to {inference.path} on {host} failed: {exc}",
            EXIT_VERIFY,
        ) from None
    if tunnel is not None and not tunnel.alive():
        raise DeployError(
            "SSH tunnel died during the inference request; the response "
            "cannot be trusted:\n" + tunnel.captured_output(),
            EXIT_VERIFY,
        )
    snippet = body[:500].replace("\n", " ")
    log(f"response {status}: {snippet}")
    if not 200 <= status < 300:
        raise DeployError(
            f"inference smoke test returned HTTP {status} for "
            f"{inference.path} on {host} (body: {snippet})",
            EXIT_VERIFY,
            hint="check verify.inference.body against the service's "
            "@bentoml.api signature",
        )
    if inference.expect_substring and inference.expect_substring not in body:
        raise DeployError(
            f"inference response from {host} did not contain expected "
            f"substring {inference.expect_substring!r} (body: {snippet})",
            EXIT_VERIFY,
        )
    log("inference smoke test passed")
