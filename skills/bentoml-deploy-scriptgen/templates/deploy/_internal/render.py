def labels_for(cfg: Config, svc: ServiceSpec) -> dict[str, str]:
    """Per-service identity labels, plus kubernetes.extra_labels. The
    app.kubernetes.io/* keys are managed here and win over extra_labels: the
    selector matches on app.kubernetes.io/name, so letting it be overridden
    would make a Deployment adopt no pods (or a sibling's)."""
    labels: dict[str, str] = {}
    k8s = cfg.require_k8s()
    for key, value in sorted(k8s.extra_labels.items()):
        labels[key] = value
    labels["app.kubernetes.io/name"] = svc.slug
    labels["app.kubernetes.io/component"] = svc.name
    labels["app.kubernetes.io/part-of"] = cfg.bento_name
    labels["app.kubernetes.io/managed-by"] = MANAGED_BY
    return labels


def service_url(k8s: K8sConfig, svc: ServiceSpec) -> str:
    return f"http://{svc.slug}.{k8s.namespace}.svc.cluster.local:{CONTAINER_PORT}"


def serve_depends_value(k8s: K8sConfig, svc: ServiceSpec) -> str:
    """`Name=URL` pairs for this service's DIRECT dependencies, whitespace
    separated (BentoML splits the value on whitespace). The key must be the
    BentoML service name exactly — lookup is by that key, and an unresolved
    dependency is silently instantiated in-process. The URL must contain no
    '=': each pair is split on '=' and a second one raises at startup."""
    by_name = {other.name: other for other in k8s.services}
    return " ".join(f"{name}={service_url(k8s, by_name[name])}" for name in svc.depends)


def config_overrides_value(svc: ServiceSpec) -> str:
    """The BENTOML_CONFIG_OVERRIDES payload for one service: its BARE
    `config_overrides` document nested under its own service name.

    The nesting is load-bearing. A global `{"services": {"<key>": ...}}` block
    is merged UNDER the @bentoml.service(...) decorator and loses; only the
    per-service form `{"services": {"<ServiceName>": {...}}}` beats it. So the
    user writes bare keys (`workers: 2`, `traffic: {timeout: 120}`) and this
    wraps them.
    """
    return json.dumps(
        {"services": {svc.name: svc.config_overrides}}, separators=(",", ":")
    )


def _env_list(cfg: Config, k8s: K8sConfig, svc: ServiceSpec) -> list[dict[str, str]]:
    """The container's env, in a stable order: derived wiring first, then the
    user's plain vars.

    A variable the user set explicitly in `env` is NEVER also derived — the raw
    value wins and nothing is emitted twice. That is the documented escape for
    the caller-side dependency-timeout trap: a call's client deadline is read
    from the CALLER's config under the CALLEE's name, which a per-service
    `config_overrides` block cannot express, so you write the full JSON as a
    raw env var instead. The config loader warns when this happens.
    """
    env: list[dict[str, str]] = []
    if svc.depends and SERVE_DEPENDS_ENV not in svc.env:
        env.append({"name": SERVE_DEPENDS_ENV, "value": serve_depends_value(k8s, svc)})
    if svc.config_overrides and CONFIG_OVERRIDES_ENV not in svc.env:
        env.append({"name": CONFIG_OVERRIDES_ENV, "value": config_overrides_value(svc)})
    for name in sorted(svc.env):
        env.append({"name": name, "value": svc.env[name]})
    return env


