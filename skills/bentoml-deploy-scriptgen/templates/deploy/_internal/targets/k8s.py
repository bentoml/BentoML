def preflight(ctx: RunContext) -> None:
    """Standalone entry point: run this target's checks in one pass."""
    run_checks(preflight_checks(ctx))


def preflight_checks(ctx: RunContext) -> list:
    """Build this target's checks so deploy.py can aggregate them with the
    build-side families into a single report. With ctx.local_only, only
    checks that need no cluster connectivity are returned; the rest are
    recorded in the summary's skipped list."""
    k8s = ctx.cfg.require_k8s()

    def kubectl_cli() -> str | None:
        _which("kubectl", "install kubectl and configure access to the cluster")
        return None

    def context_reachable() -> str | None:
        res = run(
            _kubectl(k8s, "version", "--request-timeout=10s", "-o", "yaml"),
            capture=True,
            quiet=True,
            check=False,
            timeout=30,
        )
        if res.returncode != 0:
            raise CheckFailed(
                f"cluster for context {k8s.context!r} is not reachable: {(res.stderr.strip() or res.stdout.strip())[:300]}",
                hint="check the context name (kubectl config get-contexts), "
                "VPN/credentials, and that the cluster is up",
            )
        return f"context {k8s.context} reachable"

    def rbac() -> str | None:
        res = run(
            _kubectl(k8s, "auth", "can-i", "create", "deployment", "-n", k8s.namespace),
            capture=True,
            quiet=True,
            check=False,
            timeout=30,
        )
        if res.stdout.strip().lower() != "yes":
            raise CheckFailed(
                f"identity for context {k8s.context!r} may not create deployments in "
                f"namespace {k8s.namespace!r}",
                hint="ask a cluster admin for edit rights in the namespace, "
                "or fix kubernetes.namespace",
            )
        return None

    def namespace_exists() -> str | None:
        # Still required even though nothing renders a Namespace object: this
        # bundle never creates namespaces (a bundle that could would happily
        # create a typo'd one).
        res = run(
            _kubectl(k8s, "get", "namespace", k8s.namespace),
            capture=True,
            quiet=True,
            check=False,
            timeout=30,
        )
        if res.returncode != 0:
            raise CheckFailed(
                f"namespace {k8s.namespace!r} does not exist in context {k8s.context!r}",
                hint=f"kubectl --context {k8s.context} create namespace {k8s.namespace}",
            )
        return None

    def pull_secret() -> str | None:
        if not k8s.image_pull_secret:
            # Nothing named in config.yml. The pods will run under the
            # namespace's `default` serviceaccount, so credentials can still
            # come from that account's imagePullSecrets, or from the nodes
            # themselves (an EKS instance role with the ECR credential
            # provider, a kubelet docker config, or a public registry). None of
            # those can be proven from here, but the serviceaccount can be
            # read, and its absence is the single most common cause of a
            # rollout that dies of ImagePullBackOff after burning the whole
            # rollout timeout.
            sa = run(
                _kubectl(
                    k8s,
                    "get",
                    "serviceaccount",
                    "default",
                    "-n",
                    k8s.namespace,
                    "-o",
                    "jsonpath={.imagePullSecrets[*].name}",
                ),
                capture=True,
                quiet=True,
                check=False,
                timeout=30,
            )
            names = sa.stdout.split() if sa.returncode == 0 else []
            if names:
                return (
                    "none in config.yml; the namespace's default "
                    "serviceaccount supplies " + ", ".join(sorted(names))
                )
            host = ctx.cfg.image.registry or "docker.io"
            if ctx.cfg.image.kind == REGISTRY_KIND_ECR:
                warn(
                    f"no image pull secret: {host} is a private ECR registry, "
                    "which always requires authentication, and neither "
                    "kubernetes.image_pull_secret nor the namespace's default "
                    "serviceaccount names one. Unless the NODES carry ECR "
                    "credentials (an instance role plus the ECR credential "
                    "provider), every pod will fail with ImagePullBackOff. "
                    "Fix it either way:\n"
                    f"  kubectl --context {k8s.context} -n {k8s.namespace} "
                    "create secret docker-registry ecr-creds "
                    f"--docker-server={host} --docker-username=AWS "
                    '--docker-password="$(aws ecr get-login-password '
                    f'--region {ctx.cfg.image.ecr_region or "<region>"})"\n'
                    "then set kubernetes.image_pull_secret: ecr-creds (an ECR "
                    "token expires after 12 h — recreate the secret or give "
                    "the nodes a credential provider for anything long-lived)"
                )
            elif ctx.cfg.image.pushes:
                warn(
                    "no image pull secret: neither kubernetes.image_pull_secret "
                    "nor the namespace's default serviceaccount names one, so "
                    f"the cluster must be able to pull {host} anonymously or "
                    "with node-level credentials. If it cannot, the pods fail "
                    "with ImagePullBackOff (create a docker-registry secret "
                    "and set kubernetes.image_pull_secret)"
                )
            return "no image pull secret configured"
        res = run(
            _kubectl(
                k8s,
                "get",
                "secret",
                k8s.image_pull_secret,
                "-n",
                k8s.namespace,
                "-o",
                "jsonpath={.metadata.creationTimestamp}",
            ),
            capture=True,
            quiet=True,
            check=False,
            timeout=30,
        )
        if res.returncode != 0:
            raise CheckFailed(
                f"image pull secret {k8s.image_pull_secret!r} not found in namespace {k8s.namespace!r}",
                hint=f"kubectl --context {k8s.context} create secret docker-registry {k8s.image_pull_secret} "
                f"-n {k8s.namespace} --docker-server=... --docker-username=... "
                "--docker-password=...",
            )
        if ctx.cfg.image.kind == REGISTRY_KIND_ECR:
            created = parse_k8s_timestamp(res.stdout)
            if created is not None:
                age = datetime.now(timezone.utc) - created
                if age > ECR_PULL_SECRET_MAX_AGE:
                    warn(
                        f"ECR pull secret {k8s.image_pull_secret!r} is {age.total_seconds() / 3600:.1f} h old — ECR tokens expire "
                        "after 12 h, so image pulls will likely fail. "
                        "Delete and recreate the secret with a fresh "
                        "'aws ecr get-login-password' (kubectl apply keeps "
                        "the original creationTimestamp, so recreating is "
                        "the only way this check can see it as fresh). Note "
                        "this age check is a heuristic: it cannot detect a "
                        "recently created secret that embeds an "
                        "already-expired token."
                    )
        return None

    def topology_source() -> str | None:
        """Report where the bento's service topology came from — or why there
        is none yet. config.yml carries no service list, no entry service and
        no `depends`: they are read from the bento's own bento.yaml (see
        _internal/topology.py) out of the local bento store, the image, or the
        cache next to config.yml."""
        topo = ctx.cfg.topology
        if topo is not None:
            return f"{topo.describe()} — from the {topo.source}"
        if ctx.skip_build:
            # Nothing later in this run will produce it: --skip-build means no
            # bento is built, so the store cannot answer either.
            err = unavailable_error(ctx.cfg.bundle_dir, ctx.image)
            raise CheckFailed(str(err), hint=err.hint)
        warn(
            "the service topology is not available yet — it will be read from "
            "the bento this run builds. Until then there is nothing to render, "
            "so k8s.render and k8s.rollout-plan are skipped this time. Commit "
            "the .bento-topology.json cache (or run once with --skip-build "
            "against the built image) to get those checks in a build-free run."
        )
        return "UNRESOLVED — will come from the bento built by this run"

    def node_arch() -> str | None:
        """Cross-architecture detection, the replacement for v3's
        `image.platform`: compare the builder's architecture with the cluster
        nodes' `kubernetes.io/arch` and, when they differ, build for the nodes'
        (an image of the wrong architecture starts and then dies with 'exec
        format error', burning the whole rollout timeout in CrashLoopBackOff).
        """
        builder = docker_builder_arch()
        arches = cluster_node_arches(k8s.context)
        decision = decide_platform(builder, arches, "cluster nodes")
        if decision.cross and not buildx_available():
            raise CheckFailed(
                f"a cross-architecture build is needed ({decision.message}) "
                "but docker buildx is not available",
                hint="install the docker buildx plugin (it ships with Docker "
                "Desktop; on Debian/Ubuntu: the docker-buildx-plugin package). "
                "BuildKit is what honours the platform flag — without it the "
                "image would be built for the wrong architecture and every pod "
                "would die with 'exec format error'.",
            )
        if decision.mixed:
            warn(decision.message)
        if decision.cross:
            ctx.build_platform = decision.platform
            log(f"  cross-arch build enabled: --opt platform={decision.platform}")
        return decision.message

    # ---- rendering path ---------------------------------------------------

    def render_ok() -> str | None:
        """Render the manifests exactly as the deploy would and prove the
        result is well-formed YAML. Cheap, credential-free, and it is also the
        check that the config renders AT ALL before anything is built."""
        image = ctx.image or "pending/unresolved:image"
        docs = render_documents(ctx.cfg, image)
        if yaml is not None:
            for doc in docs:
                try:
                    parsed = yaml.safe_load(doc.text)
                except yaml.YAMLError as exc:
                    raise CheckFailed(
                        f"rendered {doc.kind}/{doc.name} is not valid YAML: {exc}",
                        hint="this is a bug in the bundle, not in your config "
                        "— report it with the config.yml that triggered it "
                        "(see it with --render-only)",
                    ) from None
                if not isinstance(parsed, dict) or "kind" not in parsed:
                    raise CheckFailed(
                        f"rendered {doc.filename} is not a Kubernetes object",
                        hint="this is a bug in the bundle, not in your config",
                    )
        kinds: dict[str, int] = {}
        for doc in docs:
            kinds[doc.kind] = kinds.get(doc.kind, 0) + 1
        summary = ", ".join(f"{count} {kind}" for kind, count in sorted(kinds.items()))
        return f"{summary} rendered from config.yml"

    def rollout_plan() -> str | None:
        """Report the DERIVED rollout order and the dependency wiring EXACTLY as
        it will be emitted, so a wrong `depends:` — or a hand-written
        BENTOML_SERVE_DEPENDS that replaces it — is visible before the deploy
        rather than after."""
        wired = 0
        for svc in k8s.services:
            raw = svc.env.get(SERVE_DEPENDS_ENV)
            if raw is not None:
                # The raw value REPLACES the derived one (the loader validated
                # its syntax and that it covers `depends`). Print what the pod
                # actually gets, never the value that is not emitted.
                wired += 1
                log(f"    {svc.name} -> {raw}   [raw, from services.{svc.name}.env]")
                continue
            if not svc.depends:
                continue
            wired += 1
            value = serve_depends_value(k8s, svc)
            for pair in value.split():
                # Belt-and-braces on the renderer's own output: a URL with a
                # '=' in it raises at BentoML startup, and a comma-separated
                # value makes the dependency silently in-process.
                if pair.count("=") != 1:
                    raise CheckFailed(
                        f"{svc.name}: {SERVE_DEPENDS_ENV} pair {pair!r} does "
                        "not have exactly one '='",
                        hint="a slug or namespace containing '=' cannot be "
                        "expressed — fix services.<name>.slug / "
                        "kubernetes.namespace",
                    )
            log(f"    {svc.name} -> {value}")
        order = " -> ".join(f"{svc.name} ({svc.slug})" for svc in k8s.services)
        return (
            f"rollout order {order}; {wired} service(s) wired via {SERVE_DEPENDS_ENV}"
        )

    # ---- kubernetes.manifests_dir path (hand-owned YAML) ------------------
    #
    # These files are applied verbatim, so every invariant the renderer
    # guarantees has to be re-checked here. The checks are STRUCTURAL (PyYAML is
    # a hard requirement of this bundle anyway): a regex over lines can only see
    # the file it was pointed at, and the fault that matters most — an extra
    # file exposing a dependency's pods — lives in a file no per-service naming
    # convention would ever name.

    def _objects() -> list[tuple[Path, int, dict]]:
        """Every Kubernetes object in the directory, as (file, doc index, obj).
        Multi-document files included; a parse failure is a check failure (the
        apply would fail on it anyway, after other objects were created)."""
        out: list[tuple[Path, int, dict]] = []
        for path in _manifest_files(k8s):
            text = path.read_text(encoding="utf-8")
            if PLACEHOLDER_RE.search(text):
                raise CheckFailed(
                    f"unreplaced {{{{PLACEHOLDER}}}} values remain in {path.name}",
                    hint="regenerate the manifests with --render-only (after "
                    "unsetting kubernetes.manifests_dir), or fill them in",
                )
            try:
                docs = list(yaml.safe_load_all(text))
            except yaml.YAMLError as exc:
                raise CheckFailed(
                    f"{path.name} is not valid YAML: {exc}",
                    hint="kubectl apply would reject it — after having already "
                    "created the objects from the files before it",
                ) from None
            for index, doc in enumerate(docs, start=1):
                if doc is None:  # a trailing '---' or a comment-only document
                    continue
                if not isinstance(doc, dict) or "kind" not in doc:
                    where = path.name if index == 1 else f"{path.name} (doc {index})"
                    raise CheckFailed(
                        f"{where} is not a Kubernetes object (no 'kind')",
                        hint="every document in this directory is applied; "
                        "remove the file or the stray document",
                    )
                out.append((path, index, doc))
        return out

    def _where(path: Path, index: int) -> str:
        return path.name if index == 1 else f"{path.name} (document {index})"

    def _meta(obj: dict) -> dict:
        meta = obj.get("metadata")
        return meta if isinstance(meta, dict) else {}

    def _pod_spec(obj: dict) -> dict | None:
        """The PodSpec of a workload object, whatever wraps it."""
        spec = obj.get("spec")
        if not isinstance(spec, dict):
            return None
        if obj.get("kind") == "Pod":
            return spec
        template = spec.get("template")
        if isinstance(template, dict) and isinstance(template.get("spec"), dict):
            return template["spec"]
        return None

    def _containers(obj: dict) -> list[dict]:
        pod = _pod_spec(obj)
        if pod is None:
            return []
        out: list[dict] = []
        for key in ("initContainers", "containers"):
            for item in pod.get(key) or []:
                if isinstance(item, dict):
                    out.append(item)
        return out

    def manifests_present() -> str | None:
        files = _manifest_files(k8s)
        if not files:
            # The directory exists (the loader checked) but holds no manifests.
            raise CheckFailed(
                f"kubernetes.manifests_dir ({k8s.manifests_dir}) contains no "
                "*.yaml or *.yml files",
                hint="unset kubernetes.manifests_dir to render the manifests "
                "from config.yml instead (the normal mode), or populate the "
                "directory — `deploy.py --target k8s --render-only DIR` writes "
                "a correct starting point (unset manifests_dir first, then set "
                "it back).",
            )
        objects = _objects()
        # One Deployment + one Service OBJECT per configured service — by name,
        # not by file name: the rollout waits on deployment/<slug> and verify
        # port-forwards to svc/<slug>, so those two objects must exist. How they
        # are split across files is the user's business.
        present = {(obj.get("kind"), _meta(obj).get("name")) for _, _, obj in objects}
        missing = [
            f"{kind}/{svc.slug}"
            for svc in k8s.services
            for kind in ("Deployment", "Service")
            if (kind, svc.slug) not in present
        ]
        if missing:
            raise CheckFailed(
                f"no object for {', '.join(missing)} in {k8s.manifests_dir}",
                hint="every service in config.yml's `services:` needs a "
                "Deployment and a Service named after its slug (the rollout "
                "waits on deployment/<slug>, verify port-forwards to "
                "svc/<slug>). Re-render with --render-only, or fix the slugs.",
            )
        # Every object must DECLARE the configured namespace. An object with no
        # namespace: lands in whatever namespace the kubeconfig points at, while
        # rollout status -n <ns> watches somewhere else.
        for path, index, obj in objects:
            declared = _meta(obj).get("namespace")
            kind_name = f"{obj.get('kind')}/{_meta(obj).get('name')}"
            if not declared:
                raise CheckFailed(
                    f"{_where(path, index)}: {kind_name} declares no "
                    "metadata.namespace",
                    hint=f"add 'namespace: {k8s.namespace}' — without it the "
                    "object goes to the kubeconfig's current namespace, which "
                    "is not necessarily kubernetes.namespace",
                )
            if declared != k8s.namespace:
                raise CheckFailed(
                    f"{_where(path, index)}: {kind_name} declares namespace "
                    f"{declared!r} but kubernetes.namespace is "
                    f"{k8s.namespace!r}",
                    hint="fix the manifest, or fix kubernetes.namespace — "
                    "deploying across namespaces would roll out in one place "
                    "and verify another",
                )
        # Every container of our Deployments must name an image. The files are
        # applied verbatim, so the ref they carry is what runs — worth saying
        # out loud when it is not the ref this run resolved.
        pinned: list[str] = []
        slugs = {svc.slug for svc in k8s.services}
        for path, index, obj in objects:
            if obj.get("kind") != "Deployment" or _meta(obj).get("name") not in slugs:
                continue
            containers = _containers(obj)
            refs = [str(c.get("image")) for c in containers if c.get("image")]
            if not refs:
                raise CheckFailed(
                    f"{_where(path, index)}: Deployment/"
                    f"{_meta(obj).get('name')} has no container image",
                    hint="kubernetes.manifests_dir files are applied verbatim, "
                    "so each Deployment must name the image it should run. "
                    "`--render-only DIR` writes a correct starting point.",
                )
            pinned += refs
        drifted = sorted({ref for ref in pinned if ctx.image and ref != ctx.image})
        if drifted:
            warn(
                "kubernetes.manifests_dir is set, so the manifests are applied "
                f"verbatim: they pin {drifted} while this run resolved "
                f"{ctx.image!r}. The pinned refs are what will run — update "
                "them (or unset manifests_dir to render from config.yml) if "
                "that is not what you meant."
            )
        # An HPA owns the replica count. Because every run re-applies the whole
        # directory, a Deployment that also declares spec.replicas resets the
        # count on each deploy and then fights the autoscaler.
        deployments = {
            _meta(obj).get("name"): (path, index, obj)
            for path, index, obj in objects
            if obj.get("kind") == "Deployment"
        }
        hpas = 0
        for path, index, obj in objects:
            if obj.get("kind") != "HorizontalPodAutoscaler":
                continue
            hpas += 1
            spec = obj.get("spec") if isinstance(obj.get("spec"), dict) else {}
            target = spec.get("scaleTargetRef")
            name = target.get("name") if isinstance(target, dict) else None
            owned = deployments.get(name)
            if owned is None:
                warn(
                    f"{_where(path, index)}: HPA targets "
                    f"{name!r}, which is not a Deployment in this directory"
                )
                continue
            dep_spec = owned[2].get("spec")
            if isinstance(dep_spec, dict) and dep_spec.get("replicas") is not None:
                raise CheckFailed(
                    f"{_where(path, index)} scales Deployment/{name}, but "
                    f"{_where(owned[0], owned[1])} still declares "
                    f"replicas: {dep_spec['replicas']}",
                    hint="delete the replicas: line from the Deployment (or "
                    "the HPA). This script re-applies the whole manifests dir "
                    "on every run, so a declared replicas: resets the count "
                    "the HPA just chose and the two fight after every deploy.",
                )
        note = (
            f"{len(files)} hand-owned file(s), {len(objects)} object(s), "
            f"{len(k8s.services)} service(s)"
        )
        if hpas:
            note += f", {hpas} HPA(s) (applied too)"
        return note

    def serve_depends() -> str | None:
        """Prove, statically, that each dependency edge is wired over the
        network in the hand-owned manifests.

        An unmapped dependency is NOT an error at runtime: BentoML silently
        instantiates it IN-PROCESS (no log line), the caller's /readyz skips it
        entirely, and the inference smoke test returns a correct answer from a
        pod that loaded every model. Nothing observable at deploy time
        distinguishes that from a working split — except the manifests.
        """
        objects = _objects()
        pairs: dict[str, str] = {}  # pair -> where it was declared
        for path, index, obj in objects:
            for container in _containers(obj):
                for entry in container.get("env") or []:
                    if not isinstance(entry, dict):
                        continue
                    name = entry.get("name")
                    if name in RUNNER_MAP_ENVS:
                        raise CheckFailed(
                            f"{_where(path, index)} sets {name}",
                            hint="never set a runner map on a pod: the serving "
                            "parent overwrites it, and any dependency missing "
                            "from the effective map is instantiated in-process "
                            "with no log — the pod loads every model and still "
                            f"reports ready. Use {SERVE_DEPENDS_ENV} instead.",
                        )
                    if name != SERVE_DEPENDS_ENV:
                        continue
                    value = entry.get("value")
                    if value is None:
                        raise CheckFailed(
                            f"{_where(path, index)}: {SERVE_DEPENDS_ENV} has no "
                            "literal value",
                            hint="a valueFrom/ConfigMap indirection cannot be "
                            "checked here, and an unwired dependency fails "
                            "silently — set the value inline",
                        )
                    for pair in str(value).split():
                        if "," in pair:
                            raise CheckFailed(
                                f"{_where(path, index)}: {SERVE_DEPENDS_ENV} "
                                f"pair {pair!r} contains a comma",
                                hint="pairs are separated by WHITESPACE, not "
                                "commas — a comma becomes part of the URL and "
                                "the dependency is then silently served "
                                "in-process",
                            )
                        if pair.count("=") != 1:
                            raise CheckFailed(
                                f"{_where(path, index)}: {SERVE_DEPENDS_ENV} "
                                f"pair {pair!r} has {pair.count('=')} '=' "
                                "characters, expected exactly one",
                                hint="each pair is Name=URL and BentoML splits "
                                "on '=', so a URL containing '=' (a query "
                                "string) raises at startup; a pair with none "
                                "is ignored",
                            )
                        pairs.setdefault(pair, _where(path, index))
        # One expected pair per dependency EDGE in config.yml's `services:`.
        expected: dict[str, str] = {}
        for svc in k8s.services:
            for pair in serve_depends_value(k8s, svc).split():
                expected[pair] = svc.name
        for pair, caller in sorted(expected.items()):
            if pair not in pairs:
                raise CheckFailed(
                    f"no Deployment wires {pair!r} (needed by {caller}), found "
                    + (f"{sorted(pairs)}" if pairs else "no pairs at all"),
                    hint="the depending service's Deployment must carry "
                    f"{SERVE_DEPENDS_ENV} with one Name=URL pair per direct "
                    "dependency, keyed on the exact BentoML service name. "
                    "Without it the dependency is instantiated in-process: the "
                    "pod loads every model, /readyz still returns 200 and "
                    "inference still answers correctly. Re-render with "
                    "--render-only and copy the env block.",
                )
        unknown = sorted(
            pair
            for pair in pairs
            if pair.split("=", 1)[0] not in {svc.name for svc in k8s.services}
        )
        if unknown:
            warn(
                f"{SERVE_DEPENDS_ENV} names service(s) that are not in "
                f"config.yml's `services:`: {unknown} — a typo here is "
                "silently served in-process (dependency lookup keys on the "
                "exact BentoML service name)"
            )
        if not expected:
            return "no dependency edges to wire"
        return f"{len(expected)} dependency edge(s) wired over the network"

    def service_exposure() -> str | None:
        """No object in the directory may publish a dependency's port.

        Inter-service payloads are unauthenticated
        application/vnd.bentoml+pickle, so anything that can reach a
        dependency's port can execute code in that pod. Checking only the
        <slug>-service.yaml files would miss exactly the file that does this by
        accident: a second Service (or an Ingress) that selects a dependency's
        pods from some other file, which is applied just the same.
        """
        objects = _objects()
        dependency_targets = {svc.slug for svc in k8s.dependencies} | {
            svc.name for svc in k8s.dependencies
        }
        entry_slug = k8s.entry_service.slug
        checked = 0
        for path, index, obj in objects:
            kind = obj.get("kind")
            spec = obj.get("spec") if isinstance(obj.get("spec"), dict) else {}
            name = _meta(obj).get("name")
            if kind == "Service":
                selector = spec.get("selector")
                selected = (
                    {str(value) for value in selector.values()}
                    if isinstance(selector, dict)
                    else set()
                )
                hits = sorted(selected & dependency_targets)
                if not hits:
                    continue
                checked += 1
                svc_type = spec.get("type", "ClusterIP")
                if svc_type != "ClusterIP":
                    raise CheckFailed(
                        f"{_where(path, index)}: Service/{name} selects "
                        f"dependency pods ({', '.join(hits)}) but is "
                        f"type: {svc_type}",
                        hint="dependency Services must be ClusterIP. "
                        "Inter-service traffic is unauthenticated pickle, so "
                        "anything that can reach the port can execute code in "
                        f"the pod. Only the entry service (svc/{entry_slug}) "
                        "may be exposed.",
                    )
                node_ports = [
                    port.get("nodePort")
                    for port in spec.get("ports") or []
                    if isinstance(port, dict) and port.get("nodePort")
                ]
                if node_ports:
                    raise CheckFailed(
                        f"{_where(path, index)}: Service/{name} selects "
                        f"dependency pods ({', '.join(hits)}) and declares "
                        f"nodePort: {node_ports[0]}",
                        hint="a nodePort publishes the pickle port on every "
                        "cluster node. Remove it — only the entry service may "
                        "be exposed.",
                    )
            elif kind == "Ingress":
                backends: list[str] = []
                default = spec.get("defaultBackend")
                if isinstance(default, dict) and isinstance(
                    default.get("service"), dict
                ):
                    backends.append(str(default["service"].get("name")))
                for rule in spec.get("rules") or []:
                    http = rule.get("http") if isinstance(rule, dict) else None
                    for entry in (http or {}).get("paths") or []:
                        backend = (
                            entry.get("backend") if isinstance(entry, dict) else None
                        )
                        service = (backend or {}).get("service")
                        if isinstance(service, dict):
                            backends.append(str(service.get("name")))
                hits = sorted(set(backends) & dependency_targets)
                if hits:
                    raise CheckFailed(
                        f"{_where(path, index)}: Ingress/{name} routes to "
                        f"dependency service(s) {', '.join(hits)}",
                        hint="an Ingress for a dependency publishes an "
                        "unauthenticated pickle endpoint (remote code "
                        f"execution). Route to the entry service ({entry_slug}) "
                        "only.",
                    )
                checked += 1
        return (
            f"{len(k8s.dependencies)} dependency service(s) unexposed "
            f"({checked} selecting object(s) inspected)"
        )

    checks = [("k8s.kubectl-cli", kubectl_cli), ("k8s.topology", topology_source)]
    if ctx.local_only:
        ctx.summary.skipped += [
            "k8s.context-reachable (--local-only)",
            "k8s.rbac-create-deployment (--local-only)",
            "k8s.namespace (--local-only)",
            "k8s.image-pull-secret (--local-only)",
            "k8s.node-arch (--local-only: needs the cluster's node labels)",
        ]
    else:
        checks += [
            ("k8s.context-reachable", context_reachable),
            ("k8s.rbac-create-deployment", rbac),
            ("k8s.namespace", namespace_exists),
            ("k8s.image-pull-secret", pull_secret),
        ]
        if ctx.skip_build:
            ctx.summary.skipped.append(
                "k8s.node-arch (--skip-build: nothing is built, so no "
                "platform to choose)"
            )
        else:
            checks.append(("k8s.node-arch", node_arch))
    if not k8s.bound:
        # No topology yet (a build-first run with no cache): everything below
        # needs the service list. k8s.topology above already said so.
        ctx.summary.skipped += [
            "k8s.render (topology not yet discovered)",
            "k8s.rollout-plan (topology not yet discovered)",
        ]
        if k8s.manifests_dir is not None:
            ctx.summary.skipped += [
                "k8s.manifests (topology not yet discovered)",
                "k8s.serve-depends (topology not yet discovered)",
                "k8s.service-exposure (topology not yet discovered)",
            ]
        return checks
    # The manifest checks need no cluster: they run under --local-only too.
    if k8s.manifests_dir is None:
        # Rendering path. The checks that used to police hand-written YAML
        # (image sentinel, namespace consistency, serve-depends wiring,
        # non-entry ClusterIP, HPA-vs-replicas) are impossible to fail here:
        # the renderer writes the image ref and the namespace into every
        # object, derives BENTOML_SERVE_DEPENDS from `depends`, forces
        # ClusterIP on non-entry Services, and omits spec.replicas whenever it
        # emits an HPA. What is left to check is that the config renders and
        # that the derived plan is what the user expects.
        checks.append(("k8s.render", render_ok))
        checks.append(("k8s.rollout-plan", rollout_plan))
    else:
        checks.append(("k8s.manifests", manifests_present))
        checks.append(("k8s.serve-depends", serve_depends))
        if len(k8s.services) > 1:
            checks.append(("k8s.service-exposure", service_exposure))
    return checks


