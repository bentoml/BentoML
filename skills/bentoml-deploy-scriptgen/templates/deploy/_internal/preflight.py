def common_checks(cfg: Config, need_git: bool) -> list[Check]:
    def python_version() -> str | None:
        return sys.version.split()[0]

    def git_repo() -> str | None:
        _which("git", "install git, or pass an explicit --version/--image")
        res = run(
            ["git", "-C", str(cfg.project), "rev-parse", "--short", "HEAD"],
            capture=True,
            check=False,
            quiet=True,
        )
        if res.returncode != 0:
            raise CheckFailed(
                f"{cfg.project} is not a git repository (the default image tag is the "
                "short git SHA)",
                hint="run from a git checkout, or pass --version TAG or "
                "--image REF explicitly",
            )
        dirty = run(
            ["git", "-C", str(cfg.project), "status", "--porcelain"],
            capture=True,
            check=False,
            quiet=True,
        )
        if dirty.stdout.strip():
            warn(
                "working tree is dirty — the git-SHA image tag will not "
                "uniquely identify this build"
            )
        return "HEAD=" + res.stdout.strip()

    def pyyaml_present() -> str | None:
        # The bundle's ONE third-party dependency: config.yml is YAML and the
        # standard library has no YAML parser. Reaching this check means the
        # config already loaded, so this normally just records the version —
        # it exists so a bundle that cannot read its own config says why
        # instead of dying in a traceback.
        if yaml is None:
            raise CheckFailed(
                f"PyYAML is not installed, so {CONFIG_FILE_NAME} cannot be read",
                hint="pip install pyyaml — the `bentoml` package already "
                "depends on it, so this only bites a deploy-only environment "
                "(e.g. a CI job that runs --skip-build without installing "
                "bentoml)",
            )
        return "PyYAML " + str(getattr(yaml, "__version__", "unknown"))

    checks: list[Check] = [
        ("common.python-version", python_version),
        ("common.pyyaml", pyyaml_present),
    ]
    if need_git:
        checks.append(("common.git-repo", git_repo))
    return checks


