#!/usr/bin/env python3
"""Production deploy script for a BentoML service.

Generated by the bentoml-deploy-scriptgen skill. Do NOT edit this file (or
anything under _internal/) by hand — every tunable lives in
deploy.config.json; if the config cannot express what you need, regenerate
the bundle with the skill.

Usage:
    python3 deploy/deploy.py --target {k8s,ec2}
                             [--check-only [--local-only]]
                             [--skip-build] [--image REF] [--version TAG]
                             [--no-verify] [--config PATH]
                             [--output-json PATH]

Requirements: Python >= 3.9, standard library only. External tools (bentoml,
docker, kubectl, aws, ssh) are invoked via subprocess and validated by
preflight.

Exit codes: 0 ok, 1 generic, 2 config, 3 preflight, 4 build, 5 push,
6 deploy, 7 verify. The last stdout line is always a JSON summary (except
for argparse-level usage errors, which exit 2 before the summary machinery
starts).
"""

