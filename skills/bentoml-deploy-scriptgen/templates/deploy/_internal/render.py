"""Render the Kubernetes manifests FROM config.yml.

Generated by the bentoml-deploy-scriptgen skill — do not edit by hand; all
tunables live in config.yml.

This is the only place manifests come from: `deploy.py --target k8s` renders
them in memory on every run and pipes the result to `kubectl apply -f -`, and
`--render-only [DIR]` writes the same text to disk for review, diffing, or
GitOps. Nothing is hand-owned, so a whole class of wiring mistakes cannot
happen (see the README's "what preflight no longer has to check").

What is emitted, per BentoML service the bento declares (its service list, its
entry service and its dependency DAG all come from `bento.yaml` — see
topology.py — so no config key can contradict them):

  * one Deployment — `args: ["start-http-server", "--service-name", "<Name>"]`
    (NEVER `command:`, which would skip the image entrypoint's venv
    activation), the run's image ref inline, and BENTOML_SERVE_DEPENDS when the
    service has dependencies;
  * one Service — ClusterIP for every non-entry service, always;
  * one HorizontalPodAutoscaler when `autoscaling.enabled` (and then
    `spec.replicas` is omitted from the Deployment, because a declared replica
    count and an HPA fight each other on every apply);

plus one Ingress for the entry service when `ingress.enabled`.

A Namespace object is deliberately NOT rendered: the namespace must already
exist (preflight checks it), and a bundle that could create namespaces would
also happily create a typo'd one.

BENTOML_RUNNER_MAP / BENTOML_SERVE_RUNNER_MAP are never emitted, by anything,
ever: the serving parent overwrites a runner map, and any dependency missing
from the effective map is then instantiated IN-PROCESS with no log line — the
pod loads every model and still reports healthy. Dependencies are wired with
BENTOML_SERVE_DEPENDS only.

Output is deterministic (stable key order, sorted user-supplied maps) so that
`--render-only` diffs mean something. It is written with careful string
templating rather than a YAML library because the bundle keeps its runtime
dependencies to PyYAML alone; every emitted scalar goes through _scalar(),
which uses JSON quoting (a subset of YAML's double-quoted style), and the test
suite round-trips every rendered document through yaml.safe_load.
"""

# This bundle gets committed into arbitrary user repos; the directive below
# keeps the import layout stable under any repo's ruff/isort configuration.
# isort: skip_file
from __future__ import annotations

import json
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from .config import Config
from .config import K8sConfig
from .config import ServiceSpec

# app.kubernetes.io/managed-by. Deliberately the SAME value the interactive
# bentoml-k8s-deploy skill renders: both skills emit the same manifest shape from
# the same config.yml, so switching between them (or deploying interactively once
# and then from CI forever) must not rewrite a label on every object — and
# `kubectl get all -l app.kubernetes.io/managed-by=bentoml-k8s-deploy` must keep
# finding the whole deployment either way.
MANAGED_BY = "bentoml-k8s-deploy"

# Env var that wires a service to its dependencies: whitespace-separated
# "Name=URL" pairs, keyed on the exact BentoML service name.
SERVE_DEPENDS_ENV = "BENTOML_SERVE_DEPENDS"
CONFIG_OVERRIDES_ENV = "BENTOML_CONFIG_OVERRIDES"

# BentoML's HTTP port inside the container, and the Service port dependency
# URLs use. Changing it would also require setting BENTOML_PORT.
CONTAINER_PORT = 3000

# In-flight requests per pod — the real BentoML concurrency signal. The Gauge
# BentoML exposes on /metrics is CONCURRENCY_GAUGE; the HPA consumes it under
# the Pods-metric name a custom-metrics provider publishes it as, which
# bentoml-k8s-deploy's reference rule calls CONCURRENCY_METRIC_NAME.
CONCURRENCY_GAUGE = "bentoml_service_request_in_progress"
CONCURRENCY_METRIC_NAME = "bentoml_inflight"

# Keys that need no quoting in the emitted YAML.
_PLAIN_KEY_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_./-]*$")

# Values emitted unquoted, for readable diffs. Deliberately narrow: no colons,
# no spaces, must start with a letter — so a quantity ("1", "100m"), an image
# ref (host:tag) or a path (/readyz) always keeps its quotes and can never be
# re-read as a number, a timestamp or a mapping.
_PLAIN_VALUE_RE = re.compile(r"^[A-Za-z][A-Za-z0-9_./-]*$")

# ...and never these, whatever they look like: YAML would read them as bools
# or null.
_YAML_KEYWORDS = frozenset(
    ("y", "n", "yes", "no", "on", "off", "true", "false", "null", "none")
)

_HEADER = (
    "# RENDERED FROM config.yml by deploy/_internal/render.py — DO NOT EDIT.\n"
    "# Every deploy re-renders this from config.yml, so edits here are lost.\n"
    "# Change config.yml instead, then `deploy.py --render-only` to review.\n"
)


@dataclass
class RenderedDoc:
    """One Kubernetes object: its file name (when written to disk) and text."""

    filename: str
    kind: str
    name: str
    text: str


class Flow(list):
    """A list emitted in YAML flow style, e.g. `args: ["a", "b"]`."""


# --------------------------------------------------------------------------
# tiny YAML emitter (plain data only: str / bool / int / float / None / dict /
# list). Strings are emitted with JSON quoting, which is valid YAML.
# --------------------------------------------------------------------------


def _scalar(value: Any, *, quote: bool = False) -> str:
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return json.dumps(value)
    text = str(value)
    if not quote and _PLAIN_VALUE_RE.match(text) and text.lower() not in _YAML_KEYWORDS:
        return text
    # JSON string quoting is a subset of YAML's double-quoted style.
    return json.dumps(text)


def _key(name: Any) -> str:
    text = str(name)
    return text if _PLAIN_KEY_RE.match(text) else json.dumps(text)


def _emit(value: Any, indent: int) -> list[str]:
    """Block-style YAML lines for a nested plain-data value."""
    pad = " " * indent
    lines: list[str] = []
    if isinstance(value, dict):
        for key, item in value.items():
            if isinstance(item, Flow):
                # Flow lists are argv-shaped, so every entry stays quoted:
                # args: ["start-http-server", "--service-name", "Gateway"]
                lines.append(
                    f"{pad}{_key(key)}: ["
                    + ", ".join(_scalar(entry, quote=True) for entry in item)
                    + "]"
                )
            elif isinstance(item, dict) and item:
                lines.append(f"{pad}{_key(key)}:")
                lines += _emit(item, indent + 2)
            elif isinstance(item, list) and item:
                lines.append(f"{pad}{_key(key)}:")
                lines += _emit(item, indent + 2)
            elif isinstance(item, (dict, list)):  # empty container
                lines.append(
                    f"{pad}{_key(key)}: " + ("{}" if isinstance(item, dict) else "[]")
                )
            else:
                lines.append(f"{pad}{_key(key)}: {_scalar(item)}")
        return lines
    if isinstance(value, list):
        for item in value:
            if isinstance(item, dict) and item:
                nested = _emit(item, indent + 2)
                lines.append(f"{pad}- " + nested[0].lstrip())
                lines += nested[1:]
            elif isinstance(item, list) and item:
                nested = _emit(item, indent + 2)
                lines.append(f"{pad}-")
                lines += nested
            else:
                lines.append(f"{pad}- {_scalar(item)}")
        return lines
    return [f"{pad}{_scalar(value)}"]


def _doc(header_comment: str, body: dict[str, Any]) -> str:
    return header_comment + "\n".join(_emit(body, 0)) + "\n"


