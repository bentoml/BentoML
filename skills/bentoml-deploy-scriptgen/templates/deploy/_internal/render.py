def _deployment(
    cfg: Config, k8s: K8sConfig, svc: ServiceSpec, image: str
) -> RenderedDoc:
    labels = labels_for(cfg, svc)
    role = "entry service" if svc.entry else "dependency"
    header = (
        f"# Deployment for the BentoML service {svc.name} ({role})\n"
        f"# bento: {cfg.bento_name}\n" + _HEADER
    )
    container: dict[str, Any] = {
        "name": "bentoml",
        "image": image,
        # Deterministic git-SHA tags: a cached layer is the same image.
        "imagePullPolicy": "IfNotPresent",
        # args ONLY — never command: the image entrypoint activates the venv and
        # rewrites start-http-server into the real module invocation.
        # --service-name makes this pod serve exactly this one BentoML service
        # and spawn no sibling processes.
        "args": Flow(["start-http-server", "--service-name", svc.name]),
        "ports": [{"name": "http", "containerPort": CONTAINER_PORT, "protocol": "TCP"}],
    }
    env = _env_list(cfg, k8s, svc)
    if env:
        container["env"] = env
    if svc.env_from_secrets:
        container["envFrom"] = [
            {"secretRef": {"name": name}} for name in svc.env_from_secrets
        ]
    resources: dict[str, Any] = {}
    if svc.resources.requests:
        resources["requests"] = {
            key: svc.resources.requests[key] for key in sorted(svc.resources.requests)
        }
    if svc.resources.limits:
        resources["limits"] = {
            key: svc.resources.limits[key] for key in sorted(svc.resources.limits)
        }
    if resources:
        container["resources"] = resources
    readiness_timeout = svc.probes.readiness_timeout_seconds
    container["startupProbe"] = {
        "httpGet": {"path": "/readyz", "port": "http"},
        "periodSeconds": 10,
        "failureThreshold": svc.probes.startup_failure_threshold,
        "timeoutSeconds": readiness_timeout,
    }
    container["livenessProbe"] = {
        # /livez is pod-local and never cascades. Liveness must NEVER use
        # /readyz: that turns one sick dependency into a cluster-wide restart
        # loop.
        "httpGet": {"path": "/livez", "port": "http"},
        "periodSeconds": 10,
        "timeoutSeconds": 3,
        "failureThreshold": 3,
    }
    container["readinessProbe"] = {
        "httpGet": {"path": "/readyz", "port": "http"},
        "periodSeconds": 10,
        "timeoutSeconds": readiness_timeout,
        "failureThreshold": 3,
    }
    pod_spec: dict[str, Any] = {"terminationGracePeriodSeconds": 60}
    if k8s.image_pull_secret:
        pod_spec["imagePullSecrets"] = [{"name": k8s.image_pull_secret}]
    if svc.node_selector:
        pod_spec["nodeSelector"] = {
            key: svc.node_selector[key] for key in sorted(svc.node_selector)
        }
    if svc.tolerations:
        pod_spec["tolerations"] = svc.tolerations
    pod_spec["containers"] = [container]
    spec: dict[str, Any] = {}
    if not svc.autoscaling.enabled:
        # Omitted under an HPA: every apply of a Deployment that DECLARES
        # replicas writes that number back, overriding what the autoscaler just
        # chose — and this script re-applies everything on every run.
        spec["replicas"] = svc.replicas
    spec["revisionHistoryLimit"] = 3
    # Immutable after the first apply, and per-service so pods never
    # cross-select between two BentoML services.
    spec["selector"] = {"matchLabels": {"app.kubernetes.io/name": svc.slug}}
    spec["template"] = {"metadata": {"labels": labels}, "spec": pod_spec}
    body = {
        "apiVersion": "apps/v1",
        "kind": "Deployment",
        "metadata": {"name": svc.slug, "namespace": k8s.namespace, "labels": labels},
        "spec": spec,
    }
    return RenderedDoc(
        filename=f"{svc.slug}-deployment.yaml",
        kind="Deployment",
        name=svc.slug,
        text=_doc(header, body),
    )


def _service(cfg: Config, k8s: K8sConfig, svc: ServiceSpec) -> RenderedDoc:
    labels = labels_for(cfg, svc)
    # Non-entry Services are ALWAYS ClusterIP: inter-service payloads are
    # unauthenticated application/vnd.bentoml+pickle, so publishing one hands
    # anyone who can reach the port code execution in that pod. The loader
    # rejects `expose:` on a non-entry service, and this is the second half of
    # that invariant.
    svc_type = svc.expose.type if svc.entry else "ClusterIP"
    node_port = svc.expose.node_port if svc.entry else None
    role = "entry service" if svc.entry else "dependency (ClusterIP, always)"
    header = (
        f"# Service for the BentoML service {svc.name} ({role})\n"
        f"# In-cluster URL: {service_url(k8s, svc)}\n" + _HEADER
    )
    port: dict[str, Any] = {
        "name": "http",
        "port": CONTAINER_PORT,
        "targetPort": "http",
        "protocol": "TCP",
    }
    if node_port is not None and svc_type in ("NodePort", "LoadBalancer"):
        port["nodePort"] = node_port
    metadata: dict[str, Any] = {
        "name": svc.slug,
        "namespace": k8s.namespace,
        "labels": labels,
    }
    if svc.entry and svc.expose.annotations:
        metadata["annotations"] = {
            key: svc.expose.annotations[key] for key in sorted(svc.expose.annotations)
        }
    body = {
        "apiVersion": "v1",
        "kind": "Service",
        "metadata": metadata,
        "spec": {
            "type": svc_type,
            "selector": {"app.kubernetes.io/name": svc.slug},
            "ports": [port],
        },
    }
    return RenderedDoc(
        filename=f"{svc.slug}-service.yaml",
        kind="Service",
        name=svc.slug,
        text=_doc(header, body),
    )


def _hpa(cfg: Config, k8s: K8sConfig, svc: ServiceSpec) -> RenderedDoc:
    labels = labels_for(cfg, svc)
    hpa = svc.autoscaling
    if hpa.metric == "cpu":
        # Usable only because the Deployment always sets resources.requests.cpu:
        # "utilization" means used/requested, so a pod with no CPU request has
        # undefined utilization and the HPA reports <unknown>.
        metrics: list[dict[str, Any]] = [
            {
                "type": "Resource",
                "resource": {
                    "name": "cpu",
                    "target": {
                        "type": "Utilization",
                        "averageUtilization": hpa.target,
                    },
                },
            }
        ]
        note = f"# metric: CPU utilization, target {hpa.target}% of requests.cpu\n"
    else:
        metrics = [
            {
                "type": "Pods",
                "pods": {
                    "metric": {"name": CONCURRENCY_METRIC_NAME},
                    "target": {"type": "AverageValue", "averageValue": str(hpa.target)},
                },
            }
        ]
        note = (
            f"# metric: in-flight requests per pod, target {hpa.target}\n"
            f"# Requires a custom-metrics provider (prometheus-adapter or KEDA)\n"
            f"# exposing the Pods metric {CONCURRENCY_METRIC_NAME!r}, e.g. a\n"
            f"# prometheus-adapter rule over {CONCURRENCY_GAUGE} filtered with\n"
            f'#   runner_name="{svc.name}", endpoint!~"/(livez|readyz|healthz|metrics)"\n'
            "# LABEL TRAP: runner_name is the BentoML SERVICE name, while\n"
            "# service_name is the BENTO name — filtering on the wrong one\n"
            "# matches nothing and the HPA sits at <unknown> forever.\n"
            "# Probe traffic IS counted by the gauge, hence the endpoint filter.\n"
        )
    header = (
        f"# HorizontalPodAutoscaler for the BentoML service {svc.name}\n"
        + note
        + "# The Deployment above omits spec.replicas because this HPA owns it.\n"
        + _HEADER
    )
    body = {
        "apiVersion": "autoscaling/v2",
        "kind": "HorizontalPodAutoscaler",
        "metadata": {"name": svc.slug, "namespace": k8s.namespace, "labels": labels},
        "spec": {
            "scaleTargetRef": {
                "apiVersion": "apps/v1",
                "kind": "Deployment",
                "name": svc.slug,
            },
            # No scale-to-zero here; minReplicas must be >= 1.
            "minReplicas": hpa.min_replicas,
            "maxReplicas": hpa.max_replicas,
            "metrics": metrics,
            # Model-loading pods are expensive to start: scale up briskly,
            # down slowly, or the autoscaler thrashes.
            "behavior": {
                "scaleUp": {"stabilizationWindowSeconds": 30},
                "scaleDown": {"stabilizationWindowSeconds": 300},
            },
        },
    }
    return RenderedDoc(
        filename=f"{svc.slug}-hpa.yaml",
        kind="HorizontalPodAutoscaler",
        name=svc.slug,
        text=_doc(header, body),
    )


def _ingress(cfg: Config, k8s: K8sConfig, svc: ServiceSpec) -> RenderedDoc:
    labels = labels_for(cfg, svc)
    ing = svc.ingress
    header = (
        f"# Ingress for the ENTRY service {svc.name} — host {ing.host}\n"
        "# Never render one for a dependency: they exchange unauthenticated\n"
        "# application/vnd.bentoml+pickle and stay ClusterIP-only.\n" + _HEADER
    )
    metadata: dict[str, Any] = {
        "name": svc.slug,
        "namespace": k8s.namespace,
        "labels": labels,
    }
    if ing.annotations:
        metadata["annotations"] = {
            key: ing.annotations[key] for key in sorted(ing.annotations)
        }
    spec: dict[str, Any] = {"ingressClassName": ing.class_name}
    if ing.tls_secret:
        spec["tls"] = [{"hosts": [ing.host], "secretName": ing.tls_secret}]
    spec["rules"] = [
        {
            "host": ing.host,
            "http": {
                "paths": [
                    {
                        # BentoML serves its API routes at the root.
                        "path": "/",
                        "pathType": "Prefix",
                        "backend": {
                            "service": {"name": svc.slug, "port": {"name": "http"}}
                        },
                    }
                ]
            },
        }
    ]
    body = {
        "apiVersion": "networking.k8s.io/v1",
        "kind": "Ingress",
        "metadata": metadata,
        "spec": spec,
    }
    return RenderedDoc(
        filename="ingress.yaml",
        kind="Ingress",
        name=svc.slug,
        text=_doc(header, body),
    )


