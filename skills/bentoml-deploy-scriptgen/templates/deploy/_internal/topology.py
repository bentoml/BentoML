"""Discover the bento's service topology — the service list, the entry service
and the dependency DAG — from `bento.yaml`, never from config.yml.

Generated by the bentoml-deploy-scriptgen skill — do not edit by hand; all
tunables live in config.yml.

`bentoml build` writes a `bento.yaml` that already carries everything this
bundle needs to shape a deployment:

    name: text-suite            # the bento name -> app.kubernetes.io/part-of
    version: 1a2b3c4            # == the image tag this bundle builds
    entry_service: Gateway      # the only service that may be exposed
    services:
      - name: Gateway
        dependencies: [{service: Enricher}, {service: Sentiment}]
      - name: Enricher
        dependencies: [{service: Tokenizer}]
      ...

So config.yml has no `entry:` and no `depends:` keys: an entire class of config
error (a cycle, an unknown dependency target, two entry services, a middle tier
whose `depends` was forgotten) cannot be written down any more. Everything that
used to be derived from those keys — the rollout order, BENTOML_SERVE_DEPENDS,
the slugs, the labels, ClusterIP-for-non-entry — is derived from this instead.

THREE SOURCES, tried in this order (all three are implemented; when none works
the run fails with a message naming all of them):

1. **the local bento store**, right after the build stage — `bentoml get <tag>
   -o json` (falling back to the store path's own `bento.yaml`). Authoritative
   and needs no docker.
2. **the image**, under `--skip-build` — `docker run --rm --entrypoint cat
   <image> $BENTO_PATH/bento.yaml`, where BENTO_PATH is read out of the image's
   own environment with `docker inspect` (it defaults to /home/bentoml/bento
   but a custom base image may move it).
3. **the topology cache** — `.bento-topology.json` next to config.yml, written
   by every successful discovery from source 1 or 2. This is what makes a
   deploy-only CI job work with neither the bento nor docker: gitignored by
   default, committable on purpose.
"""

# This bundle gets committed into arbitrary user repos; the directive below
# keeps the import layout stable under any repo's ruff/isort configuration.
# isort: skip_file
from __future__ import annotations

import json
import shutil
import time
from dataclasses import dataclass
from dataclasses import field
from pathlib import Path
from typing import Any

from .common import EXIT_CONFIG
from .common import DeployError
from .common import log
from .common import run
from .common import warn

# Written next to config.yml by every fresh discovery.
TOPOLOGY_CACHE_NAME = ".bento-topology.json"
TOPOLOGY_CACHE_SCHEMA = "bentoml-deploy-topology/v1"

# Where the image keeps the bento. Overridden per image by the BENTO_PATH
# environment variable baked into it, which is what docker inspect reads.
DEFAULT_BENTO_PATH = "/home/bentoml/bento"

SOURCE_STORE = "bento-store"
SOURCE_IMAGE = "image"
SOURCE_CACHE = "cache"


@dataclass
class Topology:
    """One bento's shape, as `bento.yaml` describes it."""

    bento_name: str
    bento_version: str
    entry_service: str
    # BentoML service name -> its DIRECT dependencies, in bento.yaml order.
    services: dict[str, list[str]] = field(default_factory=dict)
    # Which of the three sources produced this, and a human-readable detail.
    source: str = SOURCE_CACHE
    detail: str = ""

    @property
    def names(self) -> list[str]:
        return list(self.services)

    @property
    def bento_tag(self) -> str:
        return f"{self.bento_name}:{self.bento_version}"

    def to_cache_dict(self) -> dict[str, Any]:
        return {
            "schema": TOPOLOGY_CACHE_SCHEMA,
            "bento_name": self.bento_name,
            "bento_version": self.bento_version,
            "entry_service": self.entry_service,
            "services": {name: list(deps) for name, deps in self.services.items()},
            "discovered_from": self.source,
            "written_at": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
        }

    def describe(self) -> str:
        tiers = " -> ".join(rollout_order(self))
        return (
            f"bento {self.bento_tag}, entry service {self.entry_service}, "
            f"{len(self.services)} service(s), rollout order {tiers}"
        )


def _malformed(where: str, message: str) -> DeployError:
    return DeployError(
        f"cannot use the service topology from {where}: {message}",
        EXIT_CONFIG,
        hint="this comes from the bento's own bento.yaml, which `bentoml "
        "build` generates — a bento whose service list is unusable is a build "
        "problem, not a config problem. Rebuild the bento (delete the topology "
        f"cache {TOPOLOGY_CACHE_NAME} first if the message names it) and, if it "
        "persists, report it with the bento.yaml that triggered it.",
    )


def parse_topology(doc: Any, where: str, source: str, detail: str = "") -> Topology:
    """Turn a parsed bento.yaml (or `bentoml get -o json`) mapping into a
    Topology, validating everything the renderer will rely on."""
    if not isinstance(doc, dict):
        raise _malformed(where, "it is not a mapping")
    name = doc.get("name")
    version = doc.get("version")
    entry = doc.get("entry_service")
    raw_services = doc.get("services")
    if not isinstance(name, str) or not name.strip():
        raise _malformed(where, "it has no `name`")
    if not isinstance(version, str) or not version.strip():
        # A bento always carries a version; a cache file might not.
        raise _malformed(where, "it has no `version`")
    if not isinstance(raw_services, (list, dict)) or not raw_services:
        raise _malformed(where, "it has no `services` list")
    services: dict[str, list[str]] = {}
    if isinstance(raw_services, dict):
        # The cache's own shape: {"Gateway": ["Enricher"], ...}
        for svc_name, deps in raw_services.items():
            if not isinstance(svc_name, str) or not svc_name.strip():
                raise _malformed(where, f"service name {svc_name!r} is not a string")
            if not isinstance(deps, list) or not all(
                isinstance(dep, str) for dep in deps
            ):
                raise _malformed(
                    where, f"dependencies of {svc_name!r} are not a list of names"
                )
            services[svc_name] = list(deps)
    else:
        for item in raw_services:
            if not isinstance(item, dict):
                raise _malformed(where, "an entry of `services` is not a mapping")
            svc_name = item.get("name")
            if not isinstance(svc_name, str) or not svc_name.strip():
                raise _malformed(where, "a service in `services` has no `name`")
            if any(ch.isspace() for ch in svc_name):
                # The name travels into --service-name and into the
                # whitespace-separated BENTOML_SERVE_DEPENDS value.
                raise _malformed(
                    where, f"service name {svc_name!r} contains whitespace"
                )
            deps: list[str] = []
            for dep in item.get("dependencies") or []:
                target = dep.get("service") if isinstance(dep, dict) else None
                if not isinstance(target, str) or not target.strip():
                    raise _malformed(
                        where,
                        f"a dependency of {svc_name!r} names no `service`",
                    )
                if target not in deps:
                    deps.append(target)
            services[svc_name] = deps
    if not isinstance(entry, str) or entry not in services:
        raise _malformed(
            where,
            f"`entry_service` is {entry!r}, which is not one of {sorted(services)}",
        )
    for svc_name, deps in services.items():
        for dep in deps:
            if dep not in services:
                raise _malformed(
                    where,
                    f"{svc_name!r} depends on {dep!r}, which is not in the "
                    f"service list {sorted(services)}",
                )
            if dep == svc_name:
                raise _malformed(where, f"{svc_name!r} depends on itself")
    topology = Topology(
        bento_name=name.strip(),
        bento_version=version.strip(),
        entry_service=entry,
        services=services,
        source=source,
        detail=detail,
    )
    cycle = _detect_cycle(services)
    if cycle is not None:
        raise _malformed(where, "dependency cycle: " + " -> ".join(cycle))
    return topology


def _detect_cycle(services: dict[str, list[str]]) -> list[str] | None:
    """One dependency cycle as a name chain, or None.

    BentoML cannot express a cyclic bento, so this can only fire on a corrupted
    bento.yaml or a hand-edited cache — but the tier sort below recurses, so the
    guard has to exist before it runs."""
    state: dict[str, int] = {}
    stack: list[str] = []

    def visit(name: str) -> list[str] | None:
        if state.get(name, 0) == 1:
            return stack[stack.index(name) :] + [name]
        if state.get(name, 0) == 2:
            return None
        state[name] = 1
        stack.append(name)
        for dep in sorted(services.get(name, [])):
            found = visit(dep)
            if found is not None:
                return found
        stack.pop()
        state[name] = 2
        return None

    for name in sorted(services):
        cycle = visit(name)
        if cycle is not None:
            return cycle
    return None


def rollout_order(topology: Topology) -> list[str]:
    """Service names in ROLLOUT order: deepest dependencies first, alphabetical
    within a tier.

    A service's tier is 1 + the deepest tier among its dependencies, so every
    service comes after everything it calls — which is the order the rollout
    needs, because a caller's /readyz fans out to its dependencies and 503s
    until they answer. Sorting by (tier, name) keeps it deterministic, so
    `--render-only` diffs stay meaningful."""
    services = topology.services
    depth: dict[str, int] = {}

    def tier(name: str) -> int:
        if name in depth:
            return depth[name]
        deps = services.get(name, [])
        # Cycles are rejected in parse_topology, so this terminates.
        depth[name] = 0 if not deps else 1 + max(tier(dep) for dep in deps)
        return depth[name]

    for name in services:
        tier(name)
    return sorted(services, key=lambda n: (depth[n], n))


# --------------------------------------------------------------------------
# source 1: the local bento store (right after the build stage)
# --------------------------------------------------------------------------


def from_bento_store(bento_tag: str, cwd: str | None = None) -> Topology | None:
    """`bentoml get <tag> -o json`. Authoritative and docker-free: this is the
    bento the run just built. None when the bentoml CLI cannot answer."""
    if not shutil.which("bentoml"):
        return None
    res = run(
        ["bentoml", "get", bento_tag, "-o", "json"],
        capture=True,
        quiet=True,
        check=False,
        cwd=cwd,
        timeout=120,
    )
    if res.returncode == 0 and res.stdout.strip():
        try:
            doc = json.loads(res.stdout)
        except ValueError:
            doc = None
        if isinstance(doc, dict) and doc.get("services"):
            return parse_topology(
                doc,
                f"the local bento store ({bento_tag})",
                SOURCE_STORE,
                detail=f"bentoml get {bento_tag}",
            )
    # Older/newer CLI output shapes: read the store path's bento.yaml instead.
    path_res = run(
        ["bentoml", "get", bento_tag, "-o", "path"],
        capture=True,
        quiet=True,
        check=False,
        cwd=cwd,
        timeout=120,
    )
    if path_res.returncode != 0 or not path_res.stdout.strip():
        return None
    bento_yaml = Path(path_res.stdout.strip().splitlines()[-1].strip()) / "bento.yaml"
    if not bento_yaml.is_file():
        return None
    return _parse_yaml_file(
        bento_yaml,
        f"the local bento store ({bento_tag})",
        SOURCE_STORE,
        detail=str(bento_yaml),
    )


def _parse_yaml_file(path: Path, where: str, source: str, detail: str) -> Topology:
    from .config import yaml  # local import: config imports nothing from here

    if yaml is None:
        raise DeployError(
            f"cannot read {path}: PyYAML is not installed",
            EXIT_CONFIG,
            hint="pip install pyyaml",
        )
    try:
        doc = yaml.safe_load(path.read_text(encoding="utf-8"))
    except (OSError, yaml.YAMLError) as exc:
        raise _malformed(where, f"{path} could not be read ({exc})") from None
    return parse_topology(doc, where, source, detail=detail)


# --------------------------------------------------------------------------
# source 2: the image (--skip-build)
# --------------------------------------------------------------------------


def _image_bento_path(image_ref: str) -> str:
    """BENTO_PATH from the image's own environment. A custom base image may put
    the bento somewhere other than /home/bentoml/bento, and then reading the
    default path would report "no such file" instead of the topology."""
    res = run(
        [
            "docker",
            "inspect",
            "--format",
            "{{range .Config.Env}}{{println .}}{{end}}",
            image_ref,
        ],
        capture=True,
        quiet=True,
        check=False,
        timeout=60,
    )
    if res.returncode != 0:
        return DEFAULT_BENTO_PATH
    for line in res.stdout.splitlines():
        key, _, value = line.partition("=")
        if key.strip() == "BENTO_PATH" and value.strip():
            return value.strip().rstrip("/")
    return DEFAULT_BENTO_PATH


def _image_present_locally(image_ref: str) -> bool:
    res = run(
        ["docker", "image", "inspect", image_ref, "--format", "{{.Id}}"],
        capture=True,
        quiet=True,
        check=False,
        timeout=60,
    )
    return res.returncode == 0


def from_image(image_ref: str, *, allow_pull: bool = True) -> Topology | None:
    """`docker run --rm --entrypoint cat <image> $BENTO_PATH/bento.yaml`.

    Returns None (never raises) when docker is unusable or the image cannot be
    read — the caller then falls back to the cache. allow_pull=False keeps this
    strictly local (used by --check-only --local-only, which must not touch a
    registry): the image is read only if it is already on this machine."""
    if not image_ref or not shutil.which("docker"):
        return None
    if not allow_pull and not _image_present_locally(image_ref):
        log(
            f"topology: {image_ref} is not present locally and pulling is "
            "disabled here — not reading the topology out of the image"
        )
        return None
    bento_path = _image_bento_path(image_ref)
    remote_file = f"{bento_path}/bento.yaml"
    res = run(
        ["docker", "run", "--rm", "--entrypoint", "cat", image_ref, remote_file],
        capture=True,
        quiet=True,
        check=False,
        timeout=600,
    )
    if res.returncode != 0 or not res.stdout.strip():
        detail = (res.stderr.strip() or res.stdout.strip())[:300]
        log(f"topology: could not read {remote_file} from {image_ref} ({detail})")
        return None
    from .config import yaml

    if yaml is None:
        return None
    try:
        doc = yaml.safe_load(res.stdout)
    except yaml.YAMLError as exc:
        raise _malformed(f"the image {image_ref}", f"{remote_file} is not YAML ({exc})")
    return parse_topology(
        doc,
        f"the image {image_ref}",
        SOURCE_IMAGE,
        detail=f"docker run --rm --entrypoint cat {image_ref} {remote_file}",
    )


# --------------------------------------------------------------------------
# source 3: the cache next to config.yml
# --------------------------------------------------------------------------


def cache_path(bundle_dir: Path) -> Path:
    return bundle_dir / TOPOLOGY_CACHE_NAME


def from_cache(bundle_dir: Path) -> Topology | None:
    path = cache_path(bundle_dir)
    if not path.is_file():
        return None
    try:
        doc = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        warn(f"ignoring unreadable topology cache {path}: {exc}")
        return None
    if not isinstance(doc, dict):
        warn(f"ignoring topology cache {path}: not a JSON object")
        return None
    schema = doc.get("schema")
    if schema != TOPOLOGY_CACHE_SCHEMA:
        warn(
            f"ignoring topology cache {path}: schema {schema!r} is not "
            f"{TOPOLOGY_CACHE_SCHEMA} — delete it and re-run a build or a "
            "--skip-build deploy to rewrite it"
        )
        return None
    written = doc.get("written_at") or "unknown time"
    origin = doc.get("discovered_from") or "unknown source"
    # The cache names the bento fields explicitly (bento_name/bento_version) so
    # the file reads on its own; map them onto the bento.yaml shape the parser
    # validates.
    return parse_topology(
        {
            "name": doc.get("bento_name"),
            "version": doc.get("bento_version"),
            "entry_service": doc.get("entry_service"),
            "services": doc.get("services"),
        },
        f"the topology cache {path}",
        SOURCE_CACHE,
        detail=f"{path} (written {written} from the {origin})",
    )


def write_cache(topology: Topology, bundle_dir: Path) -> Path | None:
    """Persist a freshly discovered topology next to config.yml so a later
    deploy-only run (no bento, no docker) can still render. Never fatal: a
    read-only checkout just loses the cache."""
    path = cache_path(bundle_dir)
    payload = json.dumps(topology.to_cache_dict(), indent=2, sort_keys=True) + "\n"
    try:
        existing = path.read_text(encoding="utf-8") if path.is_file() else None
    except OSError:
        existing = None
    if existing is not None and _same_topology(existing, payload):
        return path
    try:
        path.write_text(payload, encoding="utf-8")
    except OSError as exc:
        warn(f"could not write the topology cache {path}: {exc}")
        return None
    log(
        f"topology cache written: {path} (commit it to let a deploy-only run "
        "with no bento and no docker render this bento's manifests)"
    )
    return path


def _same_topology(existing_text: str, new_text: str) -> bool:
    """Compare two cache documents ignoring the timestamp, so an unchanged
    topology does not dirty the working tree on every run."""

    def strip(text: str) -> Any:
        try:
            doc = json.loads(text)
        except ValueError:
            return None
        if isinstance(doc, dict):
            doc.pop("written_at", None)
        return doc

    left, right = strip(existing_text), strip(new_text)
    return left is not None and left == right


# --------------------------------------------------------------------------
# resolution
# --------------------------------------------------------------------------


def resolve(
    bundle_dir: Path,
    *,
    image: str | None = None,
    bento_tag: str | None = None,
    allow_docker: bool = True,
    allow_pull: bool = True,
    cwd: str | None = None,
) -> Topology | None:
    """Try the three sources in order and return the first that answers, or
    None. Fresh discoveries (store, image) refresh the cache."""
    if bento_tag:
        topology = from_bento_store(bento_tag, cwd=cwd)
        if topology is not None:
            log(f"topology from the local bento store: {topology.describe()}")
            write_cache(topology, bundle_dir)
            return topology
    if allow_docker and image:
        topology = from_image(image, allow_pull=allow_pull)
        if topology is not None:
            log(f"topology from the image {image}: {topology.describe()}")
            write_cache(topology, bundle_dir)
            return topology
    topology = from_cache(bundle_dir)
    if topology is not None:
        log(f"topology from {topology.detail}: {topology.describe()}")
        warn(
            "the topology came from the cache, not from this bento — if the "
            "bento gained, lost or renamed a service since it was written, "
            "re-run a build (or a --skip-build deploy, which reads the image) "
            "to refresh it"
        )
        return topology
    return None


def unavailable_error(bundle_dir: Path, image: str | None) -> DeployError:
    """The three-source failure message. Every source is named, with the exact
    reason it could not be used here."""
    ref = image or "<image>"
    return DeployError(
        "could not discover the bento's service topology (the service list, "
        "the entry service and the dependency DAG). config.yml deliberately "
        "does not carry them — they come from the bento's own bento.yaml.",
        EXIT_CONFIG,
        hint=(
            "There are three sources and none of them worked:\n"
            "  1. the local bento store — available right after a build. Run "
            "without --skip-build (needs the `bentoml` CLI), or build once by "
            "hand: bentoml build\n"
            f"  2. the image — `docker run --rm --entrypoint cat {ref} "
            f"{DEFAULT_BENTO_PATH}/bento.yaml`. Needs docker and an image that "
            "can be pulled; check that `image:` in config.yml (or --image REF) "
            "names an image that exists.\n"
            f"  3. the topology cache {cache_path(bundle_dir)} — written by "
            "every successful discovery from 1 or 2, and the way a deploy-only "
            "CI job with neither the bento nor docker still works. It is "
            "missing (or unreadable) here: run a build or a --skip-build "
            "deploy on a machine that has one of the first two, then COMMIT "
            "that file."
        ),
    )
