"""Kubernetes target: apply the manifests in deploy/k8s/ with the image
sentinel rewritten to this run's image ref, wait for the rollout, and verify
/readyz (plus an optional inference smoke test) through a port-forward.

Image mechanism: the generated manifests contain the literal sentinel
``__DEPLOY_IMAGE__`` where the image ref belongs. Each run substitutes the
sentinel in memory and pipes the result to ``kubectl apply -f -`` — the files
on disk are never modified, stay committable, and re-applying the full
manifest set (rather than ``kubectl set image``) also reconciles any drift
and recreates the objects if they were deleted.

Generated by the bentoml-deploy-scriptgen skill — do not edit by hand; all
tunables live in deploy.config.json.
"""

