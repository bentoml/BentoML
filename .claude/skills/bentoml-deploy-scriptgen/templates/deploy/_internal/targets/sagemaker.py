def _failure_guidance(sm: SageMakerConfig, previous_config: str | None) -> str:
    base = (
        "Diagnose:\n"
        f"  aws sagemaker describe-endpoint --endpoint-name {sm.endpoint_name} "
        f"--region {sm.region} "
        "--query '{Status:EndpointStatus,Reason:FailureReason}'\n"
        f'  aws logs tail "/aws/sagemaker/Endpoints/{sm.endpoint_name}" '
        f"--region {sm.region} --since 1h\n"
    )
    if previous_config:
        return base + (
            "Roll back to the previous endpoint-config (recorded before "
            "this update):\n"
            f"  aws sagemaker update-endpoint --endpoint-name {sm.endpoint_name} "
            f"--endpoint-config-name {previous_config} --region {sm.region}\n"
            "(a failed update keeps serving the previous config; the "
            "endpoint must leave Updating before a rollback is accepted)"
        )
    return base + (
        "This was the first deploy of this endpoint, so there is no "
        "previous config to roll back to. A Failed endpoint still exists "
        "and blocks re-creation under the same name — fix the cause, then "
        "delete it before re-running:\n"
        f"  aws sagemaker delete-endpoint --endpoint-name {sm.endpoint_name} "
        f"--region {sm.region}"
    )


def _run_stage(ctx: RunContext, name: str, fn) -> object:
    started = time.monotonic()
    try:
        result = fn()
    except BaseException:
        ctx.summary.record_stage(name, False, time.monotonic() - started)
        raise
    ctx.summary.record_stage(
        name,
        True,
        time.monotonic() - started,
        result if isinstance(result, str) else None,
    )
    return result


def _create_model(sm: SageMakerConfig, name: str, image: str) -> str:
    if _resource_exists(sm, ["describe-model", "--model-name", name], "model"):
        log(f"model {name} already exists (same-tag redeploy) — recreating it")
        run(
            _aws_sm(sm, "delete-model", "--model-name", name),
            capture=True,
            exit_code=EXIT_DEPLOY,
            timeout=60,
        )
    # The container definition goes over as JSON, not shorthand: shorthand
    # Environment parsing breaks on ',' / '=' inside user-provided values.
    container = json.dumps(
        {"Image": image, "Environment": {**sm.environment, "BENTOML_PORT": "8080"}}
    )
    res = run(
        _aws_sm(
            sm,
            "create-model",
            "--model-name",
            name,
            "--primary-container",
            container,
            "--execution-role-arn",
            sm.execution_role_arn,
        ),
        capture=True,
        check=False,
        timeout=60,
    )
    if res.returncode != 0:
        err = res.stderr.strip() or res.stdout.strip()
        hint = None
        if "AccessDenied" in err and "PassRole" in err:
            hint = (
                "the DEPLOYING identity needs iam:PassRole on "
                f"{sm.execution_role_arn} (this is separate from the role's "
                "own permissions) — ask an admin to grant it"
            )
        elif "Cannot assume role" in err or "assume" in err.lower():
            hint = _ROLE_HINT
        raise DeployError(
            f"create-model failed (exit {res.returncode}): {err[-500:]}",
            EXIT_DEPLOY,
            hint=hint,
        )
    return f"model {name}"


def _create_endpoint_config(sm: SageMakerConfig, name: str) -> str:
    if _resource_exists(
        sm,
        ["describe-endpoint-config", "--endpoint-config-name", name],
        "endpoint config",
    ):
        log(
            f"endpoint-config {name} already exists (same-tag redeploy) — recreating it"
        )
        run(
            _aws_sm(sm, "delete-endpoint-config", "--endpoint-config-name", name),
            capture=True,
            exit_code=EXIT_DEPLOY,
            timeout=60,
        )
    variants = json.dumps(
        [
            {
                "VariantName": "AllTraffic",
                "ModelName": name,
                "InitialInstanceCount": sm.instance_count,
                "InstanceType": sm.instance_type,
                "ContainerStartupHealthCheckTimeoutInSeconds": (
                    sm.startup_health_timeout_seconds
                ),
            }
        ]
    )
    run(
        _aws_sm(
            sm,
            "create-endpoint-config",
            "--endpoint-config-name",
            name,
            "--production-variants",
            variants,
        ),
        capture=True,
        exit_code=EXIT_DEPLOY,
        timeout=60,
    )
    return f"endpoint-config {name}"


def _delete_failed_endpoint(sm: SageMakerConfig) -> str:
    run(
        _aws_sm(sm, "delete-endpoint", "--endpoint-name", sm.endpoint_name),
        capture=True,
        exit_code=EXIT_DEPLOY,
        timeout=60,
    )
    run(
        _aws_sm(sm, "wait", "endpoint-deleted", "--endpoint-name", sm.endpoint_name),
        capture=True,
        exit_code=EXIT_DEPLOY,
        timeout=900,
    )
    return "deleted"


def _wait_in_service(sm: SageMakerConfig, previous_config: str | None) -> str:
    budget = sm.startup_health_timeout_seconds + _PROVISION_BUDGET_SECONDS
    log(
        f"waiting for endpoint {sm.endpoint_name} to be InService "
        f"(timeout {budget}s; SageMaker typically needs 5-10 min)..."
    )
    try:
        res = run(
            _aws_sm(
                sm, "wait", "endpoint-in-service", "--endpoint-name", sm.endpoint_name
            ),
            capture=True,
            check=False,
            timeout=budget,
        )
        wait_failed = res.returncode != 0
    except DeployError:  # Python-side overall timeout
        wait_failed = True
    if not wait_failed:
        log("endpoint is InService")
        return "InService"
    ep = _describe_endpoint(sm) or {}
    status = ep.get("EndpointStatus", "unknown")
    reason = ep.get("FailureReason", "") or "(no FailureReason reported)"
    raise DeployError(
        f"endpoint {sm.endpoint_name} did not reach InService within "
        f"{budget}s (status: {status}; FailureReason: {reason})",
        EXIT_DEPLOY,
        hint=_failure_guidance(sm, previous_config),
    )


def deploy(ctx: RunContext) -> None:
    sm = ctx.cfg.require_sagemaker()
    image = ctx.image or ""
    name = _derived_name(sm, ctx.version or "")
    section(
        f"deploy: SageMaker endpoint {sm.endpoint_name} "
        f"(region {sm.region}, image {image})"
    )

    endpoint = _describe_endpoint(sm)
    status = endpoint.get("EndpointStatus") if endpoint else None
    previous_config = endpoint.get("EndpointConfigName") if endpoint else None

    if status in _BUSY_STATUSES:
        raise DeployError(
            f"endpoint {sm.endpoint_name} has an operation in progress "
            f"(status: {status}) — refusing to interfere",
            EXIT_DEPLOY,
            hint="wait for it to settle (aws sagemaker wait "
            f"endpoint-in-service --endpoint-name {sm.endpoint_name} "
            f"--region {sm.region}) and re-run; concurrent deploys of the "
            "same endpoint cannot be serialized by this script",
        )
    if status is not None and status not in ("InService", "Failed"):
        raise DeployError(
            f"endpoint {sm.endpoint_name} is in unexpected status "
            f"{status!r} — refusing to guess",
            EXIT_DEPLOY,
            hint=_failure_guidance(sm, previous_config),
        )

    if status == "InService" and previous_config == name:
        # AWS forbids deleting the in-use config, and UpdateEndpoint
        # requires a config different from the running one.
        warn(
            f"endpoint {sm.endpoint_name} already serves endpoint-config "
            f"{name} (this exact version tag) — nothing to deploy. If the "
            "image was rebuilt under the same tag, deploy it under a new "
            "tag (--version)."
        )
        ctx.summary.record_stage(
            "sagemaker.endpoint", True, 0.0, detail=f"already-live ({name})"
        )
        return

    if status == "Failed":
        reason = (endpoint or {}).get("FailureReason", "") or "(none reported)"
        warn(
            f"endpoint {sm.endpoint_name} is Failed (FailureReason: "
            f"{reason}) — a Failed endpoint cannot be updated, deleting "
            "and recreating it"
        )
        _run_stage(
            ctx, "sagemaker.delete-failed-endpoint", lambda: _delete_failed_endpoint(sm)
        )
        status, previous_config = None, None

    _run_stage(ctx, "sagemaker.model", lambda: _create_model(sm, name, image))
    _run_stage(
        ctx, "sagemaker.endpoint-config", lambda: _create_endpoint_config(sm, name)
    )

    if status is None:

        def _create_endpoint() -> str:
            run(
                _aws_sm(
                    sm,
                    "create-endpoint",
                    "--endpoint-name",
                    sm.endpoint_name,
                    "--endpoint-config-name",
                    name,
                ),
                capture=True,
                exit_code=EXIT_DEPLOY,
                timeout=60,
            )
            return f"created with config {name}"

        _run_stage(ctx, "sagemaker.endpoint", _create_endpoint)
    else:  # InService with a different config

        def _update_endpoint() -> str:
            log(
                f"endpoint exists (InService, config {previous_config}) — "
                f"updating to config {name}"
            )
            res = run(
                _aws_sm(
                    sm,
                    "update-endpoint",
                    "--endpoint-name",
                    sm.endpoint_name,
                    "--endpoint-config-name",
                    name,
                ),
                capture=True,
                check=False,
                timeout=60,
            )
            if res.returncode != 0:
                err = res.stderr.strip() or res.stdout.strip()
                raise DeployError(
                    f"update-endpoint failed (exit {res.returncode}): {err[-500:]}",
                    EXIT_DEPLOY,
                    hint=_failure_guidance(sm, previous_config),
                )
            return f"updated {previous_config} -> {name}"

        _run_stage(ctx, "sagemaker.endpoint", _update_endpoint)

    _run_stage(
        ctx, "sagemaker.wait-in-service", lambda: _wait_in_service(sm, previous_config)
    )
    log(
        "deployed — remember: the endpoint bills per instance-hour until "
        "'aws sagemaker delete-endpoint' (see the README's teardown section)"
    )


