@dataclass
class Config:
    bundle_dir: Path  # directory containing config.yml
    # BentoML project root, absolute — `project:` resolved against bundle_dir.
    project: Path = field(default_factory=lambda: Path("."))
    # Optional `bentoml build` target (module:Class) for projects where plain
    # `bentoml build` cannot work out which service to build.
    build_target: str | None = None
    image: ImageConfig = field(default_factory=ImageConfig)
    verify: VerifyConfig = field(default_factory=VerifyConfig)
    k8s: K8sConfig | None = None
    ec2: Ec2Config | None = None
    # The DISCOVERED topology (topology.py), set by bind_topology().
    topology: Topology | None = None

    @property
    def bento_name(self) -> str:
        """bento.yaml's `name` — the app.kubernetes.io/part-of label value.
        Falls back to the project directory name only when nothing has been
        discovered yet (labels are never rendered in that state)."""
        if self.topology is not None:
            return self.topology.bento_name
        return self.project.name or "bentoml-service"

    def require_k8s(self) -> K8sConfig:
        if self.k8s is None:
            raise _fail(
                "kubernetes",
                "no kubernetes target configured",
                hint="add a `kubernetes:` section with `context:` and "
                "`namespace:` (regenerate the bundle with the "
                "bentoml-deploy-scriptgen skill to get an annotated one)",
            )
        return self.k8s

    def require_ec2(self) -> Ec2Config:
        if self.ec2 is None:
            raise _fail(
                "ec2",
                "no ec2 target configured",
                hint="regenerate the bundle with the bentoml-deploy-scriptgen "
                "skill and include the ec2 target",
            )
        return self.ec2


def _parse_project(data: dict[str, Any], bundle_dir: Path) -> Path:
    """`project:` is a single path, relative to THIS config file's directory."""
    raw = data.get("project")
    if isinstance(raw, dict):
        raise _fail(
            "project",
            "is a mapping, but v4 expects a single path",
            hint="v3's project.dir became `project: <path>` (relative to this "
            "file); project.service became the optional top-level "
            "`build_target: module:Class`; project.name is gone — the bento "
            "name comes from the bento's own bento.yaml.",
        )
    rel = ".." if raw is None else _expect_type(raw, (str,), "project", "a string")
    if not rel.strip():
        raise _fail(
            "project",
            "must not be empty",
            hint='use "." for a config at the project root, ".." for one in deploy/',
        )
    project_dir = (bundle_dir / rel.strip()).resolve()
    if not project_dir.is_dir():
        raise _fail(
            "project",
            f"directory does not exist: {project_dir}",
            hint="`project:` is resolved relative to the directory that holds "
            f"{CONFIG_FILE_NAME} (so `..` for this bundle's deploy/config.yml, "
            "`.` for a config at the project root)",
        )
    return project_dir


_MIGRATION_HINT = (
    "there is no in-place migration; regenerate the bundle with the "
    "bentoml-deploy-scriptgen skill (it carries your settings over). What "
    "moved in v4:\n"
    "  * `project:` is now a single path (v3's project.dir). project.service "
    "became the optional top-level `build_target: module:Class`, and "
    "project.name is gone — the bento name comes from bento.yaml.\n"
    "  * `image:` is now ONE URL with NO tag (v3's image.registry + "
    "image.repository). The tag is always the bento version. "
    "image.registry_type and image.ecr_region are derived from the URL host, "
    "image.platform is auto-detected by comparing the local builder "
    "architecture with the cluster's nodes, and image.estimated_size_gb and "
    "image.local_image_preloaded are gone: an empty `image:` alone means "
    "nothing is pushed and the image name is the bento tag.\n"
    "  * `services:` is now OPTIONAL and holds per-service OVERRIDES only. "
    "`entry:` and `depends:` are DELETED: the service list, the entry service "
    "and the dependency DAG are read from the bento's own bento.yaml at run "
    "time (local bento store after a build, `docker run --entrypoint cat "
    "<image> $BENTO_PATH/bento.yaml` under --skip-build, or the "
    ".bento-topology.json cache next to config.yml).\n"
    "  * `verify.inference` is optional: with no block, verification is "
    "/readyz only.\n"
    "  * v1/v2 additionally lived in deploy.config.json with hand-owned "
    "manifests under deploy/k8s/; those manifests can still be used as-is via "
    "kubernetes.manifests_dir, but rendering is the default and the "
    "recommendation."
)


def _legacy_config_error(path: Path, schema: str | None) -> DeployError:
    found = f"schema {schema!r}" if schema else "no schema key"
    return DeployError(
        f"{path} is a pre-v4 deploy config ({found}) but this bundle requires "
        f"{CONFIG_SCHEMA} in {CONFIG_FILE_NAME}",
        EXIT_CONFIG,
        hint=_MIGRATION_HINT,
    )


def load_config(config_path: Path) -> Config:
    if not config_path.is_file():
        legacy = config_path.parent / LEGACY_CONFIG_FILE_NAME
        if config_path.name == CONFIG_FILE_NAME and legacy.is_file():
            raise _legacy_config_error(legacy, None)
        raise DeployError(
            f"config file not found: {config_path}",
            EXIT_CONFIG,
            hint="pass --config PATH, or run from a project that has a "
            f"generated deploy/{CONFIG_FILE_NAME}",
        )
    text = config_path.read_text(encoding="utf-8")
    if config_path.name == LEGACY_CONFIG_FILE_NAME or text.lstrip().startswith("{"):
        # A JSON document (or the old filename) can only be a v1/v2 config.
        # Read its schema, when it has one, so the message says which.
        try:
            legacy_schema = json.loads(text).get("schema")
        except (ValueError, AttributeError):
            legacy_schema = None
        raise _legacy_config_error(
            config_path, legacy_schema if isinstance(legacy_schema, str) else None
        )
    if yaml is None:
        raise DeployError(
            f"cannot read {config_path}: PyYAML is not installed",
            EXIT_CONFIG,
            hint="pip install pyyaml — the config is YAML and Python's "
            "standard library has no YAML parser. The `bentoml` package "
            "already depends on PyYAML, so this only bites a deploy-only "
            "environment that does not install bentoml (e.g. a CI job that "
            "runs with --skip-build).",
        )
    # Duplicate keys first: they are silent in YAML, and every check below
    # would run against the last-wins survivor.
    _check_duplicate_keys(text, config_path)
    try:
        data = yaml.safe_load(text)
    except RecursionError:
        raise _too_deep(config_path) from None
    except yaml.YAMLError as exc:
        raise DeployError(
            f"config file is not valid YAML ({config_path}): {exc}",
            EXIT_CONFIG,
            hint="common causes: a tab character used for indentation, a "
            "missing space after a ':', or an unquoted value containing ': '",
        ) from None
    if not isinstance(data, dict):
        raise _fail("$", "top level must be a YAML mapping")
    placeholder_at = _scan_placeholders(data, "$")
    if placeholder_at is not None:
        raise _fail(
            placeholder_at,
            "still holds an unreplaced {{PLACEHOLDER}} value",
            hint="the bentoml-deploy-scriptgen skill must substitute every "
            "placeholder when generating the bundle",
        )
    schema = _get_str(data, "schema", "$", default=CONFIG_SCHEMA)
    if schema in LEGACY_SCHEMAS:
        raise _legacy_config_error(config_path, schema)
    if schema != CONFIG_SCHEMA:
        raise _fail("schema", f"expected {CONFIG_SCHEMA!r}, got {schema!r}")
    _warn_unknown_keys(
        data,
        [
            "schema",
            "project",
            "build_target",
            "image",
            "kubernetes",
            "services",
            "verify",
            "ec2",
        ],
        "$",
    )
    bundle_dir = config_path.resolve().parent
    project = _parse_project(data, bundle_dir)
    build_target = _get_str(data, "build_target", "$")
    if build_target is not None and ":" not in build_target:
        raise _fail(
            "build_target",
            f"{build_target!r} is not a module:Class target",
            hint='e.g. "service:Gateway" — exactly what you would pass to '
            "`bentoml build`. Leave it out when plain `bentoml build` resolves "
            "the service on its own.",
        )
    if "kubernetes" not in data and "services" in data:
        warn(
            f"{CONFIG_FILE_NAME}: `services:` is present but there is no "
            "`kubernetes:` section, so --target k8s is not configured and the "
            "per-service overrides are unused"
        )
    return Config(
        bundle_dir=bundle_dir,
        project=project,
        build_target=build_target,
        image=_parse_image(data),
        verify=_parse_verify(data),
        k8s=_parse_k8s(data, bundle_dir),
        ec2=_parse_ec2(data, bundle_dir, project.name),
    )


