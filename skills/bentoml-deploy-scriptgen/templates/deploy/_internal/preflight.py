# A Check pairs a stable id with a callable that returns an optional short
# note on success and raises CheckFailed on failure. Non-fatal findings go
# through warn(). (Alias kept as a string: `str | None` must not be
# evaluated at runtime on Python 3.9.)
Check = "tuple[str, Callable[[], str | None]]"


class CheckFailed(Exception):
    def __init__(self, message: str, hint: str | None = None) -> None:
        super().__init__(message)
        self.hint = hint


def run_checks(checks: list[Check]) -> None:
    """Run every check (never stop at the first failure), then fail with an
    aggregated, actionable report if anything failed."""
    failures: list[str] = []
    for check_id, fn in checks:
        try:
            note = fn()
        except CheckFailed as exc:
            line = f"{check_id}: {exc}"
            if exc.hint:
                line += f"\n      fix: {exc.hint}"
            failures.append(line)
            log(f"  FAIL {check_id}: {exc}")
        except DeployError as exc:
            line = f"{check_id}: {exc}"
            if exc.hint:
                line += f"\n      fix: {exc.hint}"
            failures.append(line)
            log(f"  FAIL {check_id}: {exc}")
        else:
            log("  ok   {}{}".format(check_id, f" ({note})" if note else ""))
    if failures:
        joined = "\n  - ".join(failures)
        raise DeployError(
            f"{len(failures)} preflight check(s) failed:\n  - {joined}",
            EXIT_PREFLIGHT,
        )


def _which(tool: str, hint: str) -> str:
    path = shutil.which(tool)
    if not path:
        raise CheckFailed(f"'{tool}' not found on PATH", hint=hint)
    return path


