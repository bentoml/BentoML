_TAG_RE = re.compile(r"^[A-Za-z0-9_][A-Za-z0-9_.-]{0,127}$")


def parse_args(argv: list | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        prog="deploy.py",
        description="Build, push, deploy, and verify a BentoML service.",
    )
    parser.add_argument(
        "--target", required=True, choices=TARGET_NAMES, help="deploy target"
    )
    parser.add_argument(
        "--check-only",
        action="store_true",
        help="run preflight checks and exit (no changes)",
    )
    parser.add_argument(
        "--local-only",
        action="store_true",
        help="with --check-only: run only checks that need "
        "no cluster or registry connectivity (config, "
        "manifests, tool presence) — for CI PR gates; "
        "skipped checks are listed in the summary",
    )
    parser.add_argument(
        "--skip-build",
        action="store_true",
        help="skip build/containerize/push; deploy an already-pushed image",
    )
    parser.add_argument(
        "--image",
        metavar="REF",
        help="full image reference to deploy (implies the "
        "tag; overrides registry/repository from config)",
    )
    parser.add_argument(
        "--version",
        metavar="TAG",
        help="image tag to build/deploy (default: short git SHA of the project)",
    )
    parser.add_argument(
        "--no-verify", action="store_true", help="skip post-deploy verification"
    )
    parser.add_argument(
        "--config",
        metavar="PATH",
        help="path to deploy.config.json (default: next to this script)",
    )
    parser.add_argument(
        "--output-json", metavar="PATH", help="also write the JSON summary to this file"
    )
    args = parser.parse_args(argv)
    if args.local_only and not args.check_only:
        parser.error("--local-only only makes sense with --check-only")
    return args


def _version_from_ref(image_ref: str) -> str:
    """Best-effort tag extraction from a full image ref, for the summary."""
    tail = image_ref.rsplit("/", 1)[-1]
    if "@" in tail:  # digest ref, e.g. name@sha256:abcd...
        hexpart = tail.split("@", 1)[1].split(":")[-1]
        return "digest-" + hexpart[:12] if hexpart else "digest"
    return tail.rsplit(":", 1)[1] if ":" in tail else "latest"


def resolve_image(
    cfg: Config, args: argparse.Namespace
) -> tuple[str | None, str | None]:
    """Return (image_ref, version_tag). Precedence: CLI > env > config+git.

    Returns (None, None) when the default git-SHA tag cannot be derived —
    the aggregated preflight report then fails on common.git-repo (exit 3)
    instead of aborting here, so all other checks still run and report.
    """
    image_ref = args.image or os.environ.get("BENTOML_DEPLOY_IMAGE")
    if image_ref:
        return image_ref, _version_from_ref(image_ref)
    version = args.version or os.environ.get("BENTOML_DEPLOY_VERSION")
    if not version:
        try:
            res = run(
                ["git", "-C", str(cfg.project.dir), "rev-parse", "--short", "HEAD"],
                capture=True,
                quiet=True,
                check=False,
            )
        except DeployError:  # git binary missing — preflight reports it
            return None, None
        if res.returncode != 0:
            return None, None
        version = res.stdout.strip()
    if not _TAG_RE.match(version):
        raise DeployError(
            f"invalid image tag {version!r}",
            EXIT_CONFIG,
            hint=f"tags must match {_TAG_RE.pattern}",
        )
    if not cfg.image.repository:
        raise DeployError(
            "image.repository is not set in deploy.config.json",
            EXIT_CONFIG,
            hint="set image.registry/image.repository, or pass --image REF",
        )
    return cfg.image.ref(version), version


