def preflight(ctx: RunContext) -> None:
    """Standalone entry point: run this target's checks in one pass."""
    run_checks(preflight_checks(ctx))


def preflight_checks(ctx: RunContext) -> list:
    """Build this target's checks so deploy.py can aggregate them with the
    build-side families into a single report. With ctx.local_only, only
    config-derived checks and CLI presence are returned; the rest are
    recorded in the summary's skipped list."""
    sm = ctx.cfg.require_sagemaker()

    def aws_cli_v2() -> str | None:
        _which("aws", "install the AWS CLI v2")
        res = run(
            ["aws", "--version"], capture=True, quiet=True, check=False, timeout=30
        )
        text = (res.stdout + res.stderr).strip()
        match = _AWS_CLI_VERSION_RE.search(text)
        if res.returncode != 0 or not match:
            raise CheckFailed(
                f"'aws --version' failed or was unparseable: {text[:200]}"
            )
        if int(match.group(1)) < 2:
            raise CheckFailed(
                f"AWS CLI v2 required, found {match.group(0)}",
                hint="v1 lacks --cli-binary-format and the waiters this "
                "target uses — install the v2 bundle from AWS",
            )
        return match.group(0)

    def resource_names() -> str | None:
        if ctx.version is None:
            raise CheckFailed(
                "no version tag resolved, so the model/endpoint-config "
                "names cannot be derived",
                hint="fix the common.git-repo failure, or pass --version/--image",
            )
        return _derived_name(sm, ctx.version)

    def aws_credentials() -> str | None:
        res = run(
            ["aws", "sts", "get-caller-identity", "--output", "json"],
            capture=True,
            quiet=True,
            check=False,
            timeout=60,
        )
        if res.returncode != 0:
            raise CheckFailed(
                "AWS credentials are not usable: "
                f"{(res.stderr.strip() or res.stdout.strip())[:300]}",
                hint="export AWS_ACCESS_KEY_ID/AWS_SECRET_ACCESS_KEY (or "
                "AWS_PROFILE, or run 'aws sso login') for an identity that "
                "may manage SageMaker endpoints",
            )
        try:
            arn = json.loads(res.stdout).get("Arn", "")
        except json.JSONDecodeError:
            arn = ""
        return arn or None

    def image_in_ecr() -> str | None:
        if ctx.image is None:
            raise CheckFailed(
                "no image reference resolved, so the ECR requirement "
                "cannot be validated",
                hint="fix the common.git-repo failure, or pass --image/--version",
            )
        host = ctx.image.split("/", 1)[0]
        if ECR_HOST_RE.match(host) is None:
            raise CheckFailed(
                f"image {ctx.image!r} is not in a private ECR registry — "
                "SageMaker requires the inference image to live in ECR in "
                "the endpoint's region",
                hint="set image.registry to "
                "<account>.dkr.ecr.<region>.amazonaws.com with "
                "image.registry_type 'ecr' (Docker Hub/GHCR images cannot "
                "back a SageMaker endpoint)",
            )
        return host

    def region_match() -> str | None:
        if ctx.image is not None:
            match = ECR_HOST_RE.match(ctx.image.split("/", 1)[0])
            if match and match.group("region") != sm.region:
                raise CheckFailed(
                    f"image is in ECR region {match.group('region')} but "
                    f"targets.sagemaker.region is {sm.region!r} — SageMaker "
                    "requires the image in the same region as the endpoint",
                    hint=f"push to an ECR repository in {sm.region} (fix "
                    "image.registry) or change targets.sagemaker.region",
                )
        if (
            ctx.cfg.image.registry_type == "ecr"
            and ctx.cfg.image.ecr_region
            and ctx.cfg.image.ecr_region != sm.region
        ):
            raise CheckFailed(
                f"image.ecr_region is {ctx.cfg.image.ecr_region!r} but "
                f"targets.sagemaker.region is {sm.region!r} — the push and "
                "the endpoint would land in different regions",
                hint="make both regions equal (SageMaker cannot pull cross-region)",
            )
        return f"region {sm.region}"

    def execution_role() -> str | None:
        role_name = sm.execution_role_arn.rsplit("/", 1)[-1]
        res = run(
            ["aws", "iam", "get-role", "--role-name", role_name, "--output", "json"],
            capture=True,
            quiet=True,
            check=False,
            timeout=60,
        )
        if res.returncode != 0:
            err = res.stderr.strip() or res.stdout.strip()
            if "AccessDenied" in err or "not authorized" in err:
                # Cannot verify != invalid: many deploy identities may
                # PassRole a role they may not GetRole.
                warn(
                    f"cannot verify execution role {role_name!r} — "
                    "iam:GetRole is denied for this identity. Continuing; "
                    "create-model will surface a wrong role or trust policy."
                )
                return "UNVERIFIED (iam:GetRole denied)"
            if "NoSuchEntity" in err:
                raise CheckFailed(
                    f"execution role {sm.execution_role_arn} does not exist",
                    hint=_ROLE_HINT,
                )
            raise CheckFailed(
                f"could not verify execution role {role_name!r}: {err[:300]}"
            )
        doc = json.loads(res.stdout).get("Role", {}).get("AssumeRolePolicyDocument")
        if isinstance(doc, str):
            # The raw IAM API returns the document URL-encoded; the CLI
            # normally decodes it into JSON, but handle both shapes.
            try:
                doc = json.loads(urllib.parse.unquote(doc))
            except (ValueError, TypeError):
                doc = None
        if not isinstance(doc, dict):
            warn(
                f"could not parse the AssumeRolePolicyDocument of "
                f"{role_name!r} — trust policy unverified"
            )
            return "exists (trust policy unverified)"
        if "sagemaker.amazonaws.com" not in json.dumps(doc):
            raise CheckFailed(
                f"role {role_name!r} exists but its trust policy does not "
                "include sagemaker.amazonaws.com — SageMaker cannot assume it",
                hint=_ROLE_HINT,
            )
        return f"{role_name} trusts sagemaker.amazonaws.com"

    checks = [("sagemaker.aws-cli", aws_cli_v2)]
    if ctx.local_only:
        ctx.summary.skipped += [
            "sagemaker.aws-credentials (--local-only)",
            "sagemaker.image-in-ecr (--local-only)",
            "sagemaker.region-match (--local-only)",
            "sagemaker.execution-role (--local-only)",
        ]
    else:
        checks += [
            ("sagemaker.aws-credentials", aws_credentials),
            ("sagemaker.image-in-ecr", image_in_ecr),
            ("sagemaker.region-match", region_match),
            ("sagemaker.execution-role", execution_role),
        ]
    checks.append(("sagemaker.resource-names", resource_names))
    return checks


