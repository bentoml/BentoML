"""EC2 target: deploy the image onto one or more existing EC2 instances over
SSH (docker pull + rm -f + run), require the container to stay Up, and
verify /readyz plus the configured inference request on every host — through
a hardened SSH tunnel by default, or directly when the security group lets
the deploying machine reach the host port.

This script NEVER provisions instances: ec2.hosts must already exist
and accept key-based SSH (provisioning stays in the interactive
bentoml-ec2-deploy skill). All remote docker commands run under ``sudo -n``:
``usermod -aG docker`` does not apply to already-open SSH sessions and races
on fresh instances, while sudo always works — and ``-n`` makes a
password-prompting sudo fail fast instead of hanging a non-interactive run.

Secret transport (ec2.env_names): values are read from THIS
process's environment at deploy time — never from the config, never written
to any file. Each value travels base64-encoded over the SSH channel's stdin
as one ``NAME <base64>`` line; a small remote reader exports the variables
and execs ``sudo -n --preserve-env=<names> docker run ... -e NAME`` using
docker's value-less ``-e NAME`` form, which takes the value from the docker
client's own environment. The values therefore never appear in any argv on
either machine (``ps`` cannot see them locally or remotely) — only in
process environments, which the kernel restricts to the owning user and
root. Variable NAMES are validated against ^[A-Za-z_][A-Za-z0-9_]*$ at
config load, so they are shell-inert; every other user-controlled token
that enters a remote command line goes through shlex.quote().

Generated by the bentoml-deploy-scriptgen skill — do not edit by hand; all
tunables live in config.yml.
"""

