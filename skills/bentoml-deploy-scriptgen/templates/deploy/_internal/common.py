def http_get(url: str, timeout: float) -> tuple[int, str]:
    req = urllib.request.Request(url, method="GET")
    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            return resp.status, resp.read().decode("utf-8", "replace")
    except urllib.error.HTTPError as exc:
        # A non-2xx response is still a response — return it so callers can
        # log the status and retry, instead of treating it as a dead socket.
        return exc.code, exc.read().decode("utf-8", "replace")


def http_post_json(url: str, body: object, timeout: float) -> tuple[int, str]:
    data = json.dumps(body).encode("utf-8")
    req = urllib.request.Request(
        url,
        data=data,
        method="POST",
        headers={"Content-Type": "application/json"},
    )
    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            return resp.status, resp.read().decode("utf-8", "replace")
    except urllib.error.HTTPError as exc:
        return exc.code, exc.read().decode("utf-8", "replace")


@dataclass
class StageRecord:
    name: str
    ok: bool
    seconds: float
    detail: str | None = None


@dataclass
class Summary:
    """Machine-readable run summary, always emitted as the last stdout line."""

    target: str
    action: str  # "deploy" or "check-only"
    image: str | None = None
    version: str | None = None
    ok: bool = False
    exit_code: int = EXIT_GENERIC
    error: dict[str, Any] | None = None
    stages: list[StageRecord] = field(default_factory=list)
    # Check ids (or families) that were deliberately not run this time,
    # e.g. under --skip-build or --check-only --local-only.
    skipped: list[str] = field(default_factory=list)
    started_at: float = field(default_factory=time.time)

    def record_stage(
        self, name: str, ok: bool, seconds: float, detail: str | None = None
    ) -> None:
        self.stages.append(StageRecord(name, ok, round(seconds, 2), detail))

    def to_dict(self) -> dict[str, Any]:
        return {
            "schema": SUMMARY_SCHEMA,
            "ok": self.ok,
            "exit_code": self.exit_code,
            "exit_code_name": EXIT_CODE_NAMES.get(self.exit_code, "unknown"),
            "target": self.target,
            "action": self.action,
            "image": self.image,
            "version": self.version,
            "stages": [
                {
                    "name": s.name,
                    "ok": s.ok,
                    "seconds": s.seconds,
                    **({"detail": s.detail} if s.detail else {}),
                }
                for s in self.stages
            ],
            "skipped_checks": self.skipped,
            "error": self.error,
            "started_at": time.strftime(
                "%Y-%m-%dT%H:%M:%S%z", time.localtime(self.started_at)
            ),
            "duration_seconds": round(time.time() - self.started_at, 2),
        }

    def emit(self, output_json_path: str | None = None) -> None:
        payload = json.dumps(self.to_dict(), separators=(", ", ": "))
        if output_json_path:
            try:
                with open(output_json_path, "w", encoding="utf-8") as fh:
                    fh.write(payload + "\n")
            except OSError as exc:
                warn(f"could not write --output-json file: {exc}")
        # The single stdout line of the whole program:
        print(payload, flush=True)
