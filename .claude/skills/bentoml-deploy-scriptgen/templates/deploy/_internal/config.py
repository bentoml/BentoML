_SERVICES_HINT = (
    "`services:` maps one block per BentoML service, keyed on the service name "
    "EXACTLY as the bento declares it, with exactly one `entry: true`. A "
    "single-service bento has one block. Regenerate the bundle with the "
    "bentoml-deploy-scriptgen skill to get it right."
)

_SERVICE_KEYS = [
    "entry",
    "slug",
    "depends",
    "replicas",
    "resources",
    "env",
    "env_from_secrets",
    "config_overrides",
    "node_selector",
    "tolerations",
    "probes",
    "autoscaling",
    "expose",
    "ingress",
]


def _parse_quantities(block: dict[str, Any], key: str, path: str) -> dict[str, str]:
    raw = _get_dict(block, key, path)
    if raw is None:
        return {}
    out: dict[str, str] = {}
    for name, value in raw.items():
        item_path = f"{path}.{key}.{name}"
        if isinstance(value, bool) or not isinstance(value, str):
            raise _fail(
                item_path,
                f"expected a QUOTED string, got {value!r}",
                hint='quantities must be strings: cpu: "1", not cpu: 1. '
                "Kubernetes stores the quantity as a string, so an unquoted "
                'number makes every `kubectl apply` report "configured" '
                "forever and makes `kubectl diff` / GitOps drift detection lie.",
            )
        if not QUANTITY_RE.match(value.strip()):
            raise _fail(
                item_path,
                f"{value!r} is not a Kubernetes quantity",
                hint='e.g. "100m", "1", "1.5", "512Mi", "2Gi" (no spaces, no '
                '"mb"/"gb")',
            )
        out[name] = value.strip()
    return out


def _parse_resources(block: dict[str, Any], path: str) -> ResourcesConfig:
    section = _get_dict(block, "resources", path)
    if section is None:
        return ResourcesConfig()
    res_path = f"{path}.resources"
    _warn_unknown_keys(section, ["requests", "limits"], res_path)
    return ResourcesConfig(
        requests=_parse_quantities(section, "requests", res_path),
        limits=_parse_quantities(section, "limits", res_path),
    )


def _parse_probes(block: dict[str, Any], path: str) -> ProbesConfig:
    section = _get_dict(block, "probes", path)
    if section is None:
        return ProbesConfig()
    probes_path = f"{path}.probes"
    _warn_unknown_keys(
        section,
        ["startup_failure_threshold", "readiness_timeout_seconds"],
        probes_path,
    )
    readiness = _get_int(
        section, "readiness_timeout_seconds", probes_path, READINESS_TIMEOUT_FLOOR
    )
    if readiness < READINESS_TIMEOUT_FLOOR:
        raise _fail(
            f"{probes_path}.readiness_timeout_seconds",
            f"{readiness} is below the floor of {READINESS_TIMEOUT_FLOOR}",
            hint="when BentoML fans /readyz out to a dependency it gives that "
            "dependency a HARD-CODED 5s budget, so /readyz can legitimately "
            "take just over 5s. A lower kubelet timeout hangs up first and "
            "leaves the pod permanently unready — at startup and forever "
            "after. The 5s is a framework constant, not a tunable "
            "(runner_probe.timeout is inert on BentoML 1.2+). Raise this "
            "value for deep dependency chains; never lower it.",
        )
    return ProbesConfig(
        startup_failure_threshold=_get_int(
            section, "startup_failure_threshold", probes_path, 60
        ),
        readiness_timeout_seconds=readiness,
    )


def _parse_autoscaling(block: dict[str, Any], path: str) -> AutoscalingConfig:
    section = _get_dict(block, "autoscaling", path)
    if section is None:
        return AutoscalingConfig()
    hpa_path = f"{path}.autoscaling"
    _warn_unknown_keys(
        section,
        ["enabled", "min_replicas", "max_replicas", "metric", "target"],
        hpa_path,
    )
    metric = _get_str(section, "metric", hpa_path, default="cpu") or "cpu"
    if metric not in AUTOSCALING_METRICS:
        raise _fail(
            f"{hpa_path}.metric",
            f"{metric!r} is not one of {list(AUTOSCALING_METRICS)}",
            hint="'cpu' uses Resource/cpu averageUtilization (stock "
            "metrics-server); 'concurrency' uses a Pods metric on "
            "bentoml_service_request_in_progress and needs a custom-metrics "
            "adapter that exposes it",
        )
    min_replicas = _get_int(section, "min_replicas", hpa_path, 1)
    max_replicas = _get_int(section, "max_replicas", hpa_path, 5)
    if max_replicas < min_replicas:
        raise _fail(
            f"{hpa_path}.max_replicas",
            f"{max_replicas} is below min_replicas ({min_replicas})",
        )
    return AutoscalingConfig(
        enabled=_get_bool(section, "enabled", hpa_path, False),
        min_replicas=min_replicas,
        max_replicas=max_replicas,
        metric=metric,
        target=_get_int(section, "target", hpa_path, 70),
    )


def _parse_expose(block: dict[str, Any], path: str, entry: bool) -> ExposeConfig:
    section = _get_dict(block, "expose", path)
    if section is None:
        return ExposeConfig()
    if not entry:
        raise _fail(
            f"{path}.expose",
            "only the entry service may be exposed",
            hint="inter-service payloads are unauthenticated "
            "application/vnd.bentoml+pickle, so publishing a dependency's "
            "port hands anyone who can reach it code execution in that pod. "
            "Non-entry Services are always rendered as ClusterIP — delete "
            "this block.",
        )
    expose_path = f"{path}.expose"
    _warn_unknown_keys(section, ["type", "node_port", "annotations"], expose_path)
    svc_type = (
        _get_str(section, "type", expose_path, default="ClusterIP") or "ClusterIP"
    )
    if svc_type not in SERVICE_TYPES:
        raise _fail(
            f"{expose_path}.type",
            f"{svc_type!r} is not one of {list(SERVICE_TYPES)}",
        )
    node_port: int | None = None
    if section.get("node_port") is not None:
        node_port = _get_int(section, "node_port", expose_path, 0)
        if node_port < 30000 or node_port > 32767:
            raise _fail(
                f"{expose_path}.node_port",
                f"{node_port} is outside the Kubernetes NodePort range 30000..32767",
                hint="leave it null to let the cluster allocate one "
                "(kubectl apply preserves an existing allocation)",
            )
        if svc_type != "NodePort":
            raise _fail(
                f"{expose_path}.node_port",
                f"a node port ({node_port}) is only valid with "
                f"expose.type: NodePort (this service is {svc_type})",
                hint='set expose.type to "NodePort", or remove node_port',
            )
    return ExposeConfig(
        type=svc_type,
        node_port=node_port,
        annotations=_get_str_map(section, "annotations", expose_path),
    )


def _parse_ingress(block: dict[str, Any], path: str, entry: bool) -> IngressConfig:
    section = _get_dict(block, "ingress", path)
    if section is None:
        return IngressConfig()
    if not entry:
        raise _fail(
            f"{path}.ingress",
            "only the entry service may be exposed",
            hint="an Ingress for a dependency publishes an unauthenticated "
            "pickle endpoint (remote code execution). Delete this block; only "
            "the entry service speaks ordinary JSON HTTP.",
        )
    ing_path = f"{path}.ingress"
    _warn_unknown_keys(
        section,
        ["enabled", "class_name", "host", "tls_secret", "annotations"],
        ing_path,
    )
    enabled = _get_bool(section, "enabled", ing_path, False)
    host = _get_str(section, "host", ing_path, default="") or ""
    if enabled and not host.strip():
        raise _fail(
            f"{ing_path}.host",
            "required when ingress.enabled is true",
            hint="the DNS name that resolves to the ingress controller's load balancer",
        )
    class_name = _get_str(section, "class_name", ing_path, default="nginx") or "nginx"
    tls_secret = _get_str(section, "tls_secret", ing_path)
    if tls_secret is not None and not DNS1123_RE.match(tls_secret):
        raise _fail(
            f"{ing_path}.tls_secret",
            f"{tls_secret!r} is not a valid Secret name "
            f"(must match {DNS1123_RE.pattern})",
        )
    return IngressConfig(
        enabled=enabled,
        class_name=class_name,
        host=host.strip(),
        tls_secret=tls_secret,
        annotations=_get_str_map(section, "annotations", ing_path),
    )


def _parse_service(name: str, block: dict[str, Any]) -> ServiceSpec:
    path = f"services.{name}"
    _expect_type(block, (dict,), path, "a mapping")
    _warn_unknown_keys(block, _SERVICE_KEYS, path)
    if not SERVICE_NAME_RE.match(name):
        raise _fail(
            path,
            f"{name!r} must be a single whitespace-free BentoML service name "
            "(as the bento declares it)",
            hint="the name is passed to --service-name and used as the "
            "BENTOML_SERVE_DEPENDS lookup key, so whitespace makes the "
            "service unaddressable",
        )
    entry = _get_bool(block, "entry", path, False)
    slug = _get_str(block, "slug", path) or _slugify(name)
    if not DNS1035_RE.match(slug):
        raise _fail(
            f"{path}.slug",
            f"{slug!r} is not a valid DNS-1035 label (must match {DNS1035_RE.pattern})",
            hint="the slug names deployment/<slug>, svc/<slug> and this "
            "service's in-cluster hostname: lowercase the service name, "
            "'_' -> '-'. Set it explicitly when the derived value is invalid "
            "(e.g. a name starting with a digit).",
        )
    depends: list[str] = []
    for i, item in enumerate(_get_list(block, "depends", path)):
        dep = _expect_type(item, (str,), f"{path}.depends[{i}]", "a string")
        if dep == name:
            raise _fail(
                f"{path}.depends[{i}]",
                f"{name!r} cannot depend on itself",
            )
        if dep in depends:
            warn(f"{CONFIG_FILE_NAME}: duplicate dependency {dep!r} in {path}.depends")
        else:
            depends.append(dep)
    secrets: list[str] = []
    for i, item in enumerate(_get_list(block, "env_from_secrets", path)):
        secret = _expect_type(item, (str,), f"{path}.env_from_secrets[{i}]", "a string")
        if not DNS1123_RE.match(secret):
            raise _fail(
                f"{path}.env_from_secrets[{i}]",
                f"{secret!r} is not a valid Secret name "
                f"(must match {DNS1123_RE.pattern})",
            )
        if secret not in secrets:
            secrets.append(secret)
    tolerations: list[dict[str, Any]] = []
    for i, item in enumerate(_get_list(block, "tolerations", path)):
        toleration = _expect_type(
            item, (dict,), f"{path}.tolerations[{i}]", "a mapping"
        )
        # Emitted verbatim into the pod spec, so it must be plain data.
        _require_json_serializable(
            toleration, f"{path}.tolerations[{i}]", "into the rendered pod spec"
        )
        tolerations.append(toleration)
    overrides = _get_dict(block, "config_overrides", path) or {}
    if overrides:
        _require_json_serializable(
            overrides,
            f"{path}.config_overrides",
            "into the pod's BENTOML_CONFIG_OVERRIDES value",
        )
    env = _get_str_map(block, "env", path)
    if "BENTOML_CONFIG_OVERRIDES" in env:
        # The documented escape hatch for the caller-side dependency-timeout
        # trap (a caller's config must name the CALLEE, which a per-service
        # block cannot express). The raw value wins; nothing is derived.
        if overrides:
            warn(
                f"{CONFIG_FILE_NAME}: {path}.env.BENTOML_CONFIG_OVERRIDES is "
                f"set by hand, so {path}.config_overrides is IGNORED (the raw "
                "env value wins) — fold its keys into that JSON, or delete "
                "one of the two"
            )
        else:
            warn(
                f"{CONFIG_FILE_NAME}: {path}.env sets BENTOML_CONFIG_OVERRIDES "
                "by hand — it is passed through verbatim, so nothing is nested "
                f'under {{"services": {{"{name}": ...}}}} for you'
            )
    if "BENTOML_SERVE_DEPENDS" in env:
        # The raw value REPLACES the derived one, so it gets the same scrutiny
        # the hand-owned-manifests branch of preflight applies — an unwired or
        # misspelled dependency is instantiated IN-PROCESS with no log line, and
        # nothing at deploy time can tell that apart from a working split.
        _check_raw_serve_depends(env["BENTOML_SERVE_DEPENDS"], depends, path)
        warn(
            f"{CONFIG_FILE_NAME}: {path}.env sets BENTOML_SERVE_DEPENDS by "
            "hand, so the value derived from `depends` is NOT emitted — the "
            "raw value is what the pod gets (it was syntax-checked, and every "
            "name in `depends` is covered)"
        )
    for forbidden in ("BENTOML_RUNNER_MAP", "BENTOML_SERVE_RUNNER_MAP"):
        if forbidden in env:
            raise _fail(
                f"{path}.env.{forbidden}",
                "a runner map must never be set on a pod",
                hint="the serving parent overwrites it, and any dependency "
                "missing from the effective map is then instantiated "
                "IN-PROCESS with no log line — the pod loads every model and "
                "still reports ready. Use `depends` (which renders "
                "BENTOML_SERVE_DEPENDS) instead.",
            )
    resources = _parse_resources(block, path)
    autoscaling = _parse_autoscaling(block, path)
    if (
        autoscaling.enabled
        and autoscaling.metric == "cpu"
        and not resources.requests.get("cpu")
    ):
        raise _fail(
            f"{path}.resources.requests.cpu",
            "required when autoscaling.metric is 'cpu'",
            hint="a CPU-utilization HPA measures used/requested, so a pod "
            "with no CPU request has undefined utilization and the HPA "
            'reports <unknown> forever. Set e.g. requests: {cpu: "500m"}, or '
            "switch autoscaling.metric to 'concurrency'.",
        )
    if not resources.requests or not resources.limits:
        # @bentoml.service(resources={"cpu"/"memory"}) is INERT in open-source
        # BentoML, so a pod with nothing here is genuinely unconstrained.
        missing = " and ".join(
            part
            for part, present in (
                ("requests", resources.requests),
                ("limits", resources.limits),
            )
            if not present
        )
        warn(
            f"{CONFIG_FILE_NAME}: {path}.resources has no {missing} — nothing "
            "will constrain that pod (the @bentoml.service(resources=...) "
            "decorator is inert in open-source BentoML), and a CPU HPA cannot "
            "compute utilization without requests"
        )
    return ServiceSpec(
        name=name,
        slug=slug,
        entry=entry,
        depends=depends,
        replicas=_get_int(block, "replicas", path, 1),
        resources=resources,
        env=env,
        env_from_secrets=secrets,
        config_overrides=overrides,
        node_selector=_get_str_map(block, "node_selector", path),
        tolerations=tolerations,
        probes=_parse_probes(block, path),
        autoscaling=autoscaling,
        expose=_parse_expose(block, path, entry),
        ingress=_parse_ingress(block, path, entry),
    )


def _check_raw_serve_depends(value: str, depends: list[str], path: str) -> None:
    """Validate a BENTOML_SERVE_DEPENDS the user wrote themselves in `env`.

    Same rules the renderer guarantees and the manifests_dir preflight enforces:
    whitespace-separated `Name=URL` pairs, exactly one '=' per pair (BentoML
    splits on it, so a URL with a query string raises at startup), no commas (a
    comma ends up inside the URL), an http(s) URL, and — the important one —
    every service in `depends` actually covered. A name that is merely
    misspelled is the worst case: BentoML then serves that dependency
    IN-PROCESS, answers correctly and reports ready.
    """
    env_path = f"{path}.env.BENTOML_SERVE_DEPENDS"
    named: list[str] = []
    for pair in value.split():
        if "," in pair:
            raise _fail(
                env_path,
                f"pair {pair!r} contains a comma",
                hint="pairs are separated by WHITESPACE, not commas — a comma "
                "becomes part of the URL and the dependency is then silently "
                "served in-process",
            )
        if pair.count("=") != 1:
            raise _fail(
                env_path,
                f"pair {pair!r} has {pair.count('=')} '=' characters, expected "
                "exactly one",
                hint="each pair is Name=URL and BentoML splits on '=', so a "
                "URL containing '=' (a query string) raises at startup; a pair "
                "with none is ignored entirely",
            )
        name, url = pair.split("=", 1)
        if not name:
            raise _fail(env_path, f"pair {pair!r} has an empty service name")
        if not url.startswith(("http://", "https://")):
            raise _fail(
                env_path,
                f"pair {pair!r} does not point at an http(s) URL",
                hint="e.g. Name=http://<slug>.<namespace>.svc.cluster.local:3000",
            )
        named.append(name)
    missing = [dep for dep in depends if dep not in named]
    if missing:
        raise _fail(
            env_path,
            f"does not wire {missing} — but `depends` lists them",
            hint="a hand-written value REPLACES the derived one, so anything "
            "it omits (or misspells) is not wired at all: BentoML instantiates "
            "that dependency IN-PROCESS with no log line — the pod loads the "
            "model itself, /readyz stays 200 and answers stay correct while "
            "the dependency's pod idles. Add the missing pair(s), or delete "
            "this env var and let `depends` render it.",
        )
    unknown = [name for name in named if name not in depends]
    if unknown:
        warn(
            f"{CONFIG_FILE_NAME}: {env_path} names {unknown}, which is not in "
            f"{path}.depends — fine for a service outside this config, but a "
            "typo here is silently served in-process (lookup keys on the exact "
            "BentoML service name)"
        )


def _detect_cycle(services: dict[str, ServiceSpec]) -> list[str] | None:
    """Return one dependency cycle as a name chain, or None. Deterministic:
    services and their dependencies are both visited in sorted order."""
    state: dict[str, int] = {}  # 0 unvisited, 1 on stack, 2 done
    stack: list[str] = []

    def visit(name: str) -> list[str] | None:
        if state.get(name, 0) == 1:
            return stack[stack.index(name) :] + [name]
        if state.get(name, 0) == 2:
            return None
        state[name] = 1
        stack.append(name)
        for dep in sorted(services[name].depends):
            found = visit(dep)
            if found is not None:
                return found
        stack.pop()
        state[name] = 2
        return None

    for name in sorted(services):
        cycle = visit(name)
        if cycle is not None:
            return cycle
    return None


def _rollout_order(services: dict[str, ServiceSpec]) -> list[ServiceSpec]:
    """Topological order: deepest dependencies first, alphabetical within a
    tier. A service's tier is 1 + the deepest tier among its dependencies, so
    every service comes after everything it calls — which is the order the
    rollout needs (a caller's /readyz fans out to its dependencies and 503s
    until they answer). Sorting by (tier, name) makes the result
    deterministic, so `--render-only` diffs stay meaningful."""
    depth: dict[str, int] = {}

    def tier(name: str) -> int:
        if name in depth:
            return depth[name]
        # Cycles are rejected before this runs, so the recursion terminates.
        depth[name] = (
            0
            if not services[name].depends
            else 1 + max(tier(dep) for dep in services[name].depends)
        )
        return depth[name]

    for name in services:
        tier(name)
    return [services[name] for name in sorted(services, key=lambda n: (depth[n], n))]


def _parse_services(data: dict[str, Any]) -> list[ServiceSpec]:
    raw = data.get("services")
    if raw is None:
        raise _fail("services", "required value is missing", hint=_SERVICES_HINT)
    _expect_type(raw, (dict,), "services", "a mapping")
    if not raw:
        raise _fail("services", "must not be empty", hint=_SERVICES_HINT)
    parsed: dict[str, ServiceSpec] = {}
    for name, block in raw.items():
        if not isinstance(name, str):
            raise _fail("services", f"service key {name!r} must be a string")
        parsed[name] = _parse_service(name, block or {})
    entries = sorted(name for name, svc in parsed.items() if svc.entry)
    if not entries:
        raise _fail(
            "services",
            "no service has entry: true — exactly one must (the bento's "
            "entry_service, the only one exposed outside the cluster and the "
            "only one verification targets)",
            hint=_SERVICES_HINT,
        )
    if len(entries) > 1:
        raise _fail(
            "services",
            f"{len(entries)} services have entry: true ({', '.join(entries)}) "
            "— exactly one must",
            hint=_SERVICES_HINT,
        )
    slugs: dict[str, str] = {}
    for name in sorted(parsed):
        slug = parsed[name].slug
        if slug in slugs:
            raise _fail(
                f"services.{name}.slug",
                f"duplicate slug {slug!r} (already used by "
                f"services.{slugs[slug]}) — the two services would share one "
                "Deployment and Service",
                hint="set an explicit `slug:` on one of them",
            )
        slugs[slug] = name
    for name in sorted(parsed):
        for i, dep in enumerate(parsed[name].depends):
            if dep not in parsed:
                raise _fail(
                    f"services.{name}.depends[{i}]",
                    f"{dep!r} is not a service in this config (known: "
                    f"{sorted(parsed)})",
                    hint="`depends` names BentoML services exactly as the "
                    "bento declares them; a name that is not in `services:` "
                    "gets no Deployment, so nothing would serve it. NOTE: a "
                    "dependency BentoML cannot resolve is instantiated "
                    "IN-PROCESS with no log line — the pod loads that model "
                    "itself, answers correctly and reports ready.",
                )
    cycle = _detect_cycle(parsed)
    if cycle is not None:
        raise _fail(
            f"services.{cycle[0]}.depends",
            "dependency cycle: " + " -> ".join(cycle),
            hint="`depends` must be a DAG: it drives the rollout order, and a "
            "cycle has no order in which every dependency is ready first "
            "(BentoML itself cannot express a cyclic bento either)",
        )
    return _rollout_order(parsed)


def _parse_k8s(data: dict[str, Any], bundle_dir: Path) -> K8sConfig | None:
    section = _get_dict(data, "kubernetes", "$")
    if section is None:
        return None
    _warn_unknown_keys(
        section,
        [
            "context",
            "namespace",
            "image_pull_secret",
            "rollout_timeout_seconds",
            "local_port",
            "extra_labels",
            "manifests_dir",
        ],
        "kubernetes",
    )
    context = os.environ.get("BENTOML_DEPLOY_K8S_CONTEXT") or _get_str(
        section, "context", "kubernetes", required=True
    )
    namespace = os.environ.get("BENTOML_DEPLOY_K8S_NAMESPACE") or _get_str(
        section, "namespace", "kubernetes", required=True
    )
    if not DNS1123_RE.match(str(namespace)):
        raise _fail(
            "kubernetes.namespace",
            f"{namespace!r} is not a valid namespace name "
            f"(must match {DNS1123_RE.pattern})",
            hint="the namespace is embedded in every rendered dependency URL "
            "(http://<slug>.<namespace>.svc.cluster.local:3000)",
        )
    image_pull_secret = _get_str(section, "image_pull_secret", "kubernetes")
    if image_pull_secret is not None and not DNS1123_RE.match(image_pull_secret):
        raise _fail(
            "kubernetes.image_pull_secret",
            f"{image_pull_secret!r} is not a valid Secret name "
            f"(must match {DNS1123_RE.pattern})",
        )
    local_port = _get_int(section, "local_port", "kubernetes", 3130)
    # local_port + 1 carries the dependency /metrics scrapes during verify.
    if local_port < 1024 or local_port > 65534:
        raise _fail(
            "kubernetes.local_port",
            "must be in 1024..65534",
            hint="verify also uses local_port + 1 (to scrape each "
            "dependency's /metrics), so both must be free",
        )
    manifests_rel = _get_str(section, "manifests_dir", "kubernetes")
    manifests_dir: Path | None = None
    if manifests_rel is not None:
        if not manifests_rel.strip():
            raise _fail(
                "kubernetes.manifests_dir",
                "must not be empty",
                hint="leave it null to render the manifests from `services:` "
                "(the normal mode), or name a directory relative to deploy/",
            )
        manifests_dir = (bundle_dir / manifests_rel.strip()).resolve()
        if not manifests_dir.exists():
            raise _fail(
                "kubernetes.manifests_dir",
                f"directory does not exist: {manifests_dir}",
                hint="the path is resolved relative to the directory holding "
                f"{CONFIG_FILE_NAME}. Leave the key null to render the "
                "manifests from `services:` (the normal mode), or create the "
                "directory — `deploy.py --target k8s --render-only DIR` writes "
                "a correct starting point (unset manifests_dir first).",
            )
        if not manifests_dir.is_dir():
            raise _fail(
                "kubernetes.manifests_dir",
                f"is not a directory: {manifests_dir}",
                hint="it must be a directory of *.yaml manifests, not a single file",
            )
    return K8sConfig(
        context=str(context),
        namespace=str(namespace),
        services=_parse_services(data),
        image_pull_secret=image_pull_secret,
        rollout_timeout_seconds=_get_int(
            section, "rollout_timeout_seconds", "kubernetes", 900
        ),
        local_port=local_port,
        extra_labels=_check_extra_labels(
            _get_str_map(section, "extra_labels", "kubernetes")
        ),
        manifests_dir=manifests_dir,
    )


# The four labels the renderer owns: the selector matches on `name`, so a
# user-supplied override would produce a Deployment whose selector and pod
# template disagree (the API server rejects it, and client dry-run does not
# catch it). The renderer therefore always wins — but a silently discarded
# value is exactly the "knob that does nothing" this loader warns about
# everywhere else, so say so.
_OWNED_LABELS = (
    "app.kubernetes.io/name",
    "app.kubernetes.io/component",
    "app.kubernetes.io/part-of",
    "app.kubernetes.io/managed-by",
)


def _check_extra_labels(labels: dict[str, str]) -> dict[str, str]:
    clashes = [key for key in _OWNED_LABELS if key in labels]
    if clashes:
        warn(
            "kubernetes.extra_labels: "
            + ", ".join(clashes)
            + " is set by the renderer and your value is ignored "
            "(the pod selector matches on app.kubernetes.io/name, so an "
            "override would make the Deployment unappliable). Remove it."
        )
    return labels


def _parse_ec2(
    data: dict[str, Any], bundle_dir: Path, default_container_name: str
) -> Ec2Config | None:
    section = _get_dict(data, "ec2", "$")
    if section is None:
        return None
    _warn_unknown_keys(
        section,
        [
            "hosts",
            "ssh_user",
            "ssh_key_path",
            "container_name",
            "host_port",
            "env_names",
            "registry_auth",
            "verify_via",
            "local_tunnel_port",
        ],
        "ec2",
    )
    hosts_env = os.environ.get("BENTOML_DEPLOY_EC2_HOSTS")
    if hosts_env:
        hosts_raw: Any = [h.strip() for h in hosts_env.split(",") if h.strip()]
    else:
        hosts_raw = section.get("hosts")
    if not isinstance(hosts_raw, list) or not hosts_raw:
        raise _fail(
            "ec2.hosts",
            "must be a non-empty list of host addresses",
            hint="existing, SSH-reachable instances only — this script never "
            "provisions EC2 instances (the interactive bentoml-ec2-deploy "
            "skill does)",
        )
    hosts: list[str] = []
    for i, item in enumerate(hosts_raw):
        host = _expect_type(item, (str,), f"ec2.hosts[{i}]", "a string").strip()
        if not host:
            raise _fail(f"ec2.hosts[{i}]", "must not be empty")
        if "@" in host or any(c.isspace() for c in host):
            raise _fail(
                f"ec2.hosts[{i}]",
                f"expected a bare hostname or IP, got {host!r}",
                hint="the SSH user goes in ec2.ssh_user, not in the host",
            )
        if host in hosts:
            warn(
                f"{CONFIG_FILE_NAME}: duplicate host {host!r} in ec2.hosts — "
                "deploying to it once"
            )
        else:
            hosts.append(host)
    ssh_user = _get_str(section, "ssh_user", "ec2", required=True) or ""
    if "@" in ssh_user or any(c.isspace() for c in ssh_user):
        raise _fail("ec2.ssh_user", f"invalid user name {ssh_user!r}")
    key_raw = _get_str(section, "ssh_key_path", "ec2", required=True) or ""
    ssh_key_path = Path(key_raw).expanduser()
    if not ssh_key_path.is_absolute():
        ssh_key_path = bundle_dir / ssh_key_path
    ssh_key_path = ssh_key_path.resolve()
    container_name = (
        _get_str(section, "container_name", "ec2", default=default_container_name)
        or default_container_name
    )
    if not CONTAINER_NAME_RE.match(container_name):
        raise _fail(
            "ec2.container_name",
            f"{container_name!r} is not a valid docker container name "
            f"(must match {CONTAINER_NAME_RE.pattern})",
        )
    host_port = _get_int(section, "host_port", "ec2", 3000)
    if host_port > 65535:
        raise _fail("ec2.host_port", "must be in 1..65535")
    env_names: list[str] = []
    env_names_raw = section.get("env_names")
    if env_names_raw is not None:
        _expect_type(env_names_raw, (list,), "ec2.env_names", "a list")
        for i, item in enumerate(env_names_raw):
            name = _expect_type(item, (str,), f"ec2.env_names[{i}]", "a string")
            if not ENV_NAME_RE.match(name):
                raise _fail(
                    f"ec2.env_names[{i}]",
                    f"{name!r} is not a valid environment variable name "
                    f"(must match {ENV_NAME_RE.pattern})",
                    hint="env_names lists variable NAMES only — the values "
                    "are read from the deploying process's environment at "
                    "deploy time and are never stored",
                )
            if name in env_names:
                warn(f"{CONFIG_FILE_NAME}: duplicate name {name!r} in ec2.env_names")
            else:
                env_names.append(name)
    registry_auth = (
        _get_str(section, "registry_auth", "ec2", default="preauthed") or "preauthed"
    )
    if registry_auth not in EC2_REGISTRY_AUTH_METHODS:
        raise _fail(
            "ec2.registry_auth",
            f"{registry_auth!r} is not one of {list(EC2_REGISTRY_AUTH_METHODS)}",
            hint="'ecr-token-over-ssh' pipes a locally minted ECR token to "
            "each host; 'preauthed' means the instances can already pull "
            "(instance profile, or a docker login you maintain)",
        )
    verify_via = _get_str(section, "verify_via", "ec2", default="tunnel") or "tunnel"
    if verify_via not in EC2_VERIFY_MODES:
        raise _fail(
            "ec2.verify_via",
            f"{verify_via!r} is not one of {list(EC2_VERIFY_MODES)}",
        )
    local_tunnel_port = _get_int(section, "local_tunnel_port", "ec2", 3230)
    if local_tunnel_port < 1024 or local_tunnel_port > 65535:
        raise _fail("ec2.local_tunnel_port", "must be in 1024..65535")
    return Ec2Config(
        hosts=hosts,
        ssh_user=ssh_user,
        ssh_key_path=ssh_key_path,
        container_name=container_name,
        host_port=host_port,
        env_names=env_names,
        registry_auth=registry_auth,
        verify_via=verify_via,
        local_tunnel_port=local_tunnel_port,
    )


_MIGRATION_HINT = (
    "there is no in-place migration: v3 replaced the JSON config AND the "
    "hand-written manifests with a single config.yml from which the manifests "
    "are RENDERED on every run (see --render-only). Regenerate the bundle "
    "with the bentoml-deploy-scriptgen skill — it carries your settings over "
    "— then delete deploy.config.json and the old deploy/k8s/ directory (or "
    "point kubernetes.manifests_dir at it to keep using those files as-is)."
)


def _legacy_config_error(path: Path, schema: str | None) -> DeployError:
    found = f"schema {schema!r}" if schema else "no schema key"
    return DeployError(
        f"{path} is a pre-v3 deploy config ({found}) but this bundle requires "
        f"{CONFIG_SCHEMA} in {CONFIG_FILE_NAME}",
        EXIT_CONFIG,
        hint=_MIGRATION_HINT,
    )


def load_config(config_path: Path) -> Config:
    if not config_path.is_file():
        legacy = config_path.parent / LEGACY_CONFIG_FILE_NAME
        if config_path.name == CONFIG_FILE_NAME and legacy.is_file():
            raise _legacy_config_error(legacy, None)
        raise DeployError(
            f"config file not found: {config_path}",
            EXIT_CONFIG,
            hint="pass --config PATH, or run from a project that has a "
            f"generated deploy/{CONFIG_FILE_NAME}",
        )
    text = config_path.read_text(encoding="utf-8")
    if config_path.name == LEGACY_CONFIG_FILE_NAME or text.lstrip().startswith("{"):
        # A JSON document (or the old filename) can only be a v1/v2 config.
        # Read its schema, when it has one, so the message says which.
        try:
            legacy_schema = json.loads(text).get("schema")
        except (ValueError, AttributeError):
            legacy_schema = None
        raise _legacy_config_error(
            config_path, legacy_schema if isinstance(legacy_schema, str) else None
        )
    if yaml is None:
        raise DeployError(
            f"cannot read {config_path}: PyYAML is not installed",
            EXIT_CONFIG,
            hint="pip install pyyaml — the config is YAML and Python's "
            "standard library has no YAML parser. The `bentoml` package "
            "already depends on PyYAML, so this only bites a deploy-only "
            "environment that does not install bentoml (e.g. a CI job that "
            "runs with --skip-build).",
        )
    # Duplicate keys first: they are silent in YAML, and every check below
    # would run against the last-wins survivor.
    _check_duplicate_keys(text, config_path)
    try:
        data = yaml.safe_load(text)
    except RecursionError:
        raise _too_deep(config_path) from None
    except yaml.YAMLError as exc:
        raise DeployError(
            f"config file is not valid YAML ({config_path}): {exc}",
            EXIT_CONFIG,
            hint="common causes: a tab character used for indentation, a "
            "missing space after a ':', or an unquoted value containing ': '",
        ) from None
    if not isinstance(data, dict):
        raise _fail("$", "top level must be a YAML mapping")
    placeholder_at = _scan_placeholders(data, "$")
    if placeholder_at is not None:
        raise _fail(
            placeholder_at,
            "still holds an unreplaced {{PLACEHOLDER}} value",
            hint="the bentoml-deploy-scriptgen skill must substitute every "
            "placeholder when generating the bundle",
        )
    schema = _get_str(data, "schema", "$", default=CONFIG_SCHEMA)
    if schema in LEGACY_SCHEMAS:
        raise _legacy_config_error(config_path, schema)
    if schema != CONFIG_SCHEMA:
        raise _fail("schema", f"expected {CONFIG_SCHEMA!r}, got {schema!r}")
    _warn_unknown_keys(
        data,
        ["schema", "project", "image", "kubernetes", "services", "verify", "ec2"],
        "$",
    )
    bundle_dir = config_path.resolve().parent
    project = _parse_project(data, bundle_dir)
    if "kubernetes" not in data and "services" in data:
        warn(
            f"{CONFIG_FILE_NAME}: `services:` is present but there is no "
            "`kubernetes:` section, so --target k8s is not configured and the "
            "service blocks are unused"
        )
    return Config(
        bundle_dir=bundle_dir,
        project=project,
        image=_parse_image(data),
        verify=_parse_verify(data),
        k8s=_parse_k8s(data, bundle_dir),
        ec2=_parse_ec2(data, bundle_dir, project.name),
    )
