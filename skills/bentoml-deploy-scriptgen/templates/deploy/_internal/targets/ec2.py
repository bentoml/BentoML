def preflight(ctx: RunContext) -> None:
    """Standalone entry point: run this target's checks in one pass."""
    run_checks(preflight_checks(ctx))


def preflight_checks(ctx: RunContext) -> list:
    """Build this target's checks so deploy.py can aggregate them with the
    build-side families into a single report. With ctx.local_only, only
    checks that need no key, credentials, or host connectivity are returned;
    the rest are recorded in the summary's skipped list."""
    ec2 = ctx.cfg.require_ec2()

    def ssh_cli() -> str | None:
        _which("ssh", "install an OpenSSH client")
        return None

    checks = [("ec2.ssh-cli", ssh_cli)]

    ecr_auth = ec2.registry_auth == "ecr-token-over-ssh"
    if ecr_auth:

        def aws_cli() -> str | None:
            _which(
                "aws",
                "install the AWS CLI v2 — it mints the ECR token that is "
                "piped to the hosts",
            )
            return None

        checks.append(("ec2.aws-cli", aws_cli))
        checks.append(("ec2.ecr-image-ref", _ecr_image_ref_check(ctx)))

    if ctx.local_only:
        ctx.summary.skipped += [
            "ec2.ssh-key (--local-only)",
            "ec2.env-vars (--local-only)",
            "ec2.ssh-reachable/remote-docker/remote-arch/host-port per host (--local-only)",
        ]
        if ecr_auth:
            ctx.summary.skipped.append("ec2.ecr-token (--local-only)")
        return checks

    checks.append(("ec2.ssh-key", lambda: _ssh_key_check(ec2)))
    checks.append(("ec2.env-vars", lambda: _env_vars_check(ec2)))
    if ecr_auth:
        checks.append(("ec2.ecr-token", _ecr_token_check(ctx)))
    probes: dict[str, object] = {}
    # Shared across hosts: one image is built for every host, so two hosts of
    # different architectures cannot both be served (see _host_checks).
    host_arches: dict[str, str] = {}
    for host in ec2.hosts:
        checks += _host_checks(ctx, ec2, host, probes, host_arches)
    return checks


def _ecr_image_ref_check(ctx: RunContext):
    def ecr_image_ref() -> str | None:
        if ctx.image is None:
            raise CheckFailed(
                "no image reference resolved, so the ECR registry host "
                "cannot be validated",
                hint="fix the common.git-repo failure, or pass --image/--version",
            )
        host = ctx.image.split("/", 1)[0]
        match = ECR_HOST_RE.match(host)
        if match is None:
            raise CheckFailed(
                "registry_auth is 'ecr-token-over-ssh' but the image ref "
                f"{ctx.image!r} is not in a private ECR registry",
                hint="use an ECR image ref, or set ec2.registry_auth "
                "to 'preauthed' and handle registry login on the instances "
                "yourself",
            )
        return "{} (region {})".format(host, match.group("region"))

    return ecr_image_ref


def _ecr_token_check(ctx: RunContext):
    def ecr_token() -> str | None:
        # This machine mints the token that deploy pipes to the hosts, so
        # probe the exact call deploy will make (a fresh token per run — it
        # cannot be expired).
        match = ECR_HOST_RE.match(ctx.image.split("/", 1)[0]) if ctx.image else None
        if match is None:
            raise CheckFailed("cannot mint an ECR token (see ec2.ecr-image-ref)")
        region = match.group("region")
        res = run(
            ["aws", "ecr", "get-login-password", "--region", region],
            capture=True,
            quiet=True,
            check=False,
            timeout=60,
            secret_output=True,
        )
        if res.returncode != 0:
            raise CheckFailed(
                f"could not obtain an ECR auth token for region {region}: "
                f"{res.stderr.strip()[:300]}",
                hint="export AWS credentials (AWS_PROFILE / access keys / "
                "SSO) for an identity with ecr:GetAuthorizationToken — the "
                "token is minted locally and piped to the hosts over SSH",
            )
        return f"token ok for {region}"

    return ecr_token


def _ssh_key_check(ec2: Ec2Config) -> str | None:
    key = ec2.ssh_key_path
    if not key.is_file():
        raise CheckFailed(
            f"SSH key file not found: {key}",
            hint="fix ec2.ssh_key_path (~ expands; relative paths "
            "resolve against the deploy/ directory)",
        )
    mode = stat.S_IMODE(key.stat().st_mode)
    if mode & 0o077:
        raise CheckFailed(
            f"SSH key {key} is group/other-accessible (mode {mode:03o}) — "
            "OpenSSH itself refuses such keys",
            hint=f"chmod 600 {key}",
        )
    if not mode & 0o400:
        raise CheckFailed(
            f"SSH key {key} is not readable by its owner (mode {mode:03o})",
            hint=f"chmod 600 {key}",
        )
    return f"mode {mode:03o}"


def _env_vars_check(ec2: Ec2Config) -> str | None:
    if not ec2.env_names:
        return "no env vars configured"
    missing = [name for name in ec2.env_names if not os.environ.get(name)]
    if missing:
        raise CheckFailed(
            "missing (or empty) in this process's environment: " + ", ".join(missing),
            hint="export the value(s) before running — they are read from "
            "the environment at deploy time and are never stored anywhere",
        )
    return f"{len(ec2.env_names)} env var(s) present"


def _probe_host(ec2: Ec2Config, host: str, probes: dict) -> dict:
    """One SSH round trip gathering everything the per-host checks need,
    cached so four checks cost one connection per host."""
    cached = probes.get(host)
    if isinstance(cached, CheckFailed):
        raise CheckFailed(
            f"not probed — SSH to {host} failed (see ec2.ssh-reachable[{host}])"
        )
    if isinstance(cached, dict):
        return cached
    fmt_version = shlex.quote("{{.ServerVersion}}")
    fmt_names = shlex.quote("{{.Names}}")
    publish_filter = shlex.quote(f"publish={ec2.host_port}")
    ss_filter = shlex.quote(f"sport = :{ec2.host_port}")
    remote = (
        'echo "arch=$(uname -m)"; '
        "if ! command -v docker >/dev/null 2>&1; then echo docker=missing; "
        "elif ! sudo -n true 2>/dev/null; then echo docker=no-sudo; "
        f"elif __v=$(sudo -n docker info --format {fmt_version} 2>/dev/null); "
        'then echo "docker=$__v"; '
        f'echo "port_owner=$(sudo -n docker ps --filter {publish_filter} '
        f'--format {fmt_names} | tr "\\n" ,)"; '
        "else echo docker=down; fi; "
        "if command -v ss >/dev/null 2>&1; "
        f'then echo "listeners=$(ss -ltn {ss_filter} | grep -c LISTEN)"; '
        "else echo listeners=unknown; fi"
    )
    res = _ssh_run(ec2, host, remote, capture=True, check=False, quiet=True, timeout=90)
    if res.returncode != 0:
        failure = CheckFailed(
            f"SSH to {ec2.ssh_user}@{host} failed (exit {res.returncode}): "
            f"{(res.stderr.strip() or res.stdout.strip())[:300]}",
            hint="check the host address, that the security group allows "
            "port 22 from this machine, ec2.ssh_user (ec2-user for "
            "Amazon Linux, ubuntu for Ubuntu), and the key — BatchMode is "
            "on, so nothing may prompt",
        )
        probes[host] = failure
        raise failure
    parsed: dict[str, str] = {}
    for line in res.stdout.splitlines():
        if "=" in line:
            key, _, value = line.partition("=")
            parsed[key.strip()] = value.strip()
    probes[host] = parsed
    return parsed


def _host_checks(
    ctx: RunContext,
    ec2: Ec2Config,
    host: str,
    probes: dict,
    host_arches: dict,
) -> list:
    def reachable() -> str | None:
        probe = _probe_host(ec2, host, probes)
        return "connected (arch {})".format(probe.get("arch", "?"))

    def remote_docker() -> str | None:
        state = _probe_host(ec2, host, probes).get("docker", "")
        if state == "missing":
            raise CheckFailed(
                f"docker is not installed on {host}",
                hint="Amazon Linux 2023: sudo dnf install -y docker && sudo "
                "systemctl enable --now docker; Ubuntu: sudo apt-get "
                "install -y docker.io && sudo systemctl enable --now docker",
            )
        if state == "no-sudo":
            raise CheckFailed(
                f"{ec2.ssh_user}@{host} has no passwordless sudo — every "
                "remote docker command runs under 'sudo -n'",
                hint="grant NOPASSWD sudo to the SSH user (stock EC2 cloud "
                "images have it by default)",
            )
        if state == "down":
            raise CheckFailed(
                f"the docker daemon is not running on {host}",
                hint="sudo systemctl enable --now docker — 'enable' matters: "
                "--restart unless-stopped only survives reboots if the "
                "daemon itself comes back",
            )
        if not state:
            raise CheckFailed(f"could not determine the docker state on {host}")
        return f"server {state}"

    def remote_arch() -> str | None:
        """Cross-architecture detection for this host — the replacement for
        v3's `image.platform` knob. The image this run builds must match the
        host's architecture, or the container dies with 'exec format error'
        the moment it starts."""
        remote = normalize_arch(_probe_host(ec2, host, probes).get("arch", ""))
        if remote:
            host_arches[host] = remote
        distinct = sorted(set(host_arches.values()))
        if len(distinct) > 1:
            # One image is built and pushed for every host, so it cannot match
            # two architectures at once.
            raise CheckFailed(
                "ec2.hosts have different architectures "
                + ", ".join(f"{h}={a}" for h, a in sorted(host_arches.items()))
                + " — one image cannot run on all of them",
                hint="deploy each architecture from its own bundle/config "
                "(one ec2.hosts list per architecture), or use hosts of a "
                "single architecture",
            )
        builder = docker_builder_arch() or host_arch()
        decision = decide_platform(builder, [remote], f"host {host}")
        if ctx.skip_build:
            # Nothing is built, so a mismatch cannot be fixed here — but it is
            # worth saying out loud before the container crash-loops.
            if decision.cross:
                warn(
                    f"{host} is {remote} while this machine's builder is "
                    f"{builder}; --skip-build means the existing image is "
                    "deployed as-is, so if it was built for the builder's "
                    "architecture the container will die with 'exec format "
                    "error'"
                )
                return f"UNVERIFIED — host is {remote}, image arch unknown"
            return f"{remote} (image arch unverified under --skip-build)"
        if decision.cross:
            if not buildx_available():
                raise CheckFailed(
                    f"{host} is {remote} but the builder is {builder}, so the "
                    "image must be cross-built — and docker buildx is not "
                    "available",
                    hint="install the docker buildx plugin (ships with Docker "
                    "Desktop; on Debian/Ubuntu: docker-buildx-plugin). "
                    "BuildKit is what honours the platform flag.",
                )
            ctx.build_platform = decision.platform
            log(f"  cross-arch build enabled: --opt platform={decision.platform}")
        return decision.message

    def host_port() -> str | None:
        probe = _probe_host(ec2, host, probes)
        owners = [n for n in probe.get("port_owner", "").split(",") if n]
        if ec2.container_name in owners:
            return (
                f"port {ec2.host_port} is bound by our container (it will be replaced)"
            )
        if owners:
            raise CheckFailed(
                f"host port {ec2.host_port} on {host} is published by other "
                f"container(s): {', '.join(owners)}",
                hint="pick another ec2.host_port, or remove the "
                "container on the host if it is obsolete",
            )
        listeners = probe.get("listeners", "unknown")
        if listeners == "unknown":
            warn(
                f"{host}: 'ss' is unavailable — could not check for "
                f"non-docker listeners on port {ec2.host_port}"
            )
            return (
                f"no container publishes {ec2.host_port} "
                "(non-docker listeners unverified)"
            )
        if listeners not in ("", "0"):
            raise CheckFailed(
                f"a non-docker process is listening on port {ec2.host_port} "
                f"on {host} ({listeners} listener(s) reported by ss)",
                hint="pick another ec2.host_port, or stop that process",
            )
        return f"port {ec2.host_port} free"

    return [
        (f"ec2.ssh-reachable[{host}]", reachable),
        (f"ec2.remote-docker[{host}]", remote_docker),
        (f"ec2.remote-arch[{host}]", remote_arch),
        (f"ec2.host-port[{host}]", host_port),
    ]


