# Keys that existed in v3 and are now DERIVED from bento.yaml. Rejected rather
# than warned about: silently ignoring them would let a user believe they still
# control the topology from here.
_REMOVED_SERVICE_KEYS = {
    "entry": "the entry service is bento.yaml's `entry_service`",
    "depends": "the dependency DAG is bento.yaml's services[].dependencies",
}


def _parse_quantities(block: dict[str, Any], key: str, path: str) -> dict[str, str]:
    raw = _get_dict(block, key, path)
    if raw is None:
        return {}
    out: dict[str, str] = {}
    for name, value in raw.items():
        item_path = f"{path}.{key}.{name}"
        if isinstance(value, bool) or not isinstance(value, str):
            raise _fail(
                item_path,
                f"expected a QUOTED string, got {value!r}",
                hint='quantities must be strings: cpu: "1", not cpu: 1. '
                "Kubernetes stores the quantity as a string, so an unquoted "
                'number makes every `kubectl apply` report "configured" '
                "forever and makes `kubectl diff` / GitOps drift detection lie.",
            )
        if not QUANTITY_RE.match(value.strip()):
            raise _fail(
                item_path,
                f"{value!r} is not a Kubernetes quantity",
                hint='e.g. "100m", "1", "1.5", "512Mi", "2Gi" (no spaces, no '
                '"mb"/"gb")',
            )
        out[name] = value.strip()
    return out


def _parse_resources(block: dict[str, Any], path: str) -> ResourcesConfig:
    """requests/limits default to DEFAULT_REQUESTS/DEFAULT_LIMITS so that a
    service with no block at all is still constrained. A block the user DOES
    write replaces the corresponding default wholesale (so `limits:
    {nvidia.com/gpu: "1"}` means exactly that), and an empty one warns."""
    section = _get_dict(block, "resources", path)
    if section is None:
        return ResourcesConfig()
    res_path = f"{path}.resources"
    _warn_unknown_keys(section, ["requests", "limits"], res_path)
    resources = ResourcesConfig()
    for key in ("requests", "limits"):
        if key not in section:
            continue
        parsed = _parse_quantities(section, key, res_path)
        if not parsed:
            warn(
                f"{CONFIG_FILE_NAME}: {res_path}.{key} is empty, so the "
                f"default {key} are dropped and nothing constrains that pod "
                "(the @bentoml.service(resources=...) decorator is inert in "
                "open-source BentoML). Delete the key to keep the defaults."
            )
        setattr(resources, key, parsed)
    return resources


def _parse_probes(block: dict[str, Any], path: str) -> ProbesConfig:
    section = _get_dict(block, "probes", path)
    if section is None:
        return ProbesConfig()
    probes_path = f"{path}.probes"
    _warn_unknown_keys(
        section,
        ["startup_failure_threshold", "readiness_timeout_seconds"],
        probes_path,
    )
    readiness = _get_int(
        section, "readiness_timeout_seconds", probes_path, READINESS_TIMEOUT_FLOOR
    )
    if readiness < READINESS_TIMEOUT_FLOOR:
        raise _fail(
            f"{probes_path}.readiness_timeout_seconds",
            f"{readiness} is below the floor of {READINESS_TIMEOUT_FLOOR}",
            hint="when BentoML fans /readyz out to a dependency it gives that "
            "dependency a HARD-CODED 5s budget, so /readyz can legitimately "
            "take just over 5s. A lower kubelet timeout hangs up first and "
            "leaves the pod permanently unready — at startup and forever "
            "after. The 5s is a framework constant, not a tunable "
            "(runner_probe.timeout is inert on BentoML 1.2+). Raise this "
            "value for deep dependency chains; never lower it.",
        )
    return ProbesConfig(
        startup_failure_threshold=_get_int(
            section, "startup_failure_threshold", probes_path, 60
        ),
        readiness_timeout_seconds=readiness,
    )


def _parse_autoscaling(block: dict[str, Any], path: str) -> AutoscalingConfig:
    section = _get_dict(block, "autoscaling", path)
    if section is None:
        return AutoscalingConfig()
    hpa_path = f"{path}.autoscaling"
    _warn_unknown_keys(
        section,
        ["enabled", "min_replicas", "max_replicas", "metric", "target"],
        hpa_path,
    )
    metric = _get_str(section, "metric", hpa_path, default="cpu") or "cpu"
    if metric not in AUTOSCALING_METRICS:
        raise _fail(
            f"{hpa_path}.metric",
            f"{metric!r} is not one of {list(AUTOSCALING_METRICS)}",
            hint="'cpu' uses Resource/cpu averageUtilization (stock "
            "metrics-server); 'concurrency' uses a Pods metric on "
            "bentoml_service_request_in_progress and needs a custom-metrics "
            "adapter that exposes it",
        )
    min_replicas = _get_int(section, "min_replicas", hpa_path, 1)
    max_replicas = _get_int(section, "max_replicas", hpa_path, 5)
    if max_replicas < min_replicas:
        raise _fail(
            f"{hpa_path}.max_replicas",
            f"{max_replicas} is below min_replicas ({min_replicas})",
        )
    return AutoscalingConfig(
        enabled=_get_bool(section, "enabled", hpa_path, False),
        min_replicas=min_replicas,
        max_replicas=max_replicas,
        metric=metric,
        target=_get_int(section, "target", hpa_path, 70),
    )


def _parse_expose(
    section: dict[str, Any] | None, path: str, entry: bool
) -> ExposeConfig:
    if section is None:
        return ExposeConfig()
    if not entry:
        raise _fail(
            f"{path}.expose",
            "only the entry service may be exposed",
            hint="inter-service payloads are unauthenticated "
            "application/vnd.bentoml+pickle, so publishing a dependency's "
            "port hands anyone who can reach it code execution in that pod. "
            "Non-entry Services are always rendered as ClusterIP — delete "
            "this block. The entry service is bento.yaml's `entry_service`.",
        )
    expose_path = f"{path}.expose"
    _warn_unknown_keys(section, ["type", "node_port", "annotations"], expose_path)
    svc_type = (
        _get_str(section, "type", expose_path, default="ClusterIP") or "ClusterIP"
    )
    if svc_type not in SERVICE_TYPES:
        raise _fail(
            f"{expose_path}.type",
            f"{svc_type!r} is not one of {list(SERVICE_TYPES)}",
        )
    node_port: int | None = None
    if section.get("node_port") is not None:
        node_port = _get_int(section, "node_port", expose_path, 0)
        if node_port < 30000 or node_port > 32767:
            raise _fail(
                f"{expose_path}.node_port",
                f"{node_port} is outside the Kubernetes NodePort range 30000..32767",
                hint="leave it null to let the cluster allocate one "
                "(kubectl apply preserves an existing allocation)",
            )
        if svc_type != "NodePort":
            raise _fail(
                f"{expose_path}.node_port",
                f"a node port ({node_port}) is only valid with "
                f"expose.type: NodePort (this service is {svc_type})",
                hint='set expose.type to "NodePort", or remove node_port',
            )
    return ExposeConfig(
        type=svc_type,
        node_port=node_port,
        annotations=_get_str_map(section, "annotations", expose_path),
    )


def _parse_ingress(
    section: dict[str, Any] | None, path: str, entry: bool
) -> IngressConfig:
    if section is None:
        return IngressConfig()
    if not entry:
        raise _fail(
            f"{path}.ingress",
            "only the entry service may be exposed",
            hint="an Ingress for a dependency publishes an unauthenticated "
            "pickle endpoint (remote code execution). Delete this block; only "
            "the entry service (bento.yaml's `entry_service`) speaks ordinary "
            "JSON HTTP.",
        )
    ing_path = f"{path}.ingress"
    _warn_unknown_keys(
        section,
        ["enabled", "class_name", "host", "tls_secret", "annotations"],
        ing_path,
    )
    enabled = _get_bool(section, "enabled", ing_path, False)
    host = _get_str(section, "host", ing_path, default="") or ""
    if enabled and not host.strip():
        raise _fail(
            f"{ing_path}.host",
            "required when ingress.enabled is true",
            hint="the DNS name that resolves to the ingress controller's load balancer",
        )
    class_name = _get_str(section, "class_name", ing_path, default="nginx") or "nginx"
    tls_secret = _get_str(section, "tls_secret", ing_path)
    if tls_secret is not None and not DNS1123_RE.match(tls_secret):
        raise _fail(
            f"{ing_path}.tls_secret",
            f"{tls_secret!r} is not a valid Secret name "
            f"(must match {DNS1123_RE.pattern})",
        )
    return IngressConfig(
        enabled=enabled,
        class_name=class_name,
        host=host.strip(),
        tls_secret=tls_secret,
        annotations=_get_str_map(section, "annotations", ing_path),
    )


def _parse_service_override(name: str, block: dict[str, Any]) -> ServiceOverride:
    path = f"services.{name}"
    _expect_type(block, (dict,), path, "a mapping")
    for removed, reason in _REMOVED_SERVICE_KEYS.items():
        if removed in block:
            raise _fail(
                f"{path}.{removed}",
                f"no longer exists: {reason}",
                hint="v4 reads the service list, the entry service and the "
                "dependency DAG out of the bento's own bento.yaml, so they "
                "cannot be wrong here any more. Delete this key; `services:` "
                "now holds per-service OVERRIDES only (resources, replicas, "
                "probes, env, autoscaling, exposure) and is optional.",
            )
    _warn_unknown_keys(block, _SERVICE_KEYS, path)
    secrets: list[str] = []
    for i, item in enumerate(_get_list(block, "env_from_secrets", path)):
        secret = _expect_type(item, (str,), f"{path}.env_from_secrets[{i}]", "a string")
        if not DNS1123_RE.match(secret):
            raise _fail(
                f"{path}.env_from_secrets[{i}]",
                f"{secret!r} is not a valid Secret name "
                f"(must match {DNS1123_RE.pattern})",
            )
        if secret not in secrets:
            secrets.append(secret)
    tolerations: list[dict[str, Any]] = []
    for i, item in enumerate(_get_list(block, "tolerations", path)):
        toleration = _expect_type(
            item, (dict,), f"{path}.tolerations[{i}]", "a mapping"
        )
        # Emitted verbatim into the pod spec, so it must be plain data.
        _require_json_serializable(
            toleration, f"{path}.tolerations[{i}]", "into the rendered pod spec"
        )
        tolerations.append(toleration)
    overrides = _get_dict(block, "config_overrides", path) or {}
    if overrides:
        _require_json_serializable(
            overrides,
            f"{path}.config_overrides",
            "into the pod's BENTOML_CONFIG_OVERRIDES value",
        )
    env = _get_str_map(block, "env", path)
    if "BENTOML_CONFIG_OVERRIDES" in env:
        # The documented escape hatch for the caller-side dependency-timeout
        # trap (a caller's config must name the CALLEE, which a per-service
        # block cannot express). The raw value wins; nothing is derived.
        if overrides:
            warn(
                f"{CONFIG_FILE_NAME}: {path}.env.BENTOML_CONFIG_OVERRIDES is "
                f"set by hand, so {path}.config_overrides is IGNORED (the raw "
                "env value wins) — fold its keys into that JSON, or delete "
                "one of the two"
            )
        else:
            warn(
                f"{CONFIG_FILE_NAME}: {path}.env sets BENTOML_CONFIG_OVERRIDES "
                "by hand — it is passed through verbatim, so nothing is nested "
                f'under {{"services": {{"{name}": ...}}}} for you'
            )
    for forbidden in ("BENTOML_RUNNER_MAP", "BENTOML_SERVE_RUNNER_MAP"):
        if forbidden in env:
            raise _fail(
                f"{path}.env.{forbidden}",
                "a runner map must never be set on a pod",
                hint="the serving parent overwrites it, and any dependency "
                "missing from the effective map is then instantiated "
                "IN-PROCESS with no log line — the pod loads every model and "
                "still reports ready. The dependency wiring "
                "(BENTOML_SERVE_DEPENDS) is derived from the bento's own "
                "dependency graph; there is nothing to fix up by hand.",
            )
    resources = _parse_resources(block, path)
    autoscaling = _parse_autoscaling(block, path)
    if (
        autoscaling.enabled
        and autoscaling.metric == "cpu"
        and not resources.requests.get("cpu")
    ):
        raise _fail(
            f"{path}.resources.requests.cpu",
            "required when autoscaling.metric is 'cpu'",
            hint="a CPU-utilization HPA measures used/requested, so a pod "
            "with no CPU request has undefined utilization and the HPA "
            'reports <unknown> forever. Set e.g. requests: {cpu: "500m"}, or '
            "switch autoscaling.metric to 'concurrency'.",
        )
    slug = _get_str(block, "slug", path)
    return ServiceOverride(
        name=name,
        slug=slug,
        replicas=_get_int(block, "replicas", path, 1),
        resources=resources,
        env=env,
        env_from_secrets=secrets,
        config_overrides=overrides,
        node_selector=_get_str_map(block, "node_selector", path),
        tolerations=tolerations,
        probes=_parse_probes(block, path),
        autoscaling=autoscaling,
        expose_raw=_get_dict(block, "expose", path),
        ingress_raw=_get_dict(block, "ingress", path),
    )


def _parse_service_overrides(data: dict[str, Any]) -> dict[str, ServiceOverride]:
    raw = data.get("services")
    if raw is None:
        return {}
    _expect_type(raw, (dict,), "services", "a mapping")
    parsed: dict[str, ServiceOverride] = {}
    for name, block in raw.items():
        if not isinstance(name, str):
            raise _fail("services", f"service key {name!r} must be a string")
        parsed[name] = _parse_service_override(name, block or {})
    return parsed


def _check_raw_serve_depends(value: str, depends: list[str], path: str) -> None:
    """Validate a BENTOML_SERVE_DEPENDS the user wrote themselves in `env`.

    Same rules the renderer guarantees and the manifests_dir preflight enforces:
    whitespace-separated `Name=URL` pairs, exactly one '=' per pair (BentoML
    splits on it, so a URL with a query string raises at startup), no commas (a
    comma ends up inside the URL), an http(s) URL, and — the important one —
    every dependency the bento declares actually covered. A name that is merely
    misspelled is the worst case: BentoML then serves that dependency
    IN-PROCESS, answers correctly and reports ready.
    """
    env_path = f"{path}.env.BENTOML_SERVE_DEPENDS"
    named: list[str] = []
    for pair in value.split():
        if "," in pair:
            raise _fail(
                env_path,
                f"pair {pair!r} contains a comma",
                hint="pairs are separated by WHITESPACE, not commas — a comma "
                "becomes part of the URL and the dependency is then silently "
                "served in-process",
            )
        if pair.count("=") != 1:
            raise _fail(
                env_path,
                f"pair {pair!r} has {pair.count('=')} '=' characters, expected "
                "exactly one",
                hint="each pair is Name=URL and BentoML splits on '=', so a "
                "URL containing '=' (a query string) raises at startup; a pair "
                "with none is ignored entirely",
            )
        name, url = pair.split("=", 1)
        if not name:
            raise _fail(env_path, f"pair {pair!r} has an empty service name")
        if not url.startswith(("http://", "https://")):
            raise _fail(
                env_path,
                f"pair {pair!r} does not point at an http(s) URL",
                hint="e.g. Name=http://<slug>.<namespace>.svc.cluster.local:3000",
            )
        named.append(name)
    missing = [dep for dep in depends if dep not in named]
    if missing:
        raise _fail(
            env_path,
            f"does not wire {missing} — but the bento declares them as "
            "dependencies of this service",
            hint="a hand-written value REPLACES the derived one, so anything "
            "it omits (or misspells) is not wired at all: BentoML instantiates "
            "that dependency IN-PROCESS with no log line — the pod loads the "
            "model itself, /readyz stays 200 and answers stay correct while "
            "the dependency's pod idles. Add the missing pair(s), or delete "
            "this env var and let the bento's own dependency graph render it.",
        )
    unknown = [name for name in named if name not in depends]
    if unknown:
        warn(
            f"{CONFIG_FILE_NAME}: {env_path} names {unknown}, which the bento "
            f"does not declare as a dependency of this service — fine for a "
            "service outside this bento, but a typo here is silently served "
            "in-process (lookup keys on the exact BentoML service name)"
        )


