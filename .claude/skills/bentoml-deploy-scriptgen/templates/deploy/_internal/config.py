"""Load and validate config.yml (schema bentoml-deploy-config/v3).

Generated by the bentoml-deploy-scriptgen skill — do not edit by hand; all
tunables live in config.yml, and the Kubernetes manifests are rendered FROM
that file by render.py (see deploy.py --render-only).

Precedence for every overridable value: CLI flag > environment variable >
config.yml. Environment overrides recognized here:

    BENTOML_DEPLOY_K8S_CONTEXT     overrides kubernetes.context
    BENTOML_DEPLOY_K8S_NAMESPACE   overrides kubernetes.namespace
    BENTOML_DEPLOY_EC2_HOSTS       overrides ec2.hosts (comma-separated)

(BENTOML_DEPLOY_IMAGE / BENTOML_DEPLOY_VERSION are handled by deploy.py.)

All validation failures exit with code 2 (config error) and name the exact
config path that is wrong, e.g. `services.Gateway.expose.node_port`.

YAML parsing needs PyYAML — the one non-stdlib dependency of this bundle.
`bentoml` already depends on it, so any machine that can build is fine; a
deploy-only CI job needs `pip install pyyaml`.

Two things are DERIVED here and never maintained by hand:
  * each service's slug (its Kubernetes object name), when not set explicitly;
  * the rollout order — a topological sort of `depends` (deepest dependencies
    first, alphabetical within a tier, so it is deterministic).
"""

