def parse_k8s_timestamp(value: str) -> datetime | None:
    """Parse an RFC3339 creationTimestamp like 2026-08-13T02:11:00Z."""
    try:
        return datetime.strptime(value.strip(), "%Y-%m-%dT%H:%M:%SZ").replace(
            tzinfo=timezone.utc
        )
    except ValueError:
        return None


