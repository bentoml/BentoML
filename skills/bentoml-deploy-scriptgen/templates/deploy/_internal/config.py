@dataclass
class ImageConfig:
    """`image:` is ONE URL with no tag — the tag is always the bento version.

    Everything else about the registry is derived from the URL: whether it is
    ECR (automatic login + describe-or-create), and which region. An empty URL
    is the kind/minikube case: nothing is pushed and the image name is the bento
    tag itself.
    """

    # "<registry>/<repository>" exactly as written in config.yml, no tag.
    url: str = ""
    registry: str = ""  # host part, "" when the URL has none (Docker Hub)
    repository: str = ""  # the rest; the ECR repository name
    kind: str = REGISTRY_KIND_NONE  # derived: ecr | generic | none
    ecr_region: str | None = None  # derived from an ECR host

    @property
    def pushes(self) -> bool:
        """False for an empty `image:` — the kind/minikube case, where nothing
        is pushed and the image name is the bento tag itself."""
        return self.kind != REGISTRY_KIND_NONE

    def ref(self, tag: str) -> str:
        return f"{self.url}:{tag}" if self.url else tag


def _parse_image(data: dict[str, Any]) -> ImageConfig:
    raw = data.get("image")
    if isinstance(raw, dict):
        raise _fail(
            "image",
            "is a mapping, but v4 expects ONE image URL as a plain string",
            hint="v3's image.registry + image.repository became a single "
            "`image: <registry>/<repository>` with NO tag (the tag is always "
            "the bento version). image.registry_type, image.ecr_region and "
            "image.platform are gone: ECR is recognized from the URL host, and "
            "a cross-architecture build is detected by comparing `docker info` "
            "with the cluster's node architecture. Example:\n"
            "    image: 123456789012.dkr.ecr.us-west-1.amazonaws.com/my-bento",
        )
    if raw is None:
        url = ""
    else:
        url = _expect_type(raw, (str,), "image", "a string").strip().rstrip("/")
    if "local_image_preloaded" in data:
        warn(
            f"{CONFIG_FILE_NAME}: local_image_preloaded no longer exists and is "
            "ignored — an empty `image:` already means the image is not pushed "
            "anywhere and must already be on the cluster nodes. Delete the key."
        )
    if not url:
        # The kind/minikube case: nothing is pushed, and the image name is the
        # bento tag itself (<bento name>:<version>), which the caller resolves
        # from the discovered topology.
        return ImageConfig(kind=REGISTRY_KIND_NONE)
    if any(ch.isspace() for ch in url):
        raise _fail("image", f"{url!r} contains whitespace")
    if "://" in url:
        raise _fail(
            "image",
            f"{url!r} is a URL with a scheme",
            hint="write the image reference only, e.g. "
            "ghcr.io/acme/my-bento (no https://)",
        )
    if "@" in url:
        raise _fail(
            "image",
            f"{url!r} pins a digest",
            hint="`image:` is the repository only. The tag is the bento "
            "version, chosen per run; to deploy one specific existing image "
            "pass --image <full ref> instead.",
        )
    last = url.rsplit("/", 1)[-1]
    if ":" in last:
        raise _fail(
            "image",
            f"{url!r} includes a tag",
            hint="`image:` must be the repository with NO tag: the tag is "
            "always the bento version (by default the project's short git "
            "SHA, so bento version == git SHA == image tag). Override it with "
            "--version TAG, or deploy one specific ref with --image REF. "
            f"Write: image: {url.rsplit(':', 1)[0]}",
        )
    head = url.split("/", 1)[0]
    has_host = "." in head or ":" in head or head == "localhost"
    registry = head if has_host else ""
    repository = url.split("/", 1)[1] if (has_host and "/" in url) else url
    if has_host and "/" not in url:
        raise _fail(
            "image",
            f"{url!r} names a registry host but no repository",
            hint="write <registry>/<repository>, e.g. "
            "123456789012.dkr.ecr.us-west-1.amazonaws.com/my-bento",
        )
    if not IMAGE_PATH_RE.match(repository):
        raise _fail(
            "image",
            f"repository part {repository!r} is not a valid image path",
            hint="image repositories are LOWERCASE and may contain digits, "
            "'.', '_', '-' and '/' as a separator (docker rejects anything "
            "else outright)",
        )
    ecr_match = ECR_HOST_RE.match(registry)
    if ecr_match:
        return ImageConfig(
            url=url,
            registry=registry,
            repository=repository,
            kind=REGISTRY_KIND_ECR,
            ecr_region=ecr_match.group("region"),
        )
    return ImageConfig(
        url=url,
        registry=registry,
        repository=repository,
        kind=REGISTRY_KIND_GENERIC,
    )


