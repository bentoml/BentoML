_BENTOML_VERSION_RE = re.compile(r"version\s+(\d+)\.(\d+)")


def build_checks(cfg: Config) -> list[Check]:
    def bentoml_cli() -> str | None:
        _which(
            "bentoml",
            "pip install 'bentoml>=1.4' into the environment running this script",
        )
        res = run(
            ["bentoml", "--version"], capture=True, quiet=True, check=False, timeout=60
        )
        if res.returncode != 0:
            raise CheckFailed(
                "'bentoml --version' failed: %s"
                % (res.stderr.strip() or res.stdout.strip())
            )
        text = (res.stdout + res.stderr).strip()
        match = _BENTOML_VERSION_RE.search(text)
        if not match:
            warn(f"could not parse bentoml version from {text!r} — continuing")
            return text
        major, minor = int(match.group(1)), int(match.group(2))
        if (major, minor) < (1, 4):
            raise CheckFailed(
                f"bentoml >= 1.4 required, found {major}.{minor}",
                hint="pip install --upgrade 'bentoml>=1.4'",
            )
        return f"{major}.{minor}"

    def service_files() -> str | None:
        # The build context must look like a BentoML project.
        has_service = (cfg.project / "service.py").is_file()
        has_bentofile = (cfg.project / "bentofile.yaml").is_file()
        if not has_service and not has_bentofile:
            raise CheckFailed(
                f"neither service.py nor bentofile.yaml found in {cfg.project}",
                hint="fix `project:` in config.yml (a path resolved relative "
                "to the directory that holds config.yml)",
            )
        return str(cfg.project)

    return [
        ("build.bentoml-cli", bentoml_cli),
        ("build.project-files", service_files),
    ]


