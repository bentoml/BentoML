def _manifests_dir_text(k8s: K8sConfig) -> tuple[str, int]:
    """kubernetes.manifests_dir: the files concatenated VERBATIM. No
    substitution of any kind — those files are the source of truth, image
    reference included."""
    docs: list[str] = []
    files = _manifest_files(k8s)
    for path in files:
        docs.append(path.read_text(encoding="utf-8").rstrip() + "\n")
    return "---\n".join(docs), len(files)


def _role(svc: ServiceSpec) -> str:
    return "entry" if svc.entry else "dependency"


def _rollback_guidance(k8s: K8sConfig) -> str:
    """Diagnosis + rollback commands naming EVERY deployment: one bad
    dependency takes the whole bento down, so a partial list would send the
    user looking in the wrong pod."""
    base = f"kubectl --context {k8s.context} -n {k8s.namespace}"
    lines = [f"Diagnose ({len(k8s.services)} deployment(s), one per service):"]
    for svc in k8s.services:
        lines.append(f"  # {svc.name} ({_role(svc)})")
        lines.append(f"  {base} get pods -l app.kubernetes.io/name={svc.slug}")
        lines.append(f"  {base} describe deployment/{svc.slug}")
        lines.append(f"  {base} logs deployment/{svc.slug} --all-containers --tail=100")
    lines.append("Roll back to the previous revision (dependencies first, entry last):")
    for svc in k8s.services:
        lines.append(f"  {base} rollout undo deployment/{svc.slug}")
        lines.append(
            f"  {base} rollout status deployment/{svc.slug}"
            f" --timeout={k8s.rollout_timeout_seconds}s"
        )
    lines.append("(or re-run this script with --image <previous-ref>)")
    if len(k8s.services) > 1:
        lines.append(
            "Note: a caller's /readyz fans out to its dependencies, so it "
            "stays 503 (and its pods stay unready) until every dependency "
            "answers — diagnose the deepest dependencies first."
        )
    return "\n".join(lines)


def deploy(ctx: RunContext) -> None:
    k8s = ctx.cfg.require_k8s()
    started = time.monotonic()
    if k8s.manifests_dir is None:
        section(
            f"deploy: render config.yml + kubectl apply (context={k8s.context} "
            f"namespace={k8s.namespace} services={len(k8s.services)} "
            f"image={ctx.image})"
        )
        rendered = render_all(ctx.cfg, str(ctx.image))
        objects = len(render_documents(ctx.cfg, str(ctx.image)))
        source = f"rendered {objects} object(s) from config.yml"
        log(f"{source} (see them with --render-only)")
    else:
        section(
            f"deploy: kubectl apply of {k8s.manifests_dir} AS-IS "
            f"(kubernetes.manifests_dir is set — config.yml does NOT drive the "
            f"workload shape; context={k8s.context} namespace={k8s.namespace} "
            f"image={ctx.image})"
        )
        rendered, count = _manifests_dir_text(k8s)
        if not rendered.strip():
            raise DeployError(
                f"no manifests to apply in {k8s.manifests_dir}",
                EXIT_DEPLOY,
                hint="unset kubernetes.manifests_dir to render from config.yml",
            )
        source = (
            f"applied {count} file(s) from {k8s.manifests_dir} VERBATIM "
            "(kubernetes.manifests_dir) — the image refs in those files are "
            f"what runs; this run's image ({ctx.image}) was NOT substituted"
        )
        log(source)
    # -n is belt-and-braces: every object declares this namespace anyway, and
    # kubectl rejects a mismatch rather than silently splitting the deploy
    # across two namespaces.
    res = run(
        _kubectl(k8s, "apply", "-n", k8s.namespace, "-f", "-"),
        input_text=rendered,
        capture=True,
        check=False,
    )
    for line in (res.stdout.strip() + "\n" + res.stderr.strip()).splitlines():
        if line:
            log("  " + line)
    if res.returncode != 0:
        ctx.summary.record_stage(
            "k8s.apply", False, time.monotonic() - started, detail=source
        )
        raise DeployError(
            f"kubectl apply failed (exit {res.returncode})",
            EXIT_DEPLOY,
            hint=_rollback_guidance(k8s),
        )
    ctx.summary.record_stage(
        "k8s.apply", True, time.monotonic() - started, detail=source
    )

    _wait_for_rollouts(ctx, k8s)


def _wait_for_rollouts(ctx: RunContext, k8s: K8sConfig) -> None:
    """`kubectl rollout status` per service in the derived rollout order
    (deepest dependencies first) with the configured timeout each, fail-fast.
    Every service gets its own k8s.rollout[<slug>] stage in the summary."""
    log(
        f"waiting for {len(k8s.services)} rollout(s) in dependency order "
        f"(deepest dependencies first, entry last; timeout "
        f"{k8s.rollout_timeout_seconds}s each)..."
    )
    for index, svc in enumerate(k8s.services):
        started = time.monotonic()
        log(f"rollout {index + 1}/{len(k8s.services)}: {svc.name} ({_role(svc)})")
        rollout, fatal = _rollout_status(k8s, svc)
        if rollout.returncode != 0:
            ctx.summary.record_stage(
                _rollout_stage(svc), False, time.monotonic() - started
            )
            for later in k8s.services[index + 1 :]:
                ctx.summary.record_stage(
                    _rollout_stage(later),
                    False,
                    0.0,
                    detail="not attempted (fail-fast after an earlier "
                    "service's rollout failed)",
                )
            if fatal:
                raise DeployError(
                    f"rollout of deployment/{svc.slug} (BentoML service "
                    f"{svc.name!r}, {_role(svc)}) cannot succeed: {fatal}",
                    EXIT_DEPLOY,
                    hint=_rollback_guidance(k8s),
                )
            raise DeployError(
                f"rollout of deployment/{svc.slug} (BentoML service "
                f"{svc.name!r}, {_role(svc)}) did not complete within "
                f"{k8s.rollout_timeout_seconds}s",
                EXIT_DEPLOY,
                hint=_rollback_guidance(k8s),
            )
        ctx.summary.record_stage(_rollout_stage(svc), True, time.monotonic() - started)
        log(f"rollout of deployment/{svc.slug} complete")
    log("all rollouts complete")


# A pod state that no amount of further waiting can fix. Without this, a
# mistyped image or a missing pull secret burns the whole rollout timeout
# (kubectl rollout status keeps waiting, and the Deployment's own progress
# deadline is 10 min) before saying anything useful. Reasons are matched on
# the container's waiting.reason, which kubelet sets long before either
# deadline expires.
_FATAL_WAITING_REASONS = (
    "ImagePullBackOff",
    "ErrImagePull",
    "InvalidImageName",
    "ImageInspectError",
    "RegistryUnavailable",
    "CreateContainerConfigError",
    "CreateContainerError",
)

# CrashLoopBackOff is only fatal once the container has proven it keeps dying:
# one early restart can be a slow dependency or a transient OOM on a busy node.
_CRASHLOOP_RESTART_THRESHOLD = 3

# How long to let kubectl rollout status run before pausing to inspect the
# pods. Short enough that a pull failure is reported in well under a minute,
# long enough that a healthy rollout is not interrupted more than a few times.
_ROLLOUT_POLL_SECONDS = 15


def _fatal_pod_state(k8s: K8sConfig, svc: ServiceSpec) -> str | None:
    """A one-line diagnosis when a pod of this service is in a state that
    waiting cannot fix, else None. Read-only; any kubectl failure (RBAC, a
    flaky apiserver) yields None so this can only ever speed up a failure
    that was going to happen anyway, never invent one."""
    res = run(
        _kubectl(
            k8s,
            "get",
            "pods",
            "-n",
            k8s.namespace,
            "-l",
            "app.kubernetes.io/name=" + svc.slug,
            "-o",
            "yaml",
        ),
        capture=True,
        quiet=True,
        check=False,
        timeout=30,
    )
    if res.returncode != 0:
        return None
    try:
        parsed = yaml.safe_load(res.stdout) or {}
    except Exception:
        return None
    for pod in parsed.get("items") or []:
        if not isinstance(pod, dict):
            continue
        name = (pod.get("metadata") or {}).get("name", "?")
        status = pod.get("status") or {}
        for container in status.get("containerStatuses") or []:
            waiting = (container.get("state") or {}).get("waiting") or {}
            reason = waiting.get("reason") or ""
            message = (waiting.get("message") or "").strip().splitlines()
            detail = message[0] if message else ""
            if reason in _FATAL_WAITING_REASONS:
                return f"pod {name}: {reason}" + (f" — {detail}" if detail else "")
            if (
                reason == "CrashLoopBackOff"
                and int(container.get("restartCount") or 0)
                >= _CRASHLOOP_RESTART_THRESHOLD
            ):
                return (
                    f"pod {name}: CrashLoopBackOff after "
                    f"{container.get('restartCount')} restarts — see "
                    f"`kubectl --context {k8s.context} -n {k8s.namespace} "
                    f"logs {name} --previous`"
                )
    return None


def _pod_blocked_reason(k8s: K8sConfig, svc: ServiceSpec) -> str | None:
    """Why this service's pods are not running yet, from the pods' own
    conditions (`Unschedulable` and friends). Unlike _fatal_pod_state this is
    NOT a verdict — a pod can stop being unschedulable the moment capacity
    frees up — so it is only used to enrich a failure the Deployment itself has
    already given up on. Read-only, None on any kubectl problem."""
    res = run(
        _kubectl(
            k8s,
            "get",
            "pods",
            "-n",
            k8s.namespace,
            "-l",
            "app.kubernetes.io/name=" + svc.slug,
            "-o",
            "yaml",
        ),
        capture=True,
        quiet=True,
        check=False,
        timeout=30,
    )
    if res.returncode != 0:
        return None
    try:
        parsed = yaml.safe_load(res.stdout) or {}
    except Exception:
        return None
    for pod in parsed.get("items") or []:
        if not isinstance(pod, dict):
            continue
        status = pod.get("status") or {}
        if status.get("phase") != "Pending":
            continue
        name = (pod.get("metadata") or {}).get("name", "?")
        for condition in status.get("conditions") or []:
            if condition.get("status") == "True":
                continue
            reason = condition.get("reason") or ""
            message = (condition.get("message") or "").strip().splitlines()
            if not reason:
                continue
            detail = message[0] if message else ""
            return f"pod {name}: {reason}" + (f" — {detail}" if detail else "")
    return None


# The Deployment's own verdict, printed by `kubectl rollout status` once
# spec.progressDeadlineSeconds (10 min by default) expires without progress.
# Waiting past it is pointless: Kubernetes has stopped trying to make progress
# and will not resume without a change.
_PROGRESS_DEADLINE_MARKER = "exceeded its progress deadline"


def _rollout_status(k8s: K8sConfig, svc: ServiceSpec) -> tuple[RunResult, str | None]:
    """kubectl rollout status for one service, in short slices so the pods can
    be inspected in between. Returns (last result, fatal diagnosis or None);
    a fatal diagnosis short-circuits the wait instead of burning the timeout."""
    deadline = time.monotonic() + k8s.rollout_timeout_seconds
    reported = ""
    while True:
        slice_seconds = min(
            _ROLLOUT_POLL_SECONDS, max(1, int(deadline - time.monotonic()))
        )
        res = run(
            _kubectl(
                k8s,
                "rollout",
                "status",
                "deployment/" + svc.slug,
                "-n",
                k8s.namespace,
                f"--timeout={slice_seconds}s",
            ),
            capture=True,
            quiet=True,
            check=False,
        )
        # kubectl repeats the same progress line every slice; echo it only when
        # it changes, so a slow image pull does not scroll the log. The
        # per-slice "timed out waiting" is this function's own pacing, not a
        # failure, so it is never echoed.
        progress = [
            line.strip()
            for line in (res.stdout or "").splitlines()
            if line.strip() and not line.strip().startswith("error:")
        ]
        if progress and progress[-1] != reported:
            reported = progress[-1]
            log("  " + reported)
        if res.returncode == 0:
            return res, None
        fatal = _fatal_pod_state(k8s, svc)
        if fatal is not None:
            return res, fatal
        if _PROGRESS_DEADLINE_MARKER in (res.stdout or "") + (res.stderr or ""):
            # Kubernetes gave up before our own timeout did. Say why the pods
            # never came up when they can tell us (Unschedulable is the usual
            # answer), and stop rather than idling until rollout_timeout_seconds.
            blocked = _pod_blocked_reason(k8s, svc)
            return res, "the Deployment exceeded its own progress deadline" + (
                f" ({blocked})" if blocked else ""
            )
        if time.monotonic() >= deadline:
            # Log kubectl's last word: it is captured, so it never reached the
            # terminal, and the timeout message alone does not say what stalled.
            last = [
                line.strip()
                for line in (
                    (res.stderr or "") + "\n" + (res.stdout or "")
                ).splitlines()
                if line.strip()
            ]
            if last:
                log("  " + last[0])
            return res, None


def _rollout_stage(svc: ServiceSpec) -> str:
    return f"k8s.rollout[{svc.slug}]"


