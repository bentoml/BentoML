"""Load and validate config.yml (schema bentoml-deploy-config/v4).

Generated by the bentoml-deploy-scriptgen skill — do not edit by hand; all
tunables live in config.yml, and the Kubernetes manifests are rendered FROM
that file by render.py (see deploy.py --render-only).

v4 is deliberately smaller than v3: everything the bento already knows about
itself is read from its `bento.yaml` at run time (see topology.py) instead of
being repeated here. So config.yml has no service list, no `entry:`, no
`depends:`, no registry type, no platform and no image tag — and a minimal
config is five lines:

    project: ..
    image: 123456789012.dkr.ecr.us-west-1.amazonaws.com/my-bento
    kubernetes:
      context: my-cluster
      namespace: default

`services:` is optional and holds per-service OVERRIDES ONLY, keyed by BentoML
service name; a key that is not a service of the bento is an error (typo
protection), and a service with no block gets the shipped defaults.

Precedence for every overridable value: CLI flag > environment variable >
config.yml. Environment overrides recognized here:

    BENTOML_DEPLOY_K8S_CONTEXT     overrides kubernetes.context
    BENTOML_DEPLOY_K8S_NAMESPACE   overrides kubernetes.namespace
    BENTOML_DEPLOY_EC2_HOSTS       overrides ec2.hosts (comma-separated)

(BENTOML_DEPLOY_IMAGE / BENTOML_DEPLOY_VERSION are handled by deploy.py.)

All validation failures exit with code 2 (config error) and name the exact
config path that is wrong, e.g. `services.Gateway.expose.node_port`.

YAML parsing needs PyYAML — the one non-stdlib dependency of this bundle.
`bentoml` already depends on it, so any machine that can build is fine; a
deploy-only CI job needs `pip install pyyaml`.

DERIVED here and never maintained by hand: each service's slug (its Kubernetes
object name), and — from the discovered topology, in bind_topology() — the
entry service, the dependency wiring and the rollout order.
"""

