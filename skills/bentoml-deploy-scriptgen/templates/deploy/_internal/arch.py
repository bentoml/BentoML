"""Cross-architecture build detection — the replacement for the deleted
`image.platform` knob.

Generated by the bentoml-deploy-scriptgen skill — do not edit by hand; all
tunables live in config.yml.

An amd64 cluster served an arm64 image (or the reverse) does not fail visibly:
the pod starts, the container dies with `exec format error`, and the rollout
burns its whole timeout in CrashLoopBackOff. v3 asked the user to prevent that
by hand (`image.platform: "linux/amd64"`), which meant a knob that is wrong by
default on every machine whose arch differs from the cluster's.

v4 detects it instead: compare the local builder's architecture (`docker info`)
with the deploy target's (for Kubernetes, the `kubernetes.io/arch` label of the
cluster's nodes; for EC2, each host's `uname -m`). When they differ the build
gets `--opt platform=linux/<target arch>` and says so in the log.

decide_platform() is deliberately pure — it takes two already-collected values
and returns the decision — so the interesting cases (match, cross, mixed-arch
cluster, unknown) are testable without a docker daemon or a cluster.
"""

# This bundle gets committed into arbitrary user repos; the directive below
# keeps the import layout stable under any repo's ruff/isort configuration.
# isort: skip_file
from __future__ import annotations

import platform as _platform
import shutil
from dataclasses import dataclass

from .common import run

# docker/uname spellings -> the OCI/Kubernetes spelling used in a platform
# string and in the kubernetes.io/arch label.
ARCH_ALIASES = {
    "x86_64": "amd64",
    "x86-64": "amd64",
    "amd64": "amd64",
    "aarch64": "arm64",
    "arm64": "arm64",
    "armv8l": "arm64",
}


def normalize_arch(raw: str | None) -> str:
    """'x86_64' -> 'amd64', 'aarch64' -> 'arm64'; anything unknown is passed
    through lowercased (a genuinely exotic arch must still compare equal to
    itself rather than silently becoming 'unknown')."""
    if not raw:
        return ""
    value = raw.strip().lower()
    if not value or value in ("<none>", "none", "unknown"):
        return ""
    return ARCH_ALIASES.get(value, value)


def host_arch() -> str:
    """This machine's architecture, without asking docker."""
    return normalize_arch(_platform.machine())


_builder_arch_cache: dict[str, str] = {}


def docker_builder_arch() -> str:
    """The architecture of the daemon that will build the image (which is NOT
    necessarily this machine's: a remote DOCKER_HOST or a Lima/colima VM can
    differ). Empty string when docker cannot be asked."""
    if "arch" in _builder_arch_cache:
        return _builder_arch_cache["arch"]
    arch = ""
    if shutil.which("docker"):
        res = run(
            ["docker", "info", "--format", "{{.Architecture}}"],
            capture=True,
            quiet=True,
            check=False,
            timeout=30,
        )
        if res.returncode == 0:
            arch = normalize_arch(res.stdout)
    _builder_arch_cache["arch"] = arch
    return arch


def cluster_node_arches(context: str) -> list[str]:
    """The `kubernetes.io/arch` label of every node, in node order (duplicates
    kept, so a mixed cluster's majority arch can be computed). Empty when the
    cluster cannot be reached."""
    res = run(
        [
            "kubectl",
            "--context",
            context,
            "get",
            "nodes",
            "-L",
            "kubernetes.io/arch",
            "--no-headers",
            "--request-timeout=20s",
        ],
        capture=True,
        quiet=True,
        check=False,
        timeout=60,
    )
    if res.returncode != 0:
        return []
    arches: list[str] = []
    for line in res.stdout.splitlines():
        fields = line.split()
        if not fields:
            continue
        # -L appends the label value as the LAST column ('<none>' when unset).
        arch = normalize_arch(fields[-1])
        if arch:
            arches.append(arch)
    return arches


@dataclass
class PlatformDecision:
    """What to pass to `bentoml containerize`, and why."""

    # "linux/amd64" etc. when a cross-arch build is needed; None to build
    # natively (either the archs match or one of them is unknown).
    platform: str | None
    # True when the build has to target an arch other than the builder's.
    cross: bool
    # True when the target has more than one architecture.
    mixed: bool
    # One log line explaining the decision, always set.
    message: str


def decide_platform(
    builder_arch: str, target_arches: list[str], target_label: str = "cluster nodes"
) -> PlatformDecision:
    """Pure decision: compare the builder arch with the target's arch(es).

    - unknown on either side  -> build natively, say what was missing;
    - one arch, equal         -> build natively;
    - one arch, different     -> cross-build for it;
    - several arches          -> a single image cannot satisfy all of them.
      Build for the builder's own arch when it is among them (the pods that can
      run it will), otherwise for the most common one, and warn either way:
      the real fix is a node_selector per service.
    """
    builder = normalize_arch(builder_arch)
    targets = [normalize_arch(arch) for arch in target_arches]
    targets = [arch for arch in targets if arch]
    if not builder and not targets:
        return PlatformDecision(
            None,
            False,
            False,
            "cross-arch check skipped: neither the builder architecture nor "
            f"the {target_label} architecture could be determined",
        )
    if not builder:
        return PlatformDecision(
            None,
            False,
            len(set(targets)) > 1,
            "cross-arch check skipped: the builder architecture could not be "
            f"determined (docker info); {target_label}: {sorted(set(targets))}",
        )
    if not targets:
        return PlatformDecision(
            None,
            False,
            False,
            f"cross-arch check skipped: the {target_label} architecture could "
            f"not be determined; building natively for {builder}",
        )
    distinct = sorted(set(targets))
    if len(distinct) == 1:
        target = distinct[0]
        if target == builder:
            return PlatformDecision(
                None,
                False,
                False,
                f"builder and {target_label} both run {builder} — building natively",
            )
        return PlatformDecision(
            f"linux/{target}",
            True,
            False,
            f"CROSS-ARCH BUILD: builder={builder}, {target_label}={target} — "
            f"building for linux/{target} (an image of the wrong architecture "
            "starts and then dies with 'exec format error')",
        )
    counted = sorted(distinct, key=lambda arch: (-targets.count(arch), arch))
    if builder in distinct:
        return PlatformDecision(
            None,
            False,
            True,
            f"MIXED ARCHITECTURES in {target_label} ({distinct}) — building "
            f"natively for "
            f"{builder}, which some of them can run. Pin each service to a "
            'matching pool (node_selector: {"kubernetes.io/arch": '
            f'"{builder}"}}), or publish a multi-arch image yourself: one '
            "single-arch image cannot run everywhere here",
        )
    target = counted[0]
    return PlatformDecision(
        f"linux/{target}",
        True,
        True,
        f"MIXED ARCHITECTURES in {target_label} ({distinct}), none of them the "
        f"builder's "
        f"{builder}: building for linux/{target} (the most common). Pin each "
        'service with node_selector: {"kubernetes.io/arch": '
        f'"{target}"}}, or publish a multi-arch image yourself',
    )


def buildx_available() -> bool:
    """A cross-arch `bentoml containerize` needs the buildx plugin (BuildKit is
    what honours --opt platform)."""
    if not shutil.which("docker"):
        return False
    res = run(
        ["docker", "buildx", "version"],
        capture=True,
        quiet=True,
        check=False,
        timeout=30,
    )
    return res.returncode == 0
