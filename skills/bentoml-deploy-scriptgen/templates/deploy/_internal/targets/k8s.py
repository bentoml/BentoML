class _PortForward:
    """kubectl port-forward to one Service, with PID-liveness checks and
    guaranteed cleanup.

    A local health probe is only trustworthy while the port-forward process
    is alive — if it died, whatever squats on the local port would produce
    convincing but fake results. alive() must be checked before every probe.

    Defaults to the ENTRY service (the only one that speaks the public HTTP
    API); the dependency-metrics check forwards to each dependency POD to
    scrape its /metrics, which is a read-only probe inside the cluster.

    Pass `pod=` to target one pod instead of a Service. That matters for
    /metrics: a Service load-balances, so scraping svc/<dep> reads ONE
    replica's counters at random and a request served by a sibling pod looks
    like no request at all.
    """

    def __init__(
        self,
        k8s: K8sConfig,
        service: str | None = None,
        local_port: int | None = None,
        pod: str | None = None,
    ) -> None:
        self._k8s = k8s
        self._service = service or k8s.entry_service.slug
        self._target = f"pod/{pod}" if pod else f"svc/{self._service}"
        self._local_port = local_port or k8s.local_port
        # Not a context manager on purpose: the file must outlive this
        # constructor (the port-forward writes to it until close()).
        self._log = tempfile.NamedTemporaryFile(  # noqa: SIM115
            mode="w+", prefix="bentoml-deploy-pf-", suffix=".log", delete=False
        )
        self._proc = subprocess.Popen(
            _kubectl(
                k8s,
                "port-forward",
                self._target,
                "-n",
                k8s.namespace,
                f"{self._local_port}:3000",
            ),
            stdout=self._log,
            stderr=self._log,
            text=True,
        )

    def alive(self) -> bool:
        return self._proc.poll() is None

    def wait_until_forwarding(self, timeout_seconds: float) -> None:
        """Block until kubectl reports 'Forwarding from' (i.e. it owns the
        local port). Probing earlier risks hitting an unrelated process that
        squats on the port during kubectl's spawn-to-bind window — a
        convincing but fake result."""
        deadline = time.monotonic() + timeout_seconds
        while time.monotonic() < deadline:
            if not self.alive():
                raise DeployError(
                    "kubectl port-forward exited before binding the local "
                    "port:\n" + self.captured_output(),
                    EXIT_VERIFY,
                    hint=f"is local port {self._local_port} free "
                    "(kubernetes.local_port / local_port + 1), and does "
                    f"{self._target} exist in namespace "
                    f"{self._k8s.namespace}?",
                )
            if "Forwarding from" in self.captured_output():
                return
            time.sleep(0.2)
        raise DeployError(
            f"kubectl port-forward did not report 'Forwarding from' within "
            f"{timeout_seconds:.0f}s:\n" + self.captured_output(),
            EXIT_VERIFY,
        )

    def captured_output(self) -> str:
        try:
            with open(self._log.name, encoding="utf-8") as fh:
                return fh.read().strip()
        except OSError:
            return "(no port-forward output captured)"

    def close(self) -> None:
        if self._proc.poll() is None:
            self._proc.terminate()
            try:
                self._proc.wait(timeout=5)
            except subprocess.TimeoutExpired:
                self._proc.kill()
                self._proc.wait(timeout=5)
        self._log.close()
        try:
            Path(self._log.name).unlink()
        except OSError:
            pass


def verify(ctx: RunContext) -> None:
    k8s = ctx.cfg.require_k8s()
    vcfg = ctx.cfg.verify
    entry = k8s.entry_service
    deps = k8s.dependencies
    base_url = f"http://127.0.0.1:{k8s.local_port}"
    section(
        f"verify: entry service {entry.name} — /readyz via port-forward to "
        f"svc/{entry.slug} on {base_url}"
    )

    pf = _PortForward(k8s)
    try:
        pf.wait_until_forwarding(30)
        _wait_ready(pf, base_url, vcfg.readyz_timeout_seconds, k8s)
        if vcfg.inference is None:
            # verify.inference is OPTIONAL: with no block, /readyz above IS the
            # verification. That is enough to prove every pod started, served
            # HTTP and (for a caller) reached its dependencies' /readyz — but
            # not that an inference request travels the dependency path.
            log(
                "verify.inference is not configured — verification is /readyz "
                "only (add a verify.inference block to POST a real request)"
            )
            if deps:
                log(
                    "dependency-metrics proof SKIPPED: this bento has "
                    f"{len(deps)} dependency service(s), and only a real "
                    "inference request exercises the dependency path. Without "
                    "one, a gateway that silently instantiated its "
                    "dependencies IN-PROCESS answers /readyz exactly like a "
                    "correctly wired split — set verify.inference to close "
                    "that gap."
                )
            return
        # A gateway's /readyz proves NOTHING about a dependency that was
        # instantiated in-process: readiness only fans out to dependencies
        # that are remote proxies, so an in-process one is skipped and
        # readiness is trivially true. The dependency's own request counter
        # is the only positive evidence that the call crossed the network.
        measure = bool(deps) and vcfg.dependency_metrics
        before: dict[str, float] = {}
        if measure:
            log(
                f"sampling {REQUEST_TOTAL_METRIC} on {len(deps)} "
                "dependency service(s) before the inference request"
            )
            before = _sample_dependency_totals(k8s, deps)
        elif deps:
            warn(
                "verify.dependency_metrics is false — not proving that the "
                "dependencies are reached over the network. A gateway that "
                "silently instantiated them in-process answers correctly "
                "and reports ready, so this run cannot tell the two apart."
            )
        _inference_smoke(pf, base_url, vcfg.inference)
        if measure:
            after = _sample_dependency_totals(k8s, deps)
            _assert_dependencies_called(k8s, deps, before, after)
    finally:
        pf.close()


def _running_pods(k8s: K8sConfig, slug: str) -> list[str]:
    """Names of this service's Running pods, or [] when they cannot be listed
    (the caller then falls back to scraping the Service)."""
    res = run(
        _kubectl(
            k8s,
            "get",
            "pods",
            "-n",
            k8s.namespace,
            "-l",
            "app.kubernetes.io/name=" + slug,
            "--field-selector=status.phase=Running",
            "-o",
            "jsonpath={.items[*].metadata.name}",
        ),
        capture=True,
        quiet=True,
        check=False,
        timeout=30,
    )
    if res.returncode != 0:
        return []
    return res.stdout.split()


def _sample_dependency_totals(
    k8s: K8sConfig, deps: list[ServiceSpec]
) -> dict[str, float]:
    """Scrape each dependency's own /metrics through short-lived port-forwards
    and return its non-health request total, summed over ALL of its pods.

    Per POD, not per Service: a Service load-balances, so one scrape of
    svc/<dep> reads a random replica and a request that a sibling pod served
    would look like no request at all — a false "served no request" failure on
    any dependency with replicas > 1. Summing every pod is exact regardless of
    which replica the entry service happened to call.

    Read-only: /metrics is not instrumented by the metrics middleware, so
    scraping never moves the counter it reports. The forwards are sequential
    and share one local port (kubernetes.local_port + 1)."""
    port = k8s.local_port + 1
    totals: dict[str, float] = {}
    for dep in deps:
        pods = _running_pods(k8s, dep.slug)
        if not pods:
            # No pod list (RBAC, or a race with a restart): fall back to the
            # Service. Still correct for a single replica, and the alternative
            # is losing the proof entirely.
            warn(
                f"could not list pods of dependency {dep.name} "
                f"(svc/{dep.slug}); scraping the Service instead, which reads "
                "one replica at random — a false 'served no request' is "
                "possible if this dependency has more than one pod"
            )
        targets = pods or [None]
        total = 0.0
        for pod in targets:
            label = f"pod/{pod}" if pod else f"svc/{dep.slug}"
            pf = _PortForward(k8s, dep.slug, port, pod=pod)
            try:
                pf.wait_until_forwarding(30)
                try:
                    status, body = http_get(
                        f"http://127.0.0.1:{port}/metrics", timeout=10
                    )
                except (urllib.error.URLError, OSError) as exc:
                    raise DeployError(
                        f"could not scrape /metrics of dependency {label}: {exc}",
                        EXIT_VERIFY,
                        hint="set verify.dependency_metrics to false to skip "
                        "this proof (and lose the only signal that the "
                        "dependency is reached over the network)",
                    ) from None
                if not pf.alive():
                    raise DeployError(
                        "port-forward to dependency "
                        f"{label} died during the /metrics scrape; the "
                        "response cannot be trusted:\n" + pf.captured_output(),
                        EXIT_VERIFY,
                    )
                if status != 200:
                    raise DeployError(
                        f"/metrics of dependency {label} returned HTTP {status}",
                        EXIT_VERIFY,
                        hint="every BentoML server exposes /metrics on port "
                        "3000; if it is disabled in this bento, set "
                        "verify.dependency_metrics to false",
                    )
                total += _sum_request_total(body)
            finally:
                pf.close()
        totals[dep.slug] = total
    return totals


def _assert_dependencies_called(
    k8s: K8sConfig,
    deps: list[ServiceSpec],
    before: dict[str, float],
    after: dict[str, float],
) -> None:
    """Fail unless every dependency's request counter moved: that is the only
    positive proof the inference request crossed the network instead of being
    served by an in-process copy inside the gateway pod."""
    stale = [
        dep for dep in deps if after.get(dep.slug, 0.0) <= before.get(dep.slug, 0.0)
    ]
    for dep in deps:
        delta = after.get(dep.slug, 0.0) - before.get(dep.slug, 0.0)
        log(f"  {dep.name} (svc/{dep.slug}): {REQUEST_TOTAL_METRIC} +{delta:g}")
    if not stale:
        log("every dependency served a request over the network")
        return
    names = ", ".join(f"{dep.name} (svc/{dep.slug})" for dep in stale)
    raise DeployError(
        f"dependency service(s) {names} served no request during the "
        "inference smoke test — the entry service answered without calling "
        "them over the network",
        EXIT_VERIFY,
        hint="most likely a caller's "
        f"{SERVE_DEPENDS_ENV} does not name them exactly as the bento "
        "declares them, so BentoML instantiated them IN-PROCESS: that pod "
        "loaded those models itself, answers correctly and "
        "reports ready, while the dependency pods idle. The names are the "
        "bento's own (bento.yaml's services[].name and "
        "services[].dependencies[].service), so this points at a hand-owned "
        "manifests_dir or an overridden container command rather than at "
        "config.yml — check what was applied:\n"
        f"  kubectl --context {k8s.context} -n {k8s.namespace} get "
        "deployment/"
        + k8s.entry_service.slug
        + " -o jsonpath='{.spec.template.spec.containers[0].env}'\n"
        "If instead this dependency is simply not on the code path of "
        "verify.inference.path, point the smoke test at an API that uses "
        "it, or set verify.dependency_metrics to false.",
    )


def _wait_ready(
    pf: _PortForward, base_url: str, timeout_seconds: int, k8s: K8sConfig
) -> None:
    entry_slug = k8s.entry_service.slug
    deadline = time.monotonic() + timeout_seconds
    attempt = 0
    while True:
        if not pf.alive():
            raise DeployError(
                "kubectl port-forward exited unexpectedly:\n" + pf.captured_output(),
                EXIT_VERIFY,
                hint=f"is service/{entry_slug} in namespace {k8s.namespace} reachable? "
                f"(kubectl --context {k8s.context} -n {k8s.namespace} get svc,endpoints {entry_slug})",
            )
        attempt += 1
        try:
            status, _ = http_get(base_url + "/readyz", timeout=3)
            if status == 200:
                if not pf.alive():
                    # The forwarder died — whatever answered was not our
                    # service. Never trust a probe the tunnel can't explain.
                    raise DeployError(
                        "port-forward died during the readiness probe; "
                        "the 200 response cannot be trusted:\n" + pf.captured_output(),
                        EXIT_VERIFY,
                    )
                log(f"/readyz returned 200 (attempt {attempt})")
                return
            log(f"/readyz returned {status} — retrying")
        except (urllib.error.URLError, OSError, ConnectionError) as exc:
            if attempt % 5 == 1:
                log(f"waiting for /readyz ({exc})")
        if time.monotonic() >= deadline:
            raise DeployError(
                f"entry service {k8s.entry_service.name!r} "
                f"(svc/{entry_slug}) did not become ready within "
                f"{timeout_seconds}s; port-forward output:"
                f"\n{pf.captured_output()}",
                EXIT_VERIFY,
                hint=_rollback_guidance(k8s),
            )
        time.sleep(2)


def _inference_smoke(
    pf: _PortForward, base_url: str, inference: InferenceCheck
) -> None:
    url = base_url + inference.path
    log(f"inference smoke test: POST {inference.path}")
    if not pf.alive():
        raise DeployError(
            "port-forward died before the inference request:\n" + pf.captured_output(),
            EXIT_VERIFY,
        )
    try:
        status, body = http_post_json(
            url, inference.body, timeout=inference.timeout_seconds
        )
    except (urllib.error.URLError, OSError) as exc:
        raise DeployError(
            f"inference request to {inference.path} failed: {exc}",
            EXIT_VERIFY,
        ) from None
    if not pf.alive():
        raise DeployError(
            "port-forward died during the inference request; the response "
            "cannot be trusted:\n" + pf.captured_output(),
            EXIT_VERIFY,
        )
    snippet = body[:500].replace("\n", " ")
    log(f"response {status}: {snippet}")
    if not 200 <= status < 300:
        raise DeployError(
            f"inference smoke test returned HTTP {status} for "
            f"{inference.path} (body: {snippet})",
            EXIT_VERIFY,
            hint="check verify.inference.body against the service's "
            "@bentoml.api signature",
        )
    if inference.expect_substring and inference.expect_substring not in body:
        raise DeployError(
            f"inference response did not contain expected substring {inference.expect_substring!r} "
            f"(body: {snippet})",
            EXIT_VERIFY,
        )
    log("inference smoke test passed")
