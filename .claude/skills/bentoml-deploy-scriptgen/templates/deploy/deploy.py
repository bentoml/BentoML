def _stage(summary: Summary, name: str, fn: Callable[[], object]) -> object:
    started = time.monotonic()
    try:
        result = fn()
    except BaseException:
        summary.record_stage(name, False, time.monotonic() - started)
        raise
    summary.record_stage(name, True, time.monotonic() - started)
    return result


def main(argv: list | None = None) -> int:
    args = parse_args(argv)
    summary = Summary(
        target=args.target,
        action="check-only" if args.check_only else "deploy",
    )
    failed_stage = "startup"
    try:
        config_path = (
            Path(args.config).resolve()
            if args.config
            else Path(__file__).resolve().parent / "deploy.config.json"
        )
        cfg = load_config(config_path)
        image, version = resolve_image(cfg, args)
        summary.image, summary.version = image, version
        ctx = RunContext(
            cfg=cfg,
            target=args.target,
            image=image,
            version=version,
            check_only=args.check_only,
            skip_build=args.skip_build,
            no_verify=args.no_verify,
            summary=summary,
            local_only=args.local_only,
        )
        target = load_target(args.target)

        failed_stage = "preflight"
        section("preflight")
        need_git = not (
            args.image
            or os.environ.get("BENTOML_DEPLOY_IMAGE")
            or args.version
            or os.environ.get("BENTOML_DEPLOY_VERSION")
        )

        if args.local_only:
            log(
                "--local-only: cluster/registry connectivity checks are "
                "skipped (see skipped_checks in the summary)"
            )

        def _preflight() -> None:
            # ONE aggregated pass over every applicable family — including
            # the target's checks — so a single run reports everything that
            # is wrong (build creds AND cluster access) with one exit 3.
            checks = preflight.common_checks(cfg, need_git)
            if args.skip_build:
                log("--skip-build: skipping build/containerize/registry checks")
                summary.skipped += [
                    "build.* (--skip-build)",
                    "containerize.* (--skip-build)",
                    # registry.image-exists is NOT skipped — it still probes
                    # the registry for the image under --skip-build.
                    "registry login/push checks (--skip-build)",
                ]
                if args.local_only and cfg.image.registry_type != "none":
                    summary.skipped.append("registry.image-exists (--local-only)")
                elif cfg.image.registry_type == "none" or image:
                    # registry_type "none": the preload-ack check is pure
                    # config and must run even under --local-only.
                    checks += preflight.image_exists_checks(cfg, image or "")
            else:
                checks += preflight.build_checks(cfg)
                checks += preflight.containerize_checks(
                    cfg, args.local_only, summary.skipped
                )
                checks += preflight.registry_checks(
                    cfg, args.local_only, summary.skipped
                )
            checks += target.preflight_checks(ctx)
            preflight.run_checks(checks)

        _stage(summary, "preflight", _preflight)

        if args.check_only:
            log("check-only: all preflight checks passed — no changes made")
            if summary.skipped:
                log("skipped (not run this time): " + ", ".join(summary.skipped))
            summary.ok, summary.exit_code = True, EXIT_OK
            return EXIT_OK

        if image is None or version is None:
            # Unreachable: common.git-repo fails in preflight first. Guard
            # anyway so a future refactor cannot deploy an unresolved ref.
            raise DeployError(
                "image reference was never resolved",
                EXIT_CONFIG,
                hint="pass --version TAG or --image REF",
            )

        if args.skip_build:
            log(f"--skip-build: deploying existing image {image}")
        else:
            failed_stage = "build"
            section(f"build (tag {version})")
            bento_tag = _stage(summary, "build", lambda: build_bento(cfg, version))
            failed_stage = "containerize"
            section("containerize")
            _stage(
                summary,
                "containerize",
                lambda: containerize(cfg, str(bento_tag), image),
            )
            failed_stage = "push"
            section("push")
            _stage(summary, "push", lambda: push_image(cfg, image))

        failed_stage = "deploy"
        _stage(summary, "deploy", lambda: target.deploy(ctx))

        if args.no_verify:
            log("--no-verify: skipping post-deploy verification")
        else:
            failed_stage = "verify"
            _stage(summary, "verify", lambda: target.verify(ctx))

        summary.ok, summary.exit_code = True, EXIT_OK
        log("")
        log(f"SUCCESS: {image} deployed to target {args.target}")
        return EXIT_OK

    except DeployError as exc:
        summary.exit_code = exc.exit_code
        summary.error = {
            "stage": failed_stage,
            "code": exc.exit_code,
            "message": str(exc),
            **({"hint": exc.hint} if exc.hint else {}),
        }
        log("")
        log(f"ERROR ({failed_stage}): {exc}")
        if exc.hint:
            log(f"HINT: {exc.hint}")
        return exc.exit_code
    except Exception as exc:  # noqa: BLE001 - never die without a summary
        traceback.print_exc(file=sys.stderr)
        summary.exit_code = EXIT_GENERIC
        summary.error = {
            "stage": "internal",
            "code": EXIT_GENERIC,
            "message": f"{type(exc).__name__}: {exc}",
        }
        log(f"INTERNAL ERROR ({failed_stage}): {exc}")
        return EXIT_GENERIC
    except KeyboardInterrupt:
        summary.exit_code = EXIT_GENERIC
        summary.error = {
            "stage": failed_stage,
            "code": EXIT_GENERIC,
            "message": "interrupted",
        }
        log("interrupted")
        return EXIT_GENERIC
    finally:
        summary.emit(args.output_json)


if __name__ == "__main__":
    sys.exit(main())
