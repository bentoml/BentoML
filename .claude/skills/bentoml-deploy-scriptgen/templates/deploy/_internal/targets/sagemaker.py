"""SageMaker target: deploy the image as a real-time inference endpoint
(bring-your-own-container) and keep the SAME long-lived endpoint updated on
every subsequent run.

Naming and idempotency: every run derives one name,
``<endpoint_name>-<sanitized version tag>``, used for BOTH the model and the
endpoint config (separate SageMaker namespaces). When sanitizing changed the
tag, a short hash of the raw tag is appended so distinct tags (``v1.2.3`` vs
``v1-2-3``) can never alias to the same name. Models and endpoint configs
are immutable, so a same-tag redeploy deletes and recreates the exact-name
model/config it is about to create — never anything else. What happens to
the endpoint itself depends on ``describe-endpoint``:

    absent                        -> create-endpoint
    InService (different config)  -> update-endpoint (the previous config
                                     name is recorded for rollback)
    InService (this exact config) -> nothing to deploy: AWS forbids deleting
                                     the in-use config, and UpdateEndpoint
                                     requires a NEW config — a rebuild of
                                     the same tag needs a new --version
    Failed                        -> delete-endpoint + wait endpoint-deleted
                                     + create-endpoint (AWS rejects
                                     UpdateEndpoint on a Failed endpoint)
    Creating/Updating/Deleting/…  -> abort (exit 6): a concurrent operation
                                     is in progress; this script never
                                     interrupts one

Superseded models/endpoint-configs from earlier tags accumulate (they are
free); the bundle README carries the list/delete commands. This script never
deletes resources it did not just (re)create in the same run, and it NEVER
creates or modifies IAM — targets.sagemaker.execution_role_arn must already
exist (the interactive bentoml-sagemaker-deploy skill can find one or hand
an admin a ready-to-send creation snippet).

The service must already satisfy SageMaker's BYOC contract — HTTP on port
8080 (this target always injects BENTOML_PORT=8080 into the container
environment), ``GET /ping`` -> 200, ``POST /invocations`` — via the
interactive skill's service adaptation; this script deploys the image as-is.

Values in targets.sagemaker.environment travel into the model definition
(argv + describe-model visible) — never put secrets there.

Generated by the bentoml-deploy-scriptgen skill — do not edit by hand; all
tunables live in deploy.config.json.
"""

