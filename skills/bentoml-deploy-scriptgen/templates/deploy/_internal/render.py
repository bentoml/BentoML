def render_documents(cfg: Config, image: str) -> list[RenderedDoc]:
    """Every object to apply, in rollout order (deepest dependencies first) —
    Deployment, Service, then the optional HPA per service, then the entry
    service's optional Ingress. Deterministic."""
    k8s = cfg.require_k8s()
    docs: list[RenderedDoc] = []
    for svc in k8s.require_bound():
        docs.append(_deployment(cfg, k8s, svc, image))
        docs.append(_service(cfg, k8s, svc))
        if svc.autoscaling.enabled:
            docs.append(_hpa(cfg, k8s, svc))
    entry = k8s.entry_service
    if entry.ingress.enabled:
        docs.append(_ingress(cfg, k8s, entry))
    return docs


def render_all(cfg: Config, image: str) -> str:
    """The full multi-document manifest text piped to `kubectl apply -f -`."""
    return "---\n".join(doc.text for doc in render_documents(cfg, image))


# Files this renderer owns in an output directory. Anything matching one of
# these that we did NOT just write is a leftover from an earlier render (a
# renamed slug, a service that was deleted, autoscaling switched off) — and
# `kubectl apply -f <dir>` would happily re-create the orphan it describes.
_MANAGED_SUFFIXES = ("-deployment.yaml", "-service.yaml", "-hpa.yaml")
_MANAGED_NAMES = ("ingress.yaml",)


def _is_managed(name: str) -> bool:
    return name in _MANAGED_NAMES or name.endswith(_MANAGED_SUFFIXES)


def write_manifests(
    cfg: Config, image: str, out_dir: Path
) -> tuple[list[Path], list[Path]]:
    """Write one file per object into out_dir (created if needed) and return
    (written, removed) — both in a stable order.

    Stale files this renderer previously owned are DELETED rather than left
    behind. Leaving them is not harmless: after a slug rename or a deleted
    service, `kubectl apply -f <dir>` (or a GitOps controller pointed at it)
    re-creates the orphaned Deployment and Service, and the pods it owns keep
    serving. Files this renderer never writes (a hand-added sidecar, a README,
    a kustomization) are left strictly alone — the caller reports them.
    """
    out_dir.mkdir(parents=True, exist_ok=True)
    docs = render_documents(cfg, image)
    expected = {doc.filename for doc in docs}
    removed: list[Path] = []
    for existing in sorted(out_dir.iterdir()):
        if (
            existing.is_file()
            and _is_managed(existing.name)
            and existing.name not in expected
        ):
            existing.unlink()
            removed.append(existing)
    written: list[Path] = []
    for doc in docs:
        path = out_dir / doc.filename
        path.write_text(doc.text, encoding="utf-8")
        written.append(path)
    return written, removed


def unmanaged_files(out_dir: Path) -> list[Path]:
    """Files in out_dir that this renderer does not own (reported, never
    touched): they are applied too when the directory is applied as a whole."""
    if not out_dir.is_dir():
        return []
    return sorted(
        path
        for path in out_dir.iterdir()
        if path.is_file() and not _is_managed(path.name)
    )
