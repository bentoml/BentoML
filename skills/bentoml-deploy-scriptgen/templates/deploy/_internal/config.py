# binding the discovered topology to the config
# --------------------------------------------------------------------------


def bind_topology(cfg: Config, topology: Topology) -> None:
    """Resolve the per-service specs from the DISCOVERED topology plus the
    optional overrides in config.yml, in rollout order.

    This is where the two halves meet, and where the remaining per-service
    validation happens — the checks that need to know which service is the
    entry one, and which names actually exist:

      * an override keyed on a name the bento does not have is exit 2 (typo
        protection) and the message lists the real names;
      * `expose`/`ingress` on a non-entry service is exit 2 (the pickle/RCE
        boundary);
      * a hand-written BENTOML_SERVE_DEPENDS must cover the dependencies the
        bento declares for that service;
      * slugs must be unique DNS-1035 labels.
    """
    k8s = cfg.require_k8s()
    known = topology.names
    unknown = [name for name in k8s.overrides if name not in topology.services]
    if unknown:
        raise _fail(
            f"services.{unknown[0]}",
            f"{unknown[0]!r} is not a service of this bento",
            hint="`services:` holds per-service overrides keyed on the "
            "BentoML service name EXACTLY as the bento declares it. This "
            f"bento ({topology.bento_tag}) has: {known} (entry service: "
            f"{topology.entry_service}). The topology came from "
            f"{topology.detail or topology.source}. Fix the key, or delete the "
            "block — a service with no block gets the defaults.",
        )
    specs: dict[str, ServiceSpec] = {}
    slugs: dict[str, str] = {}
    for name in rollout_order(topology):
        override = k8s.overrides.get(name) or ServiceOverride(name=name)
        path = f"services.{name}"
        entry = name == topology.entry_service
        depends = list(topology.services[name])
        slug = override.slug or _slugify(name)
        if not DNS1035_RE.match(slug):
            raise _fail(
                f"{path}.slug",
                f"{slug!r} is not a valid DNS-1035 label "
                f"(must match {DNS1035_RE.pattern})",
                hint="the slug names deployment/<slug>, svc/<slug> and this "
                "service's in-cluster hostname. It defaults to the BentoML "
                "service name snake_cased with '_' -> '-'; set "
                f"services.{name}.slug explicitly when that is not a legal "
                "label (e.g. a service name starting with a digit).",
            )
        if slug in slugs:
            raise _fail(
                f"{path}.slug",
                f"duplicate slug {slug!r} (already used by services."
                f"{slugs[slug]}) — the two services would share one Deployment "
                "and Service",
                hint=f"set an explicit `slug:` on services.{name}",
            )
        slugs[slug] = name
        if override.env.get("BENTOML_SERVE_DEPENDS") is not None:
            # The raw value REPLACES the derived one, so it gets the same
            # scrutiny the hand-owned-manifests preflight applies — an unwired
            # or misspelled dependency is instantiated IN-PROCESS with no log
            # line, and nothing at deploy time can tell that apart from a
            # working split.
            _check_raw_serve_depends(
                override.env["BENTOML_SERVE_DEPENDS"], depends, path
            )
            warn(
                f"{CONFIG_FILE_NAME}: {path}.env sets BENTOML_SERVE_DEPENDS by "
                "hand, so the value derived from the bento's dependency graph "
                "is NOT emitted — the raw value is what the pod gets (it was "
                "syntax-checked, and every dependency the bento declares is "
                "covered)"
            )
        specs[name] = ServiceSpec(
            name=name,
            slug=slug,
            entry=entry,
            depends=depends,
            replicas=override.replicas,
            resources=override.resources,
            env=override.env,
            env_from_secrets=override.env_from_secrets,
            config_overrides=override.config_overrides,
            node_selector=override.node_selector,
            tolerations=override.tolerations,
            probes=override.probes,
            autoscaling=override.autoscaling,
            expose=_parse_expose(override.expose_raw, path, entry),
            ingress=_parse_ingress(override.ingress_raw, path, entry),
        )
    k8s.services = [specs[name] for name in rollout_order(topology)]
    cfg.topology = topology
