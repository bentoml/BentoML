def _docker_run_command(ec2: Ec2Config, image: str) -> str:
    """The remote command that starts the container. Values for env_names
    arrive via stdin (see the module docstring), so this string never
    contains a secret and is safe to log."""
    parts = [
        "docker",
        "run",
        "-d",
        "--name",
        shlex.quote(ec2.container_name),
        "--restart",
        "unless-stopped",
        "-p",
        f"{ec2.host_port}:3000",
    ]
    for name in ec2.env_names:
        parts += ["-e", name]
    parts.append(shlex.quote(image))
    if not ec2.env_names:
        return "sudo -n " + " ".join(parts)
    preserve = ",".join(ec2.env_names)
    return _ENV_READER + f"exec sudo -n --preserve-env={preserve} " + " ".join(parts)


def _env_payload(ec2: Ec2Config) -> str:
    """The stdin payload consumed by _ENV_READER: one 'NAME <base64>' line
    per variable, values straight from this process's environment."""
    if not ec2.env_names:
        return ""
    lines = []
    for name in ec2.env_names:
        value = os.environ.get(name)
        if not value:  # preflight guarantees presence; guard regardless
            raise DeployError(
                f"env var {name} (ec2.env_names) is missing from the environment",
                EXIT_DEPLOY,
                hint=f"export {name}=... before running",
            )
        encoded = base64.b64encode(value.encode("utf-8")).decode("ascii")
        lines.append(f"{name} {encoded}")
    return "\n".join(lines) + "\n"


def _container_status(ec2: Ec2Config, host: str) -> str:
    """The container's docker status line ('Up 3 seconds', 'Exited (1) ...'),
    or '' if no container with that name exists."""
    res = _ssh_run(
        ec2,
        host,
        "sudo -n docker ps -a --filter {} --format {}".format(
            # docker treats the name filter as a regex — escape the name
            shlex.quote(f"name=^{re.escape(ec2.container_name)}$"),
            shlex.quote("{{.Status}}"),
        ),
        capture=True,
        check=False,
        quiet=True,
        timeout=60,
    )
    first_line = res.stdout.strip().splitlines()[:1]
    return first_line[0].strip() if first_line else ""


def _rollback_guidance(ec2: Ec2Config, host: str) -> str:
    ssh = f"ssh -i {shlex.quote(str(ec2.ssh_key_path))} {ec2.ssh_user}@{host}"
    name = ec2.container_name
    return (
        "Diagnose:\n"
        f"  {ssh} 'sudo docker ps -a --filter name={name}'\n"
        f"  {ssh} 'sudo docker logs --tail 100 {name}'\n"
        "Roll back by redeploying the previous image (docker rm -f already "
        "replaced the old container — on EC2 a rollback IS a redeploy):\n"
        "  python3 deploy/deploy.py --target ec2 --skip-build --image <previous-ref>"
    )


def deploy(ctx: RunContext) -> None:
    ec2 = ctx.cfg.require_ec2()
    image = ctx.image or ""
    section(f"deploy: docker over SSH to {len(ec2.hosts)} host(s) (image={image})")
    token: str | None = None
    registry_host = ""
    if ec2.registry_auth == "ecr-token-over-ssh":
        registry_host, region = _ecr_registry(image)
        log(f"minting ECR token for {registry_host} (region {region})")
        token = run(
            ["aws", "ecr", "get-login-password", "--region", region],
            capture=True,
            quiet=True,
            exit_code=EXIT_DEPLOY,
            secret_output=True,
            timeout=60,
        ).stdout.strip()
    for index, host in enumerate(ec2.hosts):
        started = time.monotonic()
        try:
            _deploy_host(ec2, host, image, token, registry_host)
        except BaseException:
            ctx.summary.record_stage(
                f"ec2.deploy[{host}]", False, time.monotonic() - started
            )
            for later in ec2.hosts[index + 1 :]:
                ctx.summary.record_stage(
                    f"ec2.deploy[{later}]",
                    False,
                    0.0,
                    detail="not attempted (fail-fast after a previous host failed)",
                )
            raise
        ctx.summary.record_stage(
            f"ec2.deploy[{host}]", True, time.monotonic() - started
        )


def _deploy_host(
    ec2: Ec2Config, host: str, image: str, token: str | None, registry_host: str
) -> None:
    section(f"deploy {host}")
    if token is not None:
        log(f">>> on {host}: ECR login (token over the SSH channel's stdin)")
        res = _ssh_run(
            ec2,
            host,
            "sudo -n docker login --username AWS --password-stdin "
            + shlex.quote(registry_host),
            input_text=token,
            capture=True,
            check=False,
            secret_output=True,
            timeout=120,
        )
        if res.returncode != 0:
            # Do NOT embed the remote output: the command consumed the auth
            # token on stdin, so its output must be treated as sensitive
            # (that is what secret_output=True means).
            raise DeployError(
                f"ECR login on {host} failed (exit {res.returncode}); "
                "remote output suppressed — it may contain the auth token. "
                "Re-run the login manually on the host to see the error.",
                EXIT_DEPLOY,
                hint="check SSH access to the host and that the local AWS "
                "identity may call ecr:GetAuthorizationToken",
            )
    log(f">>> on {host}: docker pull")
    pulled = _ssh_run(
        ec2, host, "sudo -n docker pull " + shlex.quote(image), check=False
    )
    if pulled.returncode != 0:
        raise DeployError(
            f"docker pull of {image} on {host} failed (exit {pulled.returncode})",
            EXIT_DEPLOY,
            hint="registry auth is the usual cause: ECR tokens expire after "
            "12 hours ('ecr-token-over-ssh' refreshes them each run; "
            "'preauthed' means YOU keep the instance profile or docker "
            "login working). Also check the repository name, that the tag "
            "exists, and free disk space on the host (df -h /).",
        )
    removed = _ssh_run(
        ec2,
        host,
        "sudo -n docker rm -f " + shlex.quote(ec2.container_name),
        capture=True,
        check=False,
        timeout=120,
    )
    if removed.returncode == 0:
        log(f">>> on {host}: removed existing container {ec2.container_name}")
    log(f">>> on {host}: docker run ({len(ec2.env_names)} env var(s) via stdin)")
    started = _ssh_run(
        ec2,
        host,
        _docker_run_command(ec2, image),
        input_text=_env_payload(ec2),
        capture=True,
        check=False,
        timeout=300,
    )
    if started.returncode != 0:
        raise DeployError(
            f"docker run on {host} failed (exit {started.returncode}): "
            f"{(started.stderr.strip() or started.stdout.strip())[-1000:]}",
            EXIT_DEPLOY,
            hint=_rollback_guidance(ec2, host),
        )
    log(
        "waiting 3s before the status check (a container that crashes right "
        "after start still shows 'Up' at t=0)"
    )
    time.sleep(3)
    status = _container_status(ec2, host)
    if not status.startswith("Up"):
        logs = _ssh_run(
            ec2,
            host,
            "sudo -n docker logs --tail 50 " + shlex.quote(ec2.container_name),
            capture=True,
            check=False,
            timeout=60,
        )
        tail = (logs.stdout.strip() + "\n" + logs.stderr.strip()).strip()[-2000:]
        raise DeployError(
            f"container {ec2.container_name} on {host} is not Up "
            f"(status: {status or 'gone'}); last log lines:\n{tail}",
            EXIT_DEPLOY,
            hint=_rollback_guidance(ec2, host),
        )
    log(f">>> on {host}: container status: {status}")


