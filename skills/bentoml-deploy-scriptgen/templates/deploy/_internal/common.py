"""Shared plumbing: subprocess execution, logging, retry, exit codes, and the
machine-readable run summary.

Generated by the bentoml-deploy-scriptgen skill — do not edit by hand; all
tunables live in config.yml.

Conventions:
- All human-readable progress goes to STDERR. STDOUT carries exactly one line:
  the final JSON summary (so CI can `tail -n 1` it).
- Commands are always argv lists — never a shell string built from config.
"""

# This bundle gets committed into arbitrary user repos; the directive below
# keeps the import layout stable under any repo's ruff/isort configuration.
# isort: skip_file
from __future__ import annotations

import json
import subprocess
import sys
import time
import urllib.error
import urllib.request
from collections.abc import Callable
from collections.abc import Sequence
from dataclasses import dataclass
from dataclasses import field
from typing import Any
from typing import TypeVar

# Exit-code scheme (documented in README.md; stable contract for CI):
EXIT_OK = 0
EXIT_GENERIC = 1
EXIT_CONFIG = 2
EXIT_PREFLIGHT = 3
EXIT_BUILD = 4
EXIT_PUSH = 5
EXIT_DEPLOY = 6
EXIT_VERIFY = 7

EXIT_CODE_NAMES: dict[int, str] = {
    EXIT_OK: "ok",
    EXIT_GENERIC: "generic",
    EXIT_CONFIG: "config",
    EXIT_PREFLIGHT: "preflight",
    EXIT_BUILD: "build",
    EXIT_PUSH: "push",
    EXIT_DEPLOY: "deploy",
    EXIT_VERIFY: "verify",
}

SUMMARY_SCHEMA = "bentoml-deploy-summary/v1"

T = TypeVar("T")


class DeployError(Exception):
    """Fatal error carrying the process exit code and an actionable hint."""

    def __init__(
        self,
        message: str,
        exit_code: int = EXIT_GENERIC,
        hint: str | None = None,
    ) -> None:
        super().__init__(message)
        self.exit_code = exit_code
        self.hint = hint


def log(message: str) -> None:
    print(time.strftime("[%H:%M:%S] ") + message, file=sys.stderr, flush=True)


def warn(message: str) -> None:
    log("WARNING: " + message)


def section(title: str) -> None:
    log("")
    log("=== " + title + " ===")


@dataclass
class RunResult:
    returncode: int
    stdout: str
    stderr: str


def run(
    cmd: Sequence[str],
    *,
    check: bool = True,
    capture: bool = False,
    input_text: str | None = None,
    cwd: str | None = None,
    timeout: float | None = None,
    env: dict[str, str] | None = None,
    exit_code: int = EXIT_GENERIC,
    quiet: bool = False,
    secret_output: bool = False,
) -> RunResult:
    """Run an external command from an argv list.

    capture=False streams the child's output to our stderr (keeping stdout
    clean for the summary line); capture=True returns it in RunResult.
    check=True raises DeployError(exit_code) on non-zero exit.
    secret_output=True prevents captured output from appearing in error text.
    """
    argv = list(cmd)
    if not quiet:
        log("$ " + " ".join(argv))
    try:
        proc = subprocess.run(  # noqa: PLW1510 - returncode handled below
            argv,
            stdout=subprocess.PIPE if capture else sys.stderr,
            stderr=subprocess.PIPE if capture else sys.stderr,
            input=input_text,
            cwd=cwd,
            timeout=timeout,
            env=env,
            text=True,
        )
    except FileNotFoundError:
        raise DeployError(
            "command not found: " + argv[0],
            exit_code,
            hint=f"install '{argv[0]}' and make sure it is on PATH",
        ) from None
    except subprocess.TimeoutExpired:
        raise DeployError(
            "command timed out after {}s: {}".format(timeout, " ".join(argv)),
            exit_code,
        ) from None
    result = RunResult(
        returncode=proc.returncode,
        stdout=proc.stdout or "",
        stderr=proc.stderr or "",
    )
    if check and result.returncode != 0:
        detail = ""
        if capture and not secret_output:
            tail = (result.stderr.strip() or result.stdout.strip())[-2000:]
            if tail:
                detail = "\n" + tail
        joined = " ".join(argv)
        raise DeployError(
            f"command failed (exit {result.returncode}): {joined}{detail}",
            exit_code,
        )
    return result


def retry(
    fn: Callable[[], T],
    *,
    attempts: int = 3,
    delay_seconds: float = 2.0,
    description: str = "operation",
) -> T:
    """Retry fn up to `attempts` times with a fixed delay between tries."""
    last: BaseException | None = None
    for attempt in range(1, attempts + 1):
        try:
            return fn()
        except Exception as exc:  # noqa: BLE001 - deliberate broad retry
            last = exc
            if attempt < attempts:
                warn(
                    f"{description} failed (attempt {attempt}/{attempts}): "
                    f"{exc} — retrying in {delay_seconds:.0f}s"
                )
                time.sleep(delay_seconds)
    assert last is not None
    raise last


