@dataclass
class K8sConfig:
    context: str
    namespace: str
    # Per-service OVERRIDES from config.yml, keyed by BentoML service name.
    overrides: dict[str, ServiceOverride] = field(default_factory=dict)
    # Every BentoML service, in ROLLOUT ORDER — populated by bind_topology()
    # from the DISCOVERED topology, never from config.yml. Empty until then.
    services: list[ServiceSpec] = field(default_factory=list)
    image_pull_secret: str | None = None
    # 900s, deliberately MORE than a pod's startup budget
    # (probes.startup_failure_threshold x periodSeconds 10): with the two
    # equal, a pod that legitimately uses its whole startup budget loses the
    # race and the rollout is reported failed at the moment it succeeds.
    rollout_timeout_seconds: int = 900
    local_port: int = 3130
    extra_labels: dict[str, str] = field(default_factory=dict)
    # ESCAPE HATCH (absolute, resolved) — when set, rendering is skipped and
    # these files are applied as-is instead. None = render from the topology.
    manifests_dir: Path | None = None

    @property
    def bound(self) -> bool:
        return bool(self.services)

    def require_bound(self) -> list[ServiceSpec]:
        if not self.services:
            raise DeployError(
                "the bento's service topology has not been resolved yet",
                EXIT_CONFIG,
                hint="this is a bug in the bundle: bind_topology() must run "
                "before the manifests are rendered. Report it.",
            )
        return self.services

    @property
    def entry_service(self) -> ServiceSpec:
        """The service verify talks to (never a dependency: inter-service
        payloads are pickle and must not leave the cluster)."""
        for svc in self.require_bound():
            if svc.entry:
                return svc
        # Unreachable: the entry service comes from bento.yaml's entry_service,
        # which parse_topology() validated against the service list.
        raise _fail("services", "the discovered topology named no entry service")

    @property
    def dependencies(self) -> list[ServiceSpec]:
        return [svc for svc in self.require_bound() if not svc.entry]


def _parse_k8s(data: dict[str, Any], bundle_dir: Path) -> K8sConfig | None:
    section = _get_dict(data, "kubernetes", "$")
    if section is None:
        return None
    _warn_unknown_keys(
        section,
        [
            "context",
            "namespace",
            "image_pull_secret",
            "rollout_timeout_seconds",
            "local_port",
            "extra_labels",
            "manifests_dir",
        ],
        "kubernetes",
    )
    context = os.environ.get("BENTOML_DEPLOY_K8S_CONTEXT") or _get_str(
        section, "context", "kubernetes", required=True
    )
    namespace = os.environ.get("BENTOML_DEPLOY_K8S_NAMESPACE") or _get_str(
        section, "namespace", "kubernetes", required=True
    )
    if not DNS1123_RE.match(str(namespace)):
        raise _fail(
            "kubernetes.namespace",
            f"{namespace!r} is not a valid namespace name "
            f"(must match {DNS1123_RE.pattern})",
            hint="the namespace is embedded in every rendered dependency URL "
            "(http://<slug>.<namespace>.svc.cluster.local:3000)",
        )
    image_pull_secret = _get_str(section, "image_pull_secret", "kubernetes")
    if image_pull_secret is not None and not DNS1123_RE.match(image_pull_secret):
        raise _fail(
            "kubernetes.image_pull_secret",
            f"{image_pull_secret!r} is not a valid Secret name "
            f"(must match {DNS1123_RE.pattern})",
        )
    local_port = _get_int(section, "local_port", "kubernetes", 3130)
    # local_port + 1 carries the dependency /metrics scrapes during verify.
    if local_port < 1024 or local_port > 65534:
        raise _fail(
            "kubernetes.local_port",
            "must be in 1024..65534",
            hint="verify also uses local_port + 1 (to scrape each "
            "dependency's /metrics), so both must be free",
        )
    manifests_rel = _get_str(section, "manifests_dir", "kubernetes")
    manifests_dir: Path | None = None
    if manifests_rel is not None:
        if not manifests_rel.strip():
            raise _fail(
                "kubernetes.manifests_dir",
                "must not be empty",
                hint="leave it null to render the manifests from the bento's "
                "topology (the normal mode), or name a directory relative to "
                "the directory holding config.yml",
            )
        manifests_dir = (bundle_dir / manifests_rel.strip()).resolve()
        if not manifests_dir.exists():
            raise _fail(
                "kubernetes.manifests_dir",
                f"directory does not exist: {manifests_dir}",
                hint="the path is resolved relative to the directory holding "
                f"{CONFIG_FILE_NAME}. Leave the key null to render the "
                "manifests (the normal mode), or create the directory — "
                "`deploy.py --target k8s --render-only DIR` writes a correct "
                "starting point (unset manifests_dir first).",
            )
        if not manifests_dir.is_dir():
            raise _fail(
                "kubernetes.manifests_dir",
                f"is not a directory: {manifests_dir}",
                hint="it must be a directory of *.yaml manifests, not a single file",
            )
    return K8sConfig(
        context=str(context),
        namespace=str(namespace),
        overrides=_parse_service_overrides(data),
        image_pull_secret=image_pull_secret,
        rollout_timeout_seconds=_get_int(
            section, "rollout_timeout_seconds", "kubernetes", 900
        ),
        local_port=local_port,
        extra_labels=_check_extra_labels(
            _get_str_map(section, "extra_labels", "kubernetes")
        ),
        manifests_dir=manifests_dir,
    )


# The four labels the renderer owns: the selector matches on `name`, so a
# user-supplied override would produce a Deployment whose selector and pod
# template disagree (the API server rejects it, and client dry-run does not
# catch it). The renderer therefore always wins — but a silently discarded
# value is exactly the "knob that does nothing" this loader warns about
# everywhere else, so say so.
_OWNED_LABELS = (
    "app.kubernetes.io/name",
    "app.kubernetes.io/component",
    "app.kubernetes.io/part-of",
    "app.kubernetes.io/managed-by",
)


def _check_extra_labels(labels: dict[str, str]) -> dict[str, str]:
    clashes = [key for key in _OWNED_LABELS if key in labels]
    if clashes:
        warn(
            "kubernetes.extra_labels: "
            + ", ".join(clashes)
            + " is set by the renderer and your value is ignored "
            "(the pod selector matches on app.kubernetes.io/name, so an "
            "override would make the Deployment unappliable). Remove it."
        )
    return labels


