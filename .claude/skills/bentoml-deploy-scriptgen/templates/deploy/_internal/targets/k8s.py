def preflight(ctx: RunContext) -> None:
    """Standalone entry point: run this target's checks in one pass."""
    run_checks(preflight_checks(ctx))


def preflight_checks(ctx: RunContext) -> list:
    """Build this target's checks so deploy.py can aggregate them with the
    build-side families into a single report. With ctx.local_only, only
    checks that need no cluster connectivity are returned; the rest are
    recorded in the summary's skipped list."""
    k8s = ctx.cfg.require_k8s()

    def kubectl_cli() -> str | None:
        _which("kubectl", "install kubectl and configure access to the cluster")
        return None

    def context_reachable() -> str | None:
        res = run(
            _kubectl(k8s, "version", "--request-timeout=10s", "-o", "yaml"),
            capture=True,
            quiet=True,
            check=False,
            timeout=30,
        )
        if res.returncode != 0:
            raise CheckFailed(
                f"cluster for context {k8s.context!r} is not reachable: {(res.stderr.strip() or res.stdout.strip())[:300]}",
                hint="check the context name (kubectl config get-contexts), "
                "VPN/credentials, and that the cluster is up",
            )
        return f"context {k8s.context} reachable"

    def rbac() -> str | None:
        res = run(
            _kubectl(k8s, "auth", "can-i", "create", "deployment", "-n", k8s.namespace),
            capture=True,
            quiet=True,
            check=False,
            timeout=30,
        )
        if res.stdout.strip().lower() != "yes":
            raise CheckFailed(
                f"identity for context {k8s.context!r} may not create deployments in "
                f"namespace {k8s.namespace!r}",
                hint="ask a cluster admin for edit rights in the namespace, "
                "or fix targets.k8s.namespace",
            )
        return None

    def namespace_exists() -> str | None:
        res = run(
            _kubectl(k8s, "get", "namespace", k8s.namespace),
            capture=True,
            quiet=True,
            check=False,
            timeout=30,
        )
        if res.returncode != 0:
            raise CheckFailed(
                f"namespace {k8s.namespace!r} does not exist in context {k8s.context!r}",
                hint=f"kubectl --context {k8s.context} create namespace {k8s.namespace}",
            )
        return None

    def pull_secret() -> str | None:
        if not k8s.image_pull_secret:
            return "no image pull secret configured"
        res = run(
            _kubectl(
                k8s,
                "get",
                "secret",
                k8s.image_pull_secret,
                "-n",
                k8s.namespace,
                "-o",
                "jsonpath={.metadata.creationTimestamp}",
            ),
            capture=True,
            quiet=True,
            check=False,
            timeout=30,
        )
        if res.returncode != 0:
            raise CheckFailed(
                f"image pull secret {k8s.image_pull_secret!r} not found in namespace {k8s.namespace!r}",
                hint=f"kubectl --context {k8s.context} create secret docker-registry {k8s.image_pull_secret} "
                f"-n {k8s.namespace} --docker-server=... --docker-username=... "
                "--docker-password=...",
            )
        if ctx.cfg.image.registry_type == "ecr":
            created = parse_k8s_timestamp(res.stdout)
            if created is not None:
                age = datetime.now(timezone.utc) - created
                if age > ECR_PULL_SECRET_MAX_AGE:
                    warn(
                        f"ECR pull secret {k8s.image_pull_secret!r} is {age.total_seconds() / 3600:.1f} h old — ECR tokens expire "
                        "after 12 h, so image pulls will likely fail. "
                        "Delete and recreate the secret with a fresh "
                        "'aws ecr get-login-password' (kubectl apply keeps "
                        "the original creationTimestamp, so recreating is "
                        "the only way this check can see it as fresh). Note "
                        "this age check is a heuristic: it cannot detect a "
                        "recently created secret that embeds an "
                        "already-expired token."
                    )
        return None

    def manifests_present() -> str | None:
        files = _manifest_files(k8s)
        if not files:
            raise CheckFailed(
                f"no *.yaml manifests found in {k8s.manifests_dir}",
                hint="regenerate the bundle with the bentoml-deploy-scriptgen skill",
            )
        combined = "\n".join(f.read_text(encoding="utf-8") for f in files)
        if IMAGE_SENTINEL not in combined:
            raise CheckFailed(
                f"image sentinel {IMAGE_SENTINEL!r} not found in any manifest under {k8s.manifests_dir}",
                hint="the Deployment's image: line must be exactly the "
                "sentinel; regenerate the bundle with the skill",
            )
        if PLACEHOLDER_RE.search(combined):
            raise CheckFailed(
                f"unreplaced {{{{PLACEHOLDER}}}} values remain in {k8s.manifests_dir}",
                hint="regenerate the bundle with the bentoml-deploy-scriptgen skill",
            )
        declared = set(
            re.findall(
                r"^\s*namespace:\s*([A-Za-z0-9._-]+)\s*$", combined, re.MULTILINE
            )
        )
        wrong = sorted(declared - {k8s.namespace})
        if wrong:
            raise CheckFailed(
                f"manifests under {k8s.manifests_dir} declare namespace(s) "
                f"{wrong} but targets.k8s.namespace is {k8s.namespace!r}",
                hint="regenerate the manifests, or fix targets.k8s.namespace "
                "in deploy.config.json — deploying across namespaces would "
                "roll out in one place and verify another",
            )
        if k8s.node_port is not None:
            node_port_line = f"nodePort: {k8s.node_port}"
            if node_port_line not in combined:
                raise CheckFailed(
                    f"targets.k8s.node_port is {k8s.node_port} but no "
                    f"'{node_port_line}' line exists in the Service manifest",
                    hint="regenerate the manifests with the skill, or align "
                    "node_port with the manifest (unset it to let the "
                    "cluster keep its current allocation)",
                )
        return f"{len(files)} manifest file(s)"

    checks = [("k8s.kubectl-cli", kubectl_cli)]
    if ctx.local_only:
        ctx.summary.skipped += [
            "k8s.context-reachable (--local-only)",
            "k8s.rbac-create-deployment (--local-only)",
            "k8s.namespace (--local-only)",
            "k8s.image-pull-secret (--local-only)",
        ]
    else:
        checks += [
            ("k8s.context-reachable", context_reachable),
            ("k8s.rbac-create-deployment", rbac),
            ("k8s.namespace", namespace_exists),
            ("k8s.image-pull-secret", pull_secret),
        ]
    checks.append(("k8s.manifests", manifests_present))
    return checks


