@dataclass
class ResourcesConfig:
    requests: dict[str, str] = field(default_factory=lambda: dict(DEFAULT_REQUESTS))
    limits: dict[str, str] = field(default_factory=lambda: dict(DEFAULT_LIMITS))


@dataclass
class ProbesConfig:
    startup_failure_threshold: int = 60
    readiness_timeout_seconds: int = READINESS_TIMEOUT_FLOOR


@dataclass
class AutoscalingConfig:
    enabled: bool = False
    min_replicas: int = 1
    max_replicas: int = 5
    metric: str = "cpu"  # one of AUTOSCALING_METRICS
    target: int = 70


@dataclass
class ExposeConfig:
    type: str = "ClusterIP"  # one of SERVICE_TYPES
    node_port: int | None = None
    annotations: dict[str, str] = field(default_factory=dict)


@dataclass
class IngressConfig:
    enabled: bool = False
    class_name: str = "nginx"
    host: str = ""
    tls_secret: str | None = None
    annotations: dict[str, str] = field(default_factory=dict)


@dataclass
class ServiceOverride:
    """The optional `services.<Name>:` block — overrides only.

    Nothing in here describes the bento's SHAPE: the service list, the entry
    service and the dependency DAG come from bento.yaml. `expose` and `ingress`
    are kept unparsed until bind_topology() knows which service is the entry
    one (they are legal on that one only)."""

    name: str
    slug: str | None = None
    replicas: int = 1
    resources: ResourcesConfig = field(default_factory=ResourcesConfig)
    env: dict[str, str] = field(default_factory=dict)
    env_from_secrets: list[str] = field(default_factory=list)
    config_overrides: dict[str, Any] = field(default_factory=dict)
    node_selector: dict[str, str] = field(default_factory=dict)
    tolerations: list[dict[str, Any]] = field(default_factory=list)
    probes: ProbesConfig = field(default_factory=ProbesConfig)
    autoscaling: AutoscalingConfig = field(default_factory=AutoscalingConfig)
    expose_raw: dict[str, Any] | None = None
    ingress_raw: dict[str, Any] | None = None


@dataclass
class ServiceSpec:
    """One BentoML service == one Kubernetes Deployment + Service (+ optional
    HPA, + optional Ingress for the entry service).

    Built by bind_topology() from the discovered topology plus the (optional)
    per-service overrides — never from config alone."""

    # BentoML service name as the bento declares it (e.g. "Summarizer") — what
    # the rendered manifests pass to --service-name and use as the
    # BENTOML_SERVE_DEPENDS key.
    name: str
    # DNS-1035 object-name stem: names deployment/<slug>, svc/<slug>, the HPA,
    # and the service's in-cluster hostname.
    slug: str
    # bento.yaml's entry_service: the only one that may carry expose/ingress
    # and the only one verify targets.
    entry: bool = False
    # Direct dependencies, from bento.yaml's services[].dependencies.
    depends: list[str] = field(default_factory=list)
    replicas: int = 1
    resources: ResourcesConfig = field(default_factory=ResourcesConfig)
    env: dict[str, str] = field(default_factory=dict)
    env_from_secrets: list[str] = field(default_factory=list)
    config_overrides: dict[str, Any] = field(default_factory=dict)
    node_selector: dict[str, str] = field(default_factory=dict)
    tolerations: list[dict[str, Any]] = field(default_factory=list)
    probes: ProbesConfig = field(default_factory=ProbesConfig)
    autoscaling: AutoscalingConfig = field(default_factory=AutoscalingConfig)
    expose: ExposeConfig = field(default_factory=ExposeConfig)
    ingress: IngressConfig = field(default_factory=IngressConfig)


