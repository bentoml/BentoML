def verify(ctx: RunContext) -> None:
    sm = ctx.cfg.require_sagemaker()
    inference = ctx.cfg.verify.inference
    section(f"verify: invoke-endpoint on {sm.endpoint_name} (region {sm.region})")
    if inference is None:
        endpoint = _describe_endpoint(sm, exit_code=EXIT_VERIFY) or {}
        status = endpoint.get("EndpointStatus", "absent")
        if status != "InService":
            raise DeployError(
                f"endpoint {sm.endpoint_name} is not InService (status: {status})",
                EXIT_VERIFY,
                hint=_failure_guidance(sm, None),
            )
        log(
            "no inference smoke test configured (verify.inference) — "
            "endpoint is InService, skipping invoke"
        )
        return
    _invoke_smoke(sm, inference)


def _invoke_smoke(sm: SageMakerConfig, inference: InferenceCheck) -> None:
    if inference.path != "/invocations":
        warn(
            f"verify.inference.path is {inference.path!r}, but SageMaker "
            "always invokes POST /invocations — the configured path is "
            "ignored for this target"
        )
    log("inference smoke test: sagemaker-runtime invoke-endpoint")
    body_file = tempfile.NamedTemporaryFile(  # noqa: SIM115 - closed in finally
        mode="w",
        prefix="bentoml-deploy-sm-body-",
        suffix=".json",
        delete=False,
        encoding="utf-8",
    )
    out_path = body_file.name + ".out"
    try:
        json.dump(inference.body, body_file)
        body_file.close()
        res = run(
            [
                "aws",
                "sagemaker-runtime",
                "invoke-endpoint",
                "--endpoint-name",
                sm.endpoint_name,
                "--content-type",
                "application/json",
                "--accept",
                "application/json",
                "--cli-binary-format",
                "raw-in-base64-out",
                "--body",
                f"fileb://{body_file.name}",
                "--region",
                sm.region,
                "--output",
                "json",
                out_path,
            ],
            capture=True,
            check=False,
            timeout=inference.timeout_seconds + 30,
        )
        if res.returncode != 0:
            err = res.stderr.strip() or res.stdout.strip()
            raise DeployError(
                f"invoke-endpoint failed (exit {res.returncode}): {err[-800:]}",
                EXIT_VERIFY,
                hint="a ModelError (424) means the container returned "
                "4xx/5xx — check the payload against the /invocations "
                "signature, and read the container logs: aws logs tail "
                f'"/aws/sagemaker/Endpoints/{sm.endpoint_name}" '
                f"--region {sm.region} --since 1h. Platform limits: 60 s "
                "per request, 6 MB bodies.",
            )
        try:
            metadata = json.loads(res.stdout)
        except json.JSONDecodeError:
            metadata = {}
        content_type = str(metadata.get("ContentType", ""))
        try:
            body = Path(out_path).read_text(encoding="utf-8", errors="replace")
        except OSError:
            body = ""
        snippet = body[:500].replace("\n", " ")
        log(f"response ContentType {content_type or '(missing)'}: {snippet}")
        if not content_type:
            raise DeployError(
                "invoke-endpoint reported no response ContentType",
                EXIT_VERIFY,
                hint="the container's /invocations response is malformed — "
                "read the CloudWatch logs (log group "
                f"/aws/sagemaker/Endpoints/{sm.endpoint_name})",
            )
        if "json" in content_type.lower():
            try:
                json.loads(body)
            except json.JSONDecodeError:
                raise DeployError(
                    f"response declares ContentType {content_type!r} but the "
                    f"body is not valid JSON (body: {snippet})",
                    EXIT_VERIFY,
                ) from None
        if inference.expect_substring and inference.expect_substring not in body:
            raise DeployError(
                "inference response did not contain expected substring "
                f"{inference.expect_substring!r} (body: {snippet})",
                EXIT_VERIFY,
            )
        log("inference smoke test passed")
    finally:
        body_file.close()
        for path in (body_file.name, out_path):
            try:
                Path(path).unlink()
            except OSError:
                pass
