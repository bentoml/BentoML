@dataclass
class Config:
    bundle_dir: Path  # directory containing config.yml
    project: ProjectConfig = field(default_factory=lambda: ProjectConfig(Path(".")))
    image: ImageConfig = field(default_factory=ImageConfig)
    verify: VerifyConfig = field(default_factory=VerifyConfig)
    k8s: K8sConfig | None = None
    ec2: Ec2Config | None = None

    def require_k8s(self) -> K8sConfig:
        if self.k8s is None:
            raise _fail(
                "kubernetes",
                "no kubernetes target configured",
                hint="regenerate the bundle with the bentoml-deploy-scriptgen "
                "skill and include the k8s target (config.yml needs both a "
                "`kubernetes:` section and a `services:` section)",
            )
        return self.k8s

    def require_ec2(self) -> Ec2Config:
        if self.ec2 is None:
            raise _fail(
                "ec2",
                "no ec2 target configured",
                hint="regenerate the bundle with the bentoml-deploy-scriptgen "
                "skill and include the ec2 target",
            )
        return self.ec2


def _parse_project(data: dict[str, Any], bundle_dir: Path) -> ProjectConfig:
    section = _get_dict(data, "project", "$") or {}
    _warn_unknown_keys(section, ["dir", "service", "name"], "project")
    rel = _get_str(section, "dir", "project", default="..") or ".."
    project_dir = (bundle_dir / rel).resolve()
    if not project_dir.is_dir():
        raise _fail(
            "project.dir",
            f"directory does not exist: {project_dir}",
            hint="project.dir is resolved relative to the directory that "
            "holds config.yml (deploy/ in this bundle)",
        )
    return ProjectConfig(
        dir=project_dir,
        service=_get_str(section, "service", "project"),
        name=_get_str(section, "name", "project", default="bentoml-service")
        or "bentoml-service",
    )


def _parse_image(data: dict[str, Any]) -> ImageConfig:
    section = _get_dict(data, "image", "$") or {}
    _warn_unknown_keys(
        section,
        [
            "registry",
            "repository",
            "registry_type",
            "platform",
            "ecr_region",
            "local_image_preloaded",
        ],
        "image",
    )
    registry = (_get_str(section, "registry", "image", default="") or "").rstrip("/")
    registry_type = (
        _get_str(section, "registry_type", "image", default="generic") or "generic"
    )
    if registry_type not in REGISTRY_TYPES:
        raise _fail(
            "image.registry_type",
            f"{registry_type!r} is not one of {list(REGISTRY_TYPES)}",
        )
    ecr_region = _get_str(section, "ecr_region", "image")
    if registry_type == "ecr" and not ecr_region:
        match = ECR_HOST_RE.match(registry)
        if match:
            ecr_region = match.group("region")
        else:
            raise _fail(
                "image.ecr_region",
                "registry_type is 'ecr' but the region could not be derived "
                f"from image.registry ({registry!r})",
                hint='set image.ecr_region explicitly, e.g. "us-west-1"',
            )
    local_image_preloaded = _get_bool(section, "local_image_preloaded", "image", False)
    if registry_type == "none" and not local_image_preloaded:
        raise _fail(
            "image.local_image_preloaded",
            "must be true when image.registry_type is 'none'",
            hint="registry_type 'none' pushes nothing, so the image must "
            "already be on the cluster nodes: load it (minikube image load "
            "<image> / kind load docker-image <image> --name <cluster>) and "
            "set image.local_image_preloaded: true to acknowledge. Otherwise "
            "the rollout dies in ImagePullBackOff after burning the whole "
            "rollout timeout.",
        )
    platform = _get_str(section, "platform", "image")
    if platform and not platform.startswith("linux/"):
        raise _fail("image.platform", f'expected e.g. "linux/amd64", got {platform!r}')
    return ImageConfig(
        registry=registry,
        repository=_get_str(section, "repository", "image", default="") or "",
        registry_type=registry_type,
        platform=platform,
        ecr_region=ecr_region,
        local_image_preloaded=local_image_preloaded,
    )


def _parse_verify(data: dict[str, Any]) -> VerifyConfig:
    section = _get_dict(data, "verify", "$") or {}
    _warn_unknown_keys(
        section,
        ["readyz_timeout_seconds", "inference", "dependency_metrics"],
        "verify",
    )
    inference: InferenceCheck | None = None
    inf = _get_dict(section, "inference", "verify")
    if inf is not None:
        _warn_unknown_keys(
            inf,
            ["path", "body", "expect_substring", "timeout_seconds"],
            "verify.inference",
        )
        path = _get_str(inf, "path", "verify.inference", required=True) or ""
        if not path.startswith("/"):
            raise _fail("verify.inference.path", "must start with '/'")
        if "body" not in inf:
            raise _fail(
                "verify.inference.body",
                "required value is missing",
                hint="the request body as native YAML, e.g.\n"
                '    body:\n      text: "a great day"',
            )
        _require_json_serializable(
            inf["body"],
            "verify.inference.body",
            "and POSTed to the entry service during verification — which "
            "happens AFTER the cluster has been changed, so a body that "
            "cannot be serialized would fail the run at its very last step",
        )
        inference = InferenceCheck(
            path=path,
            body=inf["body"],
            expect_substring=_get_str(inf, "expect_substring", "verify.inference"),
            timeout_seconds=_get_int(inf, "timeout_seconds", "verify.inference", 60),
        )
    return VerifyConfig(
        readyz_timeout_seconds=_get_int(
            section, "readyz_timeout_seconds", "verify", 600
        ),
        inference=inference,
        dependency_metrics=_get_bool(section, "dependency_metrics", "verify", True),
    )


