def build_bento(cfg: Config, version: str) -> str:
    """`bentoml build --version <tag> -o tag` from the project root; returns
    the bento tag parsed from the `__tag__:` line."""
    cmd = ["bentoml", "build"]
    if cfg.project.service:
        cmd.append(cfg.project.service)
    cmd += ["--version", version, "-o", "tag"]
    res = run(
        cmd, cwd=str(cfg.project.dir), capture=True, check=False, exit_code=EXIT_BUILD
    )
    bento_tag = ""
    for line in res.stdout.splitlines():
        if line.startswith("__tag__:"):
            bento_tag = line[len("__tag__:") :].strip()
    if res.returncode != 0 or not bento_tag:
        output = res.stderr.strip() or res.stdout.strip()
        # Idempotent re-run at the same version tag: the bento is already in
        # the local store — reuse it instead of failing (CI retries and
        # "redeploy head" both hit this).
        exists = re.search(r"Item '([^']+)' already exists in the store", output)
        if exists:
            bento_tag = exists.group(1)
            log(f"bento {bento_tag} already built for this version — reusing it")
            return bento_tag
        raise DeployError(
            f"bentoml build failed (exit {res.returncode}):\n{output[-3000:]}",
            EXIT_BUILD,
            hint="common causes: project.service does not match the "
            "module:Class in service.py, a missing python package, or a "
            "model download failure (gated HF models need HF_TOKEN "
            "exported)",
        )
    log(f"built bento: {bento_tag}")
    return bento_tag


def containerize(cfg: Config, bento_tag: str, image: str) -> None:
    cmd = ["bentoml", "containerize", bento_tag, "-t", image]
    if cfg.image.platform:
        cmd += ["--opt", f"platform={cfg.image.platform}"]
    run(cmd, cwd=str(cfg.project.dir), exit_code=EXIT_BUILD)
    log(f"containerized: {image}")


def push_image(cfg: Config, image: str) -> None:
    if cfg.image.registry_type == "none":
        warn(
            "image.registry_type is 'none' — nothing is pushed. Load the "
            "image into your local cluster yourself (e.g. "
            f"`minikube image load {image}` or `kind load docker-image {image}`)."
        )
        return
    if cfg.image.registry_type == "ecr":
        _ecr_login_and_ensure_repo(cfg)
    run(["docker", "push", image], exit_code=EXIT_PUSH)
    log(f"pushed: {image}")


def _ecr_login_and_ensure_repo(cfg: Config) -> None:
    region = cfg.image.ecr_region or ""
    token = run(
        ["aws", "ecr", "get-login-password", "--region", region],
        capture=True,
        quiet=True,
        exit_code=EXIT_PUSH,
        secret_output=True,
    ).stdout.strip()
    run(
        [
            "docker",
            "login",
            "--username",
            "AWS",
            "--password-stdin",
            cfg.image.registry,
        ],
        input_text=token,
        capture=True,
        exit_code=EXIT_PUSH,
        secret_output=True,
        quiet=True,
    )
    log(f"docker login to {cfg.image.registry} ok")
    # ECR requires the repository to exist before pushing; create only if
    # missing so permission/name errors surface here, not at push time.
    described = run(
        [
            "aws",
            "ecr",
            "describe-repositories",
            "--repository-names",
            cfg.image.repository,
            "--region",
            region,
        ],
        capture=True,
        quiet=True,
        check=False,
    )
    if described.returncode != 0:
        run(
            [
                "aws",
                "ecr",
                "create-repository",
                "--repository-name",
                cfg.image.repository,
                "--region",
                region,
            ],
            capture=True,
            exit_code=EXIT_PUSH,
        )
        log(f"created ECR repository {cfg.image.repository}")


