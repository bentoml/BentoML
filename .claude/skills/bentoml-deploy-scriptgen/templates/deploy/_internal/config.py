CONFIG_SCHEMA = "bentoml-deploy-config/v3"
CONFIG_FILE_NAME = "config.yml"
# v1/v2 lived in deploy.config.json: v1 named a single Deployment/Service, v2
# carried a targets.k8s.services list next to hand-owned manifests. v3 replaces
# both with this single YAML file from which the manifests are rendered, so an
# old config is rejected with instructions instead of migrated in place.
LEGACY_SCHEMAS = ("bentoml-deploy-config/v1", "bentoml-deploy-config/v2")
LEGACY_CONFIG_FILE_NAME = "deploy.config.json"

REGISTRY_TYPES = ("generic", "ecr", "none")

EC2_REGISTRY_AUTH_METHODS = ("ecr-token-over-ssh", "preauthed")
EC2_VERIFY_MODES = ("tunnel", "direct")

SERVICE_TYPES = ("ClusterIP", "NodePort", "LoadBalancer")
AUTOSCALING_METRICS = ("cpu", "concurrency")

# When BentoML fans /readyz out to a dependency it gives that dependency a
# HARD-CODED 5s budget, so /readyz can legitimately take just over 5s. A
# kubelet timeout below that hangs up first and leaves the pod permanently
# unready. The 5s is a framework constant, not a tunable (runner_probe.timeout
# is inert on BentoML 1.2+).
READINESS_TIMEOUT_FLOOR = 6

ECR_HOST_RE = re.compile(r"^\d{12}\.dkr\.ecr\.(?P<region>[a-z0-9-]+)\.amazonaws\.com$")

# Names in ec2.env_names travel into remote command lines (as names only —
# never values), so they must be shell-inert by construction.
ENV_NAME_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")

# Docker's own container-name rule; shell-inert for the same reason.
CONTAINER_NAME_RE = re.compile(r"^[a-zA-Z0-9][a-zA-Z0-9_.-]*$")

# Kubernetes object names that end up in a Service name must be DNS-1035
# labels (stricter than DNS-1123: no leading digit). Every per-service slug
# names both a Deployment and a Service, so all slugs follow this rule.
DNS1035_RE = re.compile(r"^[a-z]([-a-z0-9]*[a-z0-9])?$")

# Namespaces, Secret names and ingress classes are DNS-1123 labels.
DNS1123_RE = re.compile(r"^[a-z0-9]([-a-z0-9]*[a-z0-9])?$")

# BentoML service names travel into the rendered whitespace-separated
# BENTOML_SERVE_DEPENDS value and into `--service-name`, so a name with
# whitespace in it could never be addressed at all.
SERVICE_NAME_RE = re.compile(r"^\S+$")

# Kubernetes quantities: "100m", "512Mi", "1", "1.5", "2Gi", "1e3".
QUANTITY_RE = re.compile(
    r"^\+?(?:[0-9]+|[0-9]*\.[0-9]+)(?:[eE][-+]?[0-9]+)?"
    r"(?:m|k|M|G|T|P|E|Ki|Mi|Gi|Ti|Pi|Ei)?$"
)

# Real generator placeholders look like {{SERVICE_NAME}} or {{EC2_HOST}} —
# digits included ({{K8S_CONTEXT}}!) — but this pattern must not fire on
# legitimate braces in user-provided values.
PLACEHOLDER_RE = re.compile(r"\{\{[A-Z][A-Z0-9_]*\}\}")


def _yaml_path(node_path: list[str]) -> str:
    """Render a node path for messages: ["services", "Gateway"] -> the config
    path users see in every other error."""
    return ".".join(node_path) if node_path else "$"


def _check_duplicate_keys(text: str, config_path: Path) -> None:
    """Reject duplicate mapping keys, which YAML resolves LAST-WINS in silence.

    Two `Gateway:` blocks (or two `depends:` keys inside one) would otherwise
    leave one of them with no effect at all: the config on disk says one thing
    and the rendered manifests another. PyYAML's safe_load never complains, so
    the document is walked as a node graph — which also gives the exact path
    and both line numbers.
    """
    try:
        root = yaml.compose(text, Loader=yaml.SafeLoader)
    except RecursionError:
        raise _too_deep(config_path) from None
    except yaml.YAMLError:
        # Not our error to report: the safe_load below raises with a better
        # message (and compose additionally rejects multi-document input).
        return
    if root is None:
        return

    def walk(node: Any, path: list[str]) -> None:
        if isinstance(node, yaml.MappingNode):
            seen: dict[str, Any] = {}
            for key_node, value_node in node.value:
                name = str(getattr(key_node, "value", key_node))
                if name in seen:
                    first = seen[name].start_mark.line + 1
                    dup = key_node.start_mark.line + 1
                    raise _fail(
                        _yaml_path([*path, name]),
                        f"duplicate key (line {dup}; first defined at line {first})",
                        hint="YAML keeps only the LAST of two identical keys, "
                        "silently — so half of what this file says would have "
                        "no effect. Merge the two blocks, or rename one (two "
                        "services must have two different names).",
                    )
                seen[name] = key_node
                walk(value_node, [*path, name])
        elif isinstance(node, yaml.SequenceNode):
            for index, item in enumerate(node.value):
                if path:
                    walk(item, [*path[:-1], f"{path[-1]}[{index}]"])
                else:
                    walk(item, [f"[{index}]"])

    walk(root, [])


def _scan_placeholders(value: Any, path: str) -> str | None:
    """Path of the first unreplaced {{PLACEHOLDER}}, keys included.

    Walks the data instead of serializing it: a config can legitimately hold
    values json.dumps refuses (a YAML date as a mapping key), and that must not
    turn into an internal error.
    """
    if isinstance(value, dict):
        for key, item in value.items():
            if isinstance(key, str) and PLACEHOLDER_RE.search(key):
                return f"{path}.{key}"
            found = _scan_placeholders(item, f"{path}.{key}")
            if found is not None:
                return found
        return None
    if isinstance(value, (list, tuple)):
        for index, item in enumerate(value):
            found = _scan_placeholders(item, f"{path}[{index}]")
            if found is not None:
                return found
        return None
    if isinstance(value, str) and PLACEHOLDER_RE.search(value):
        return path
    return None


def _require_json_serializable(value: Any, path: str, purpose: str) -> None:
    """Reject a value that cannot survive the trip this bundle puts it through.

    Everything checked here is json.dumps'd LATER — the smoke-test body when it
    is POSTed (after the cluster was already mutated), config_overrides when the
    manifests are rendered — and json.dumps rejects more than YAML accepts: a
    date, a datetime, a tuple key, a set. Failing here makes it a config error
    with a path instead of a mid-deploy traceback.
    """
    try:
        json.dumps(value)
    except RecursionError:
        raise _fail(
            path,
            "is nested too deeply to serialize",
            hint="flatten it; this value is serialized to JSON " + purpose,
        ) from None
    except (TypeError, ValueError) as exc:
        raise _fail(
            path,
            f"cannot be serialized to JSON ({exc})",
            hint="this value is serialized to JSON " + purpose + ". YAML "
            "accepts more than JSON does: an unquoted date (2024-01-01), a "
            "timestamp, or a complex mapping key all parse here and fail "
            'there. Quote them — "2024-01-01" — or use plain strings, '
            "numbers, booleans, lists and string-keyed mappings.",
        ) from None


def _too_deep(config_path: Path) -> DeployError:
    return DeployError(
        f"config file is nested too deeply to parse ({config_path})",
        EXIT_CONFIG,
        hint="Python hit its recursion limit while reading this YAML — the "
        "document nests thousands of levels deep. Flatten it (a real "
        "deployment config is a handful of levels).",
    )


def _fail(path: str, message: str, hint: str | None = None) -> DeployError:
    return DeployError(
        f"invalid {CONFIG_FILE_NAME} — {path}: {message}",
        EXIT_CONFIG,
        hint=hint,
    )


def _expect_type(value: Any, types: tuple, path: str, type_name: str) -> Any:
    if not isinstance(value, types) or isinstance(value, bool) and bool not in types:
        raise _fail(path, f"expected {type_name}, got {value!r}")
    return value


def _get_str(
    d: dict[str, Any],
    key: str,
    path: str,
    *,
    required: bool = False,
    default: str | None = None,
) -> str | None:
    if key not in d or d[key] is None:
        if required:
            raise _fail(f"{path}.{key}", "required value is missing")
        return default
    value = _expect_type(d[key], (str,), f"{path}.{key}", "a string")
    if required and not value.strip():
        raise _fail(f"{path}.{key}", "must not be empty")
    return value


def _get_int(d: dict[str, Any], key: str, path: str, default: int) -> int:
    if key not in d or d[key] is None:
        return default
    value = _expect_type(d[key], (int,), f"{path}.{key}", "an integer")
    if value <= 0:
        raise _fail(f"{path}.{key}", "must be a positive integer")
    return int(value)


def _get_bool(d: dict[str, Any], key: str, path: str, default: bool) -> bool:
    if key not in d or d[key] is None:
        return default
    value = d[key]
    if not isinstance(value, bool):
        raise _fail(f"{path}.{key}", f"expected true or false, got {value!r}")
    return value


def _get_dict(d: dict[str, Any], key: str, path: str) -> dict[str, Any] | None:
    if key not in d or d[key] is None:
        return None
    return _expect_type(d[key], (dict,), f"{path}.{key}", "a mapping")


def _get_list(d: dict[str, Any], key: str, path: str) -> list[Any]:
    if key not in d or d[key] is None:
        return []
    return list(_expect_type(d[key], (list,), f"{path}.{key}", "a list"))


def _get_str_map(d: dict[str, Any], key: str, path: str) -> dict[str, str]:
    """A mapping of string keys to STRING values (labels, env, node selectors,
    annotations). Non-string values are rejected rather than coerced: an
    unquoted `1` or `true` in Kubernetes YAML is a different type than the API
    server stores, so every later apply reports a spurious change."""
    raw = _get_dict(d, key, path)
    if raw is None:
        return {}
    out: dict[str, str] = {}
    for name, value in raw.items():
        item_path = f"{path}.{key}.{name}"
        if not isinstance(name, str):
            raise _fail(f"{path}.{key}", f"key {name!r} must be a string")
        if not isinstance(value, str):
            raise _fail(
                item_path,
                f"expected a quoted string, got {value!r}",
                hint="quote the value: Kubernetes stores these as strings, so "
                "an unquoted number or boolean makes every `kubectl apply` "
                'report "configured" and `kubectl diff` lie',
            )
        out[name] = value
    return out


def _warn_unknown_keys(d: dict[str, Any], known: list[str], path: str) -> None:
    for key in d:
        if key not in known:
            warn(f"{CONFIG_FILE_NAME}: unknown key {path}.{key} (typo?)")


def _slugify(name: str) -> str:
    """Default slug: the service name snake_cased, then '_' -> '-'."""
    stepped = re.sub(r"(.)([A-Z][a-z]+)", r"\1_\2", name)
    stepped = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", stepped)
    return stepped.lower().replace("_", "-")


