# Remote reader for the env payload (one "NAME <base64>" line per variable
# on stdin). The `&& printf x` / ${...%x} pair preserves trailing newlines
# that the shell's command substitution would otherwise strip; a value that
# fails to decode aborts with exit 78 before docker run starts.
_ENV_READER = (
    "while IFS=' ' read -r __n __b; do "
    '__v=$(printf %s "$__b" | base64 -d && printf x) || exit 78; '
    'export "$__n=${__v%x}"; '
    "done; "
)


def _ssh_base(ec2: Ec2Config) -> list[str]:
    return [
        "ssh",
        "-i",
        str(ec2.ssh_key_path),
        "-o",
        "StrictHostKeyChecking=accept-new",
        "-o",
        "BatchMode=yes",
        "-o",
        "ConnectTimeout=10",
    ]


def _ssh_run(
    ec2: Ec2Config,
    host: str,
    remote_command: str,
    *,
    check: bool = True,
    capture: bool = False,
    input_text: str = "",
    quiet: bool = False,
    timeout: float | None = None,
    exit_code: int = EXIT_GENERIC,
    secret_output: bool = False,
) -> RunResult:
    """Run one remote command over SSH. stdin defaults to an empty pipe so
    ssh can never eat the caller's stdin; input_text carries the secret
    payloads (ECR token, env values) when there are any."""
    return run(
        [*_ssh_base(ec2), f"{ec2.ssh_user}@{host}", remote_command],
        check=check,
        capture=capture,
        input_text=input_text,
        quiet=quiet,
        timeout=timeout,
        exit_code=exit_code,
        secret_output=secret_output,
    )


def _ecr_registry(image: str) -> tuple[str, str]:
    """Return (registry_host, region) for an ECR image ref."""
    host = image.split("/", 1)[0]
    match = ECR_HOST_RE.match(host)
    if match is None:
        raise DeployError(
            "ec2.registry_auth is 'ecr-token-over-ssh' but the "
            f"image ref {image!r} is not in a private ECR registry",
            EXIT_DEPLOY,
            hint="use an ECR image ref, or set ec2.registry_auth to "
            "'preauthed' and handle registry login on the instances yourself",
        )
    return host, match.group("region")


