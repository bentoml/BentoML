"""Load and validate deploy.config.json.

Generated by the bentoml-deploy-scriptgen skill — do not edit by hand; all
tunables live in deploy.config.json.

Precedence for every overridable value: CLI flag > environment variable >
deploy.config.json. Environment overrides recognized here:

    BENTOML_DEPLOY_K8S_CONTEXT     overrides targets.k8s.context
    BENTOML_DEPLOY_K8S_NAMESPACE   overrides targets.k8s.namespace
    BENTOML_DEPLOY_EC2_HOSTS       overrides targets.ec2.hosts (comma-separated)

(BENTOML_DEPLOY_IMAGE / BENTOML_DEPLOY_VERSION are handled by deploy.py.)

All validation failures exit with code 2 (config error) and name the exact
JSON path that is wrong.

JSON has no comment syntax, so any key whose name starts with "//" is
treated as free-text documentation and ignored (the generated config ships
one such note next to targets.k8s.services; keep or delete it at will).
"""

# This bundle gets committed into arbitrary user repos; the directive below
# keeps the import layout stable under any repo's ruff/isort configuration.
# isort: skip_file
from __future__ import annotations

import json
import os
import re
from dataclasses import dataclass
from dataclasses import field
from pathlib import Path
from typing import Any

from .common import EXIT_CONFIG
from .common import DeployError
from .common import warn

CONFIG_SCHEMA = "bentoml-deploy-config/v2"
# v1 named a single Deployment/Service (targets.k8s.deployment_name /
# service_name). v2 deploys one Deployment per BentoML service and carries a
# targets.k8s.services list instead; the manifest layout changed with it, so
# a v1 config is rejected rather than migrated in place.
CONFIG_SCHEMA_V1 = "bentoml-deploy-config/v1"

REGISTRY_TYPES = ("generic", "ecr", "none")

EC2_REGISTRY_AUTH_METHODS = ("ecr-token-over-ssh", "preauthed")
EC2_VERIFY_MODES = ("tunnel", "direct")

ECR_HOST_RE = re.compile(r"^\d{12}\.dkr\.ecr\.(?P<region>[a-z0-9-]+)\.amazonaws\.com$")

# Names in targets.ec2.env_names travel into remote command lines (as names
# only — never values), so they must be shell-inert by construction.
ENV_NAME_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")

# Docker's own container-name rule; shell-inert for the same reason.
CONTAINER_NAME_RE = re.compile(r"^[a-zA-Z0-9][a-zA-Z0-9_.-]*$")

# Kubernetes object names that end up in a Service name must be DNS-1035
# labels (stricter than DNS-1123: no leading digit). Every per-service slug
# names both a Deployment and a Service, so all slugs follow this rule.
DNS1035_RE = re.compile(r"^[a-z]([-a-z0-9]*[a-z0-9])?$")

# BentoML service names travel into the manifests' whitespace-separated
# BENTOML_SERVE_DEPENDS value and into `--service-name`, so a name with
# whitespace in it could never be addressed at all.
SERVICE_NAME_RE = re.compile(r"^\S+$")

# Real generator placeholders look like {{SERVICE_NAME}} or {{EC2_HOST}} —
# digits included ({{K8S_CONTEXT}}!) — but this pattern must not fire on
# legitimate braces in user-provided values.
PLACEHOLDER_RE = re.compile(r"\{\{[A-Z][A-Z0-9_]*\}\}")


def _fail(path: str, message: str, hint: str | None = None) -> DeployError:
    return DeployError(
        f"invalid deploy.config.json — {path}: {message}",
        EXIT_CONFIG,
        hint=hint,
    )


def _expect_type(value: Any, types: tuple, path: str, type_name: str) -> Any:
    if not isinstance(value, types) or isinstance(value, bool) and bool not in types:
        raise _fail(path, f"expected {type_name}, got {value!r}")
    return value


def _get_str(
    d: dict[str, Any],
    key: str,
    path: str,
    *,
    required: bool = False,
    default: str | None = None,
) -> str | None:
    if key not in d or d[key] is None:
        if required:
            raise _fail(f"{path}.{key}", "required value is missing")
        return default
    value = _expect_type(d[key], (str,), f"{path}.{key}", "a string")
    if required and not value.strip():
        raise _fail(f"{path}.{key}", "must not be empty")
    return value


def _get_int(d: dict[str, Any], key: str, path: str, default: int) -> int:
    if key not in d or d[key] is None:
        return default
    value = _expect_type(d[key], (int,), f"{path}.{key}", "an integer")
    if value <= 0:
        raise _fail(f"{path}.{key}", "must be a positive integer")
    return int(value)


def _get_float(d: dict[str, Any], key: str, path: str, default: float) -> float:
    if key not in d or d[key] is None:
        return default
    value = _expect_type(d[key], (int, float), f"{path}.{key}", "a number")
    if value <= 0:
        raise _fail(f"{path}.{key}", "must be a positive number")
    return float(value)


def _get_bool(d: dict[str, Any], key: str, path: str, default: bool) -> bool:
    if key not in d or d[key] is None:
        return default
    value = d[key]
    if not isinstance(value, bool):
        raise _fail(f"{path}.{key}", f"expected true or false, got {value!r}")
    return value


def _get_dict(d: dict[str, Any], key: str, path: str) -> dict[str, Any] | None:
    if key not in d or d[key] is None:
        return None
    return _expect_type(d[key], (dict,), f"{path}.{key}", "an object")


# The one "//" note the generated config ships; not a commented-out key.
_DOC_KEYS = ("//services",)


def _warn_unknown_keys(d: dict[str, Any], known: list[str], path: str) -> None:
    for key in d:
        # "//..." keys are the config's stand-in for JSON comments.
        if key.startswith("//"):
            shadowed = key.lstrip("/").strip()
            if key not in _DOC_KEYS and shadowed in known:
                warn(
                    f"deploy.config.json: {path}.{key} is commented out, so "
                    f"{path}.{shadowed} is NOT set and its default applies — "
                    "rename the key to activate it, or delete the note"
                )
            continue
        if key not in known:
            warn(f"deploy.config.json: unknown key {path}.{key} (typo?)")


@dataclass
class ProjectConfig:
    dir: Path  # absolute, resolved
    service: str | None = None  # `bentoml build` target, e.g. "service:MyService"
    name: str = "bentoml-service"


@dataclass
class ImageConfig:
    registry: str = ""
    repository: str = ""
    registry_type: str = "generic"  # one of REGISTRY_TYPES
    platform: str | None = None  # e.g. "linux/amd64"
    estimated_size_gb: float = 2.0
    ecr_region: str | None = None  # derived from registry host if omitted
    # registry_type "none" only: user's acknowledgement that the image was
    # already loaded into the cluster nodes (minikube/kind image load).
    local_image_preloaded: bool = False

    def ref(self, tag: str) -> str:
        if self.registry:
            return f"{self.registry}/{self.repository}:{tag}"
        return f"{self.repository}:{tag}"


@dataclass
class InferenceCheck:
    path: str
    body: Any
    expect_substring: str | None = None
    timeout_seconds: int = 60


@dataclass
class VerifyConfig:
    readyz_timeout_seconds: int = 600
    inference: InferenceCheck | None = None
    # k8s, multi-service bentos only: after the inference request, prove that
    # every dependency's own request counter moved. Without it, a gateway that
    # silently instantiated its dependencies in-process is indistinguishable
    # from a working split (it answers correctly and reports ready). Turn it
    # off only when a dependency is deliberately off the smoke test's path.
    dependency_metrics: bool = True


@dataclass
class K8sService:
    """One BentoML service == one Kubernetes Deployment + Service."""

    # BentoML service name as the bento declares it (e.g. "Summarizer") —
    # what the manifests pass to --service-name / BENTOML_SERVE_DEPENDS.
    name: str
    # DNS-1035 object-name stem: names deployment/<slug>, svc/<slug>, and the
    # manifest files <slug>-deployment.yaml / <slug>-service.yaml.
    slug: str
    # The externally exposed service (the bento's entry_service): the one
    # whose Service carries the exposure type and the one verify targets.
    entry: bool = False


@dataclass
class K8sConfig:
    context: str
    namespace: str
    # One entry per BentoML service, in rollout order: dependencies first,
    # entry last (a dependency that is not ready makes the entry service's
    # /readyz 503). Exactly one has entry=True.
    services: list[K8sService]
    manifests_dir: Path  # absolute, resolved
    image_pull_secret: str | None = None
    # 900s, deliberately MORE than the manifests' startupProbe budget
    # (failureThreshold 120 x periodSeconds 5 = 600s): with the two equal, a
    # pod that legitimately uses its whole startup budget loses the race and
    # the rollout is reported failed at the very moment it succeeds.
    rollout_timeout_seconds: int = 900
    local_port: int = 3130
    # Optional fixed NodePort (30000..32767) for a stable URL; rendered into
    # the entry service's Service manifest at generate time. When unset,
    # kubectl apply preserves whatever port the cluster already allocated.
    node_port: int | None = None

    @property
    def entry_service(self) -> K8sService:
        """The service verify talks to (never a dependency: inter-service
        payloads are pickle and must not leave the cluster)."""
        for svc in self.services:
            if svc.entry:
                return svc
        # Unreachable: _parse_k8s enforces exactly one entry: true.
        raise _fail(
            "targets.k8s.services",
            "no service is marked entry: true",
            hint='exactly one service must have "entry": true',
        )


@dataclass
class Ec2Config:
    # Existing, SSH-reachable instances only — the script never provisions
    # EC2 (the interactive bentoml-ec2-deploy skill covers provisioning).
    hosts: list[str]
    ssh_user: str
    ssh_key_path: Path  # absolute, ~ expanded, resolved
    container_name: str
    host_port: int = 3000
    # Env var NAMES only; values are read from the deploying process's
    # environment at deploy time and are never stored anywhere.
    env_names: list[str] = field(default_factory=list)
    registry_auth: str = "preauthed"  # one of EC2_REGISTRY_AUTH_METHODS
    verify_via: str = "tunnel"  # one of EC2_VERIFY_MODES
    local_tunnel_port: int = 3230


@dataclass
class Config:
    bundle_dir: Path  # directory containing deploy.config.json
    project: ProjectConfig = field(default_factory=lambda: ProjectConfig(Path(".")))
    image: ImageConfig = field(default_factory=ImageConfig)
    verify: VerifyConfig = field(default_factory=VerifyConfig)
    k8s: K8sConfig | None = None
    ec2: Ec2Config | None = None
    raw_targets: dict[str, Any] = field(default_factory=dict)

    def require_k8s(self) -> K8sConfig:
        if self.k8s is None:
            raise _fail(
                "targets.k8s",
                "no k8s target configured",
                hint="regenerate the bundle with the bentoml-deploy-scriptgen "
                "skill and include the k8s target",
            )
        return self.k8s

    def require_ec2(self) -> Ec2Config:
        if self.ec2 is None:
            raise _fail(
                "targets.ec2",
                "no ec2 target configured",
                hint="regenerate the bundle with the bentoml-deploy-scriptgen "
                "skill and include the ec2 target",
            )
        return self.ec2


def _parse_project(data: dict[str, Any], bundle_dir: Path) -> ProjectConfig:
    section = _get_dict(data, "project", "$") or {}
    _warn_unknown_keys(section, ["dir", "service", "name"], "project")
    rel = _get_str(section, "dir", "project", default="..") or ".."
    project_dir = (bundle_dir / rel).resolve()
    if not project_dir.is_dir():
        raise _fail(
            "project.dir",
            f"directory does not exist: {project_dir}",
            hint="project.dir is resolved relative to the deploy/ directory",
        )
    return ProjectConfig(
        dir=project_dir,
        service=_get_str(section, "service", "project"),
        name=_get_str(section, "name", "project", default="bentoml-service")
        or "bentoml-service",
    )


def _parse_image(data: dict[str, Any]) -> ImageConfig:
    section = _get_dict(data, "image", "$") or {}
    _warn_unknown_keys(
        section,
        [
            "registry",
            "repository",
            "registry_type",
            "platform",
            "estimated_size_gb",
            "ecr_region",
            "local_image_preloaded",
        ],
        "image",
    )
    registry = (_get_str(section, "registry", "image", default="") or "").rstrip("/")
    registry_type = (
        _get_str(section, "registry_type", "image", default="generic") or "generic"
    )
    if registry_type not in REGISTRY_TYPES:
        raise _fail(
            "image.registry_type",
            f"{registry_type!r} is not one of {list(REGISTRY_TYPES)}",
        )
    ecr_region = _get_str(section, "ecr_region", "image")
    if registry_type == "ecr" and not ecr_region:
        match = ECR_HOST_RE.match(registry)
        if match:
            ecr_region = match.group("region")
        else:
            raise _fail(
                "image.ecr_region",
                "registry_type is 'ecr' but the region could not be derived "
                f"from image.registry ({registry!r})",
                hint='set image.ecr_region explicitly, e.g. "us-west-1"',
            )
    platform = _get_str(section, "platform", "image")
    if platform and not platform.startswith("linux/"):
        raise _fail("image.platform", f'expected e.g. "linux/amd64", got {platform!r}')
    return ImageConfig(
        registry=registry,
        repository=_get_str(section, "repository", "image", default="") or "",
        registry_type=registry_type,
        platform=platform,
        estimated_size_gb=_get_float(section, "estimated_size_gb", "image", 2.0),
        ecr_region=ecr_region,
        local_image_preloaded=_get_bool(
            section, "local_image_preloaded", "image", False
        ),
    )


def _parse_verify(data: dict[str, Any]) -> VerifyConfig:
    section = _get_dict(data, "verify", "$") or {}
    _warn_unknown_keys(
        section,
        ["readyz_timeout_seconds", "inference", "dependency_metrics"],
        "verify",
    )
    inference: InferenceCheck | None = None
    inf = _get_dict(section, "inference", "verify")
    if inf is not None:
        _warn_unknown_keys(
            inf,
            ["path", "body", "expect_substring", "timeout_seconds"],
            "verify.inference",
        )
        path = _get_str(inf, "path", "verify.inference", required=True) or ""
        if not path.startswith("/"):
            raise _fail("verify.inference.path", "must start with '/'")
        if "body" not in inf:
            raise _fail("verify.inference.body", "required value is missing")
        inference = InferenceCheck(
            path=path,
            body=inf["body"],
            expect_substring=_get_str(inf, "expect_substring", "verify.inference"),
            timeout_seconds=_get_int(inf, "timeout_seconds", "verify.inference", 60),
        )
    return VerifyConfig(
        readyz_timeout_seconds=_get_int(
            section, "readyz_timeout_seconds", "verify", 600
        ),
        inference=inference,
        dependency_metrics=_get_bool(section, "dependency_metrics", "verify", True),
    )


_SERVICES_HINT = (
    "targets.k8s.services lists one object per BentoML service — "
    '[{"name": "<ServiceName>", "slug": "<dns-1035-slug>", "entry": '
    "true|false}] — in rollout order (dependencies first, entry last) with "
    "exactly one entry: true. A single-service bento has a one-element list "
    "with entry: true. Regenerate the bundle with the "
    "bentoml-deploy-scriptgen skill to get it right."
)


def _parse_k8s_services(section: dict[str, Any]) -> list[K8sService]:
    """Parse targets.k8s.services: non-empty, unique names and slugs, slugs
    DNS-1035, exactly one entry."""
    path = "targets.k8s.services"
    raw = section.get("services")
    if raw is None:
        legacy = [k for k in ("deployment_name", "service_name") if k in section]
        if legacy:
            raise _fail(
                path,
                "required value is missing — this config still carries the v1 "
                f"key(s) {legacy}",
                hint=_SERVICES_HINT,
            )
        raise _fail(path, "required value is missing", hint=_SERVICES_HINT)
    _expect_type(raw, (list,), path, "an array")
    if not raw:
        raise _fail(path, "must not be empty", hint=_SERVICES_HINT)
    services: list[K8sService] = []
    names_seen: dict[str, int] = {}
    slugs_seen: dict[str, int] = {}
    entries: list[str] = []
    for i, item in enumerate(raw):
        item_path = f"{path}[{i}]"
        _expect_type(item, (dict,), item_path, "an object")
        _warn_unknown_keys(item, ["name", "slug", "entry"], item_path)
        name = _get_str(item, "name", item_path, required=True) or ""
        if not SERVICE_NAME_RE.match(name):
            raise _fail(
                f"{item_path}.name",
                f"{name!r} must be a single whitespace-free BentoML service "
                "name (as declared in the bento)",
            )
        slug = _get_str(item, "slug", item_path, required=True) or ""
        if not DNS1035_RE.match(slug):
            raise _fail(
                f"{item_path}.slug",
                f"{slug!r} is not a valid DNS-1035 label "
                f"(must match {DNS1035_RE.pattern})",
                hint="the slug names deployment/<slug>, svc/<slug> and the "
                "<slug>-deployment.yaml / <slug>-service.yaml manifests: "
                "lowercase the service name, '_' -> '-'",
            )
        if name in names_seen:
            raise _fail(
                f"{item_path}.name",
                f"duplicate service name {name!r} (already used at "
                f"{path}[{names_seen[name]}].name)",
            )
        if slug in slugs_seen:
            raise _fail(
                f"{item_path}.slug",
                f"duplicate slug {slug!r} (already used at "
                f"{path}[{slugs_seen[slug]}].slug) — two services would "
                "share one Deployment and Service",
            )
        names_seen[name] = i
        slugs_seen[slug] = i
        entry = _get_bool(item, "entry", item_path, False)
        if entry:
            entries.append(item_path)
        services.append(K8sService(name=name, slug=slug, entry=entry))
    if not entries:
        raise _fail(
            path,
            'no service has "entry": true — exactly one must (the bento\'s '
            "entry_service, the only one exposed outside the cluster)",
            hint=_SERVICES_HINT,
        )
    if len(entries) > 1:
        raise _fail(
            path,
            f'{len(entries)} services have "entry": true ({", ".join(entries)})'
            " — exactly one must",
            hint=_SERVICES_HINT,
        )
    if not services[-1].entry:
        entry_index = next(i for i, svc in enumerate(services) if svc.entry)
        raise _fail(
            path,
            f"the entry service is at {path}[{entry_index}] but must be LAST "
            f"(it is followed by {len(services) - entry_index - 1} "
            "dependency service(s))",
            hint="the list IS the rollout order and dependencies must be "
            "ready first: the entry service's /readyz fans out to them, so "
            "rolling it out first makes it 503 until the rest catch up. "
            "Move the entry: true element to the end.",
        )
    return services


def _parse_k8s(targets: dict[str, Any], bundle_dir: Path) -> K8sConfig | None:
    section = _get_dict(targets, "k8s", "targets")
    if section is None:
        return None
    _warn_unknown_keys(
        section,
        [
            "context",
            "namespace",
            "services",
            "manifests_dir",
            "image_pull_secret",
            "rollout_timeout_seconds",
            "local_port",
            "node_port",
        ],
        "targets.k8s",
    )
    context = os.environ.get("BENTOML_DEPLOY_K8S_CONTEXT") or _get_str(
        section, "context", "targets.k8s", required=True
    )
    namespace = os.environ.get("BENTOML_DEPLOY_K8S_NAMESPACE") or _get_str(
        section, "namespace", "targets.k8s", required=True
    )
    services = _parse_k8s_services(section)
    manifests_rel = (
        _get_str(section, "manifests_dir", "targets.k8s", default="k8s") or "k8s"
    )
    local_port = _get_int(section, "local_port", "targets.k8s", 3130)
    # local_port + 1 carries the dependency /metrics scrapes during verify.
    if local_port < 1024 or local_port > 65534:
        raise _fail(
            "targets.k8s.local_port",
            "must be in 1024..65534",
            hint="verify also uses local_port + 1 (to scrape each "
            "dependency's /metrics), so both must be free",
        )
    node_port = section.get("node_port")
    if node_port is not None:
        node_port = _get_int(section, "node_port", "targets.k8s", 0)
        if node_port < 30000 or node_port > 32767:
            raise _fail(
                "targets.k8s.node_port",
                "must be in the Kubernetes NodePort range 30000..32767",
                hint="leave it unset to let the cluster allocate one "
                "(kubectl apply preserves an existing allocation)",
            )
    return K8sConfig(
        context=str(context),
        namespace=str(namespace),
        services=services,
        manifests_dir=(bundle_dir / manifests_rel).resolve(),
        image_pull_secret=_get_str(section, "image_pull_secret", "targets.k8s"),
        rollout_timeout_seconds=_get_int(
            section, "rollout_timeout_seconds", "targets.k8s", 900
        ),
        local_port=local_port,
        node_port=node_port,
    )


def _parse_ec2(
    targets: dict[str, Any], bundle_dir: Path, default_container_name: str
) -> Ec2Config | None:
    section = _get_dict(targets, "ec2", "targets")
    if section is None:
        return None
    _warn_unknown_keys(
        section,
        [
            "hosts",
            "ssh_user",
            "ssh_key_path",
            "container_name",
            "host_port",
            "env_names",
            "registry_auth",
            "verify_via",
            "local_tunnel_port",
        ],
        "targets.ec2",
    )
    hosts_env = os.environ.get("BENTOML_DEPLOY_EC2_HOSTS")
    if hosts_env:
        hosts_raw: Any = [h.strip() for h in hosts_env.split(",") if h.strip()]
    else:
        hosts_raw = section.get("hosts")
    if not isinstance(hosts_raw, list) or not hosts_raw:
        raise _fail(
            "targets.ec2.hosts",
            "must be a non-empty array of host addresses",
            hint="existing, SSH-reachable instances only — this script never "
            "provisions EC2 instances (the interactive bentoml-ec2-deploy "
            "skill does)",
        )
    hosts: list[str] = []
    for i, item in enumerate(hosts_raw):
        host = _expect_type(item, (str,), f"targets.ec2.hosts[{i}]", "a string").strip()
        if not host:
            raise _fail(f"targets.ec2.hosts[{i}]", "must not be empty")
        if "@" in host or any(c.isspace() for c in host):
            raise _fail(
                f"targets.ec2.hosts[{i}]",
                f"expected a bare hostname or IP, got {host!r}",
                hint="the SSH user goes in targets.ec2.ssh_user, not in the host",
            )
        if host in hosts:
            warn(
                f"deploy.config.json: duplicate host {host!r} in "
                "targets.ec2.hosts — deploying to it once"
            )
        else:
            hosts.append(host)
    ssh_user = _get_str(section, "ssh_user", "targets.ec2", required=True) or ""
    if "@" in ssh_user or any(c.isspace() for c in ssh_user):
        raise _fail("targets.ec2.ssh_user", f"invalid user name {ssh_user!r}")
    key_raw = _get_str(section, "ssh_key_path", "targets.ec2", required=True) or ""
    ssh_key_path = Path(key_raw).expanduser()
    if not ssh_key_path.is_absolute():
        ssh_key_path = bundle_dir / ssh_key_path
    ssh_key_path = ssh_key_path.resolve()
    container_name = (
        _get_str(
            section, "container_name", "targets.ec2", default=default_container_name
        )
        or default_container_name
    )
    if not CONTAINER_NAME_RE.match(container_name):
        raise _fail(
            "targets.ec2.container_name",
            f"{container_name!r} is not a valid docker container name "
            f"(must match {CONTAINER_NAME_RE.pattern})",
        )
    host_port = _get_int(section, "host_port", "targets.ec2", 3000)
    if host_port > 65535:
        raise _fail("targets.ec2.host_port", "must be in 1..65535")
    env_names: list[str] = []
    env_names_raw = section.get("env_names")
    if env_names_raw is not None:
        _expect_type(env_names_raw, (list,), "targets.ec2.env_names", "an array")
        for i, item in enumerate(env_names_raw):
            name = _expect_type(item, (str,), f"targets.ec2.env_names[{i}]", "a string")
            if not ENV_NAME_RE.match(name):
                raise _fail(
                    f"targets.ec2.env_names[{i}]",
                    f"{name!r} is not a valid environment variable name "
                    f"(must match {ENV_NAME_RE.pattern})",
                    hint="env_names lists variable NAMES only — the values "
                    "are read from the deploying process's environment at "
                    "deploy time and are never stored",
                )
            if name in env_names:
                warn(
                    f"deploy.config.json: duplicate name {name!r} in "
                    "targets.ec2.env_names"
                )
            else:
                env_names.append(name)
    registry_auth = (
        _get_str(section, "registry_auth", "targets.ec2", default="preauthed")
        or "preauthed"
    )
    if registry_auth not in EC2_REGISTRY_AUTH_METHODS:
        raise _fail(
            "targets.ec2.registry_auth",
            f"{registry_auth!r} is not one of {list(EC2_REGISTRY_AUTH_METHODS)}",
            hint="'ecr-token-over-ssh' pipes a locally minted ECR token to "
            "each host; 'preauthed' means the instances can already pull "
            "(instance profile, or a docker login you maintain)",
        )
    verify_via = (
        _get_str(section, "verify_via", "targets.ec2", default="tunnel") or "tunnel"
    )
    if verify_via not in EC2_VERIFY_MODES:
        raise _fail(
            "targets.ec2.verify_via",
            f"{verify_via!r} is not one of {list(EC2_VERIFY_MODES)}",
        )
    local_tunnel_port = _get_int(section, "local_tunnel_port", "targets.ec2", 3230)
    if local_tunnel_port < 1024 or local_tunnel_port > 65535:
        raise _fail("targets.ec2.local_tunnel_port", "must be in 1024..65535")
    return Ec2Config(
        hosts=hosts,
        ssh_user=ssh_user,
        ssh_key_path=ssh_key_path,
        container_name=container_name,
        host_port=host_port,
        env_names=env_names,
        registry_auth=registry_auth,
        verify_via=verify_via,
        local_tunnel_port=local_tunnel_port,
    )


def load_config(config_path: Path) -> Config:
    if not config_path.is_file():
        raise DeployError(
            f"config file not found: {config_path}",
            EXIT_CONFIG,
            hint="pass --config PATH, or run from a project that has a "
            "generated deploy/deploy.config.json",
        )
    try:
        data = json.loads(config_path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise DeployError(
            f"config file is not valid JSON ({config_path}): {exc}",
            EXIT_CONFIG,
        ) from None
    if not isinstance(data, dict):
        raise _fail("$", "top level must be a JSON object")
    leftover = json.dumps(data)
    if PLACEHOLDER_RE.search(leftover):
        raise _fail(
            "$",
            "unreplaced {{PLACEHOLDER}} values remain in the config",
            hint="the bentoml-deploy-scriptgen skill must substitute every "
            "placeholder when generating the bundle",
        )
    schema = _get_str(data, "schema", "$", default=CONFIG_SCHEMA)
    if schema == CONFIG_SCHEMA_V1:
        raise _fail(
            "schema",
            f"this config is {CONFIG_SCHEMA_V1} but this bundle requires "
            f"{CONFIG_SCHEMA}; the k8s target now deploys one Deployment per "
            "BentoML service, so targets.k8s.deployment_name and "
            "targets.k8s.service_name were replaced by a targets.k8s.services "
            'list ([{"name": ..., "slug": ..., "entry": true|false}], '
            "dependencies first, entry last, exactly one entry)",
            hint="the manifest layout changed with it (one "
            "<slug>-deployment.yaml plus one <slug>-service.yaml per "
            "service), so regenerate the whole bundle with the "
            "bentoml-deploy-scriptgen skill instead of hand-editing this "
            "file",
        )
    if schema != CONFIG_SCHEMA:
        raise _fail("schema", f"expected {CONFIG_SCHEMA!r}, got {schema!r}")
    _warn_unknown_keys(data, ["schema", "project", "image", "verify", "targets"], "$")
    bundle_dir = config_path.resolve().parent
    targets = _get_dict(data, "targets", "$") or {}
    # Without this, a mis-cased "K8s" reads as "no k8s target configured".
    _warn_unknown_keys(targets, ["k8s", "ec2"], "targets")
    project = _parse_project(data, bundle_dir)
    return Config(
        bundle_dir=bundle_dir,
        project=project,
        image=_parse_image(data),
        verify=_parse_verify(data),
        k8s=_parse_k8s(targets, bundle_dir),
        ec2=_parse_ec2(targets, bundle_dir, project.name),
        raw_targets=targets,
    )
