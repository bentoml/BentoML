def render_manifests_to_dir(
    cfg: Config, target: str, image: str | None, out_dir: Path
) -> None:
    """Write the manifests rendered from config.yml into out_dir and stop.

    Nothing is applied, no cluster is contacted, and no image is built: this is
    the "show me exactly what would be applied" path — review a config change,
    diff two revisions, or seed a GitOps repo.
    """
    if target != "k8s":
        raise DeployError(
            f"--render-only applies to --target k8s only (got {target!r})",
            EXIT_CONFIG,
            hint="the ec2 target has no manifests to render",
        )
    k8s = cfg.require_k8s()
    if k8s.manifests_dir is not None:
        raise DeployError(
            "--render-only has nothing to render: kubernetes.manifests_dir is "
            f"set ({k8s.manifests_dir}), so those files are applied as-is "
            "instead of being rendered from config.yml",
            EXIT_CONFIG,
            hint="unset kubernetes.manifests_dir to go back to rendering from "
            "config.yml (rendering is the normal mode; manifests_dir is the "
            "escape hatch for YAML you have taken ownership of)",
        )
    if image is None:
        raise DeployError(
            "cannot render: the image reference is unresolved",
            EXIT_CONFIG,
            hint="the rendered Deployments carry a real image ref. The tag is "
            "the bento version, which defaults to the project's short git SHA "
            "— run from a git checkout, or pass --version TAG / --image REF. "
            "With an empty `image:` the ref is the bento tag itself, which "
            "needs the discovered topology (or an explicit --image REF).",
        )
    section(f"render-only: config.yml -> {out_dir} (image {image})")
    written, removed = write_manifests(cfg, image, out_dir)
    for path in written:
        log("  wrote " + str(path))
    for path in removed:
        # A leftover from an earlier render (renamed slug, deleted service,
        # autoscaling turned off). Left in place, `kubectl apply -f <dir>` would
        # re-create the object it describes on the next apply.
        log("  removed stale " + str(path))
    stray = unmanaged_files(out_dir)
    if stray:
        warn(
            "this directory also holds file(s) this renderer does not own: "
            + ", ".join(path.name for path in stray)
            + " — they are left untouched, but `kubectl apply -f <dir>` "
            "applies them too"
        )
    order = " -> ".join(svc.name for svc in k8s.services)
    log(f"{len(written)} manifest(s) written; rollout order would be: {order}")
    log(
        "nothing was applied. Review/diff them, then either run the same "
        "command without --render-only, or apply by hand:\n"
        f"  kubectl --context {k8s.context} -n {k8s.namespace} apply -f {out_dir}"
    )
    log(
        "to take ownership of this YAML instead: commit this directory and set "
        "kubernetes.manifests_dir to it — from then on these files are applied "
        "VERBATIM (image ref included), so re-render or edit the tag per build "
        "(see the README)"
    )


