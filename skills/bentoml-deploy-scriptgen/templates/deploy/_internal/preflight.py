"""Preflight checks: every external dependency is probed before any state is
mutated. Each check has a stable id and an actionable failure message; all
preflight failures exit with code 3.

Generated by the bentoml-deploy-scriptgen skill — do not edit by hand; all
tunables live in config.yml.
"""

