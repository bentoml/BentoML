def registry_checks(
    cfg: Config, local_only: bool = False, skipped: list | None = None
) -> list[Check]:
    if cfg.image.kind == REGISTRY_KIND_NONE:
        # Nothing is ever pushed; the image must already be on the cluster
        # nodes. This is a pure config check, so it runs in local-only too.
        return [local_preload_check(cfg)]
    if cfg.image.kind == REGISTRY_KIND_ECR:
        if local_only:
            if skipped is not None:
                skipped += [
                    "registry.aws-credentials (--local-only)",
                    "registry.ecr-token (--local-only)",
                    "registry.ecr-repository (--local-only)",
                ]

            def aws_cli_only() -> str | None:
                _which("aws", "install the AWS CLI v2")
                return None

            return [("registry.aws-cli", aws_cli_only)]
        return _ecr_checks(cfg)
    if local_only:
        if skipped is not None:
            skipped.append("registry.docker-auth (--local-only)")
        return []
    return _generic_registry_checks(cfg)


def local_preload_check(cfg: Config) -> Check:
    """Empty `image:` — the kind/minikube case: nothing is pushed anywhere, so
    the image must already be on the cluster nodes under its bento tag. Nothing
    outside the cluster can prove that, so this check states it loudly instead
    of pretending to verify it (the failure mode it warns about is an
    ImagePullBackOff, which the rollout wait reports within a few seconds of the
    pods reaching that state)."""

    def preloaded() -> str | None:
        warn(
            "`image:` is empty, so NOTHING IS PUSHED: the image name is the "
            "bento tag and every node must already have it. Load it first — "
            "minikube image load <bento>:<tag>, or kind load docker-image "
            "<bento>:<tag> --name <cluster> — or set `image: "
            "<registry>/<repository>` in config.yml to push it instead. An "
            "image that is missing on the nodes fails as ImagePullBackOff, "
            "which the rollout wait reports as soon as kubelet gives up."
        )
        return "no registry configured; image must be preloaded on the nodes"

    return ("registry.local-image", preloaded)


def image_exists_checks(cfg: Config, image_ref: str) -> list[Check]:
    """--skip-build only: verify the image actually exists before the
    deploy burns the rollout timeout discovering it does not. Absence is a
    hard failure; an inconclusive probe (bad credentials, no docker) only
    warns."""
    if cfg.image.kind == REGISTRY_KIND_NONE:
        return [local_preload_check(cfg)]

    def image_exists() -> str | None:
        host = image_ref.split("/", 1)[0] if "/" in image_ref else ""
        ecr_match = ECR_HOST_RE.match(host)
        if ecr_match and shutil.which("aws"):
            return _probe_ecr_image(image_ref, ecr_match.group("region"))
        if shutil.which("docker"):
            return _probe_manifest(image_ref)
        warn(
            f"cannot verify that {image_ref} exists (no docker CLI, not an "
            "ECR ref probe-able via aws) — if it is missing, the rollout "
            "will fail with ImagePullBackOff"
        )
        return "UNVERIFIED (no probe tool available)"

    return [("registry.image-exists", image_exists)]


def _probe_ecr_image(image_ref: str, region: str) -> str | None:
    rest = image_ref.split("/", 1)[1]
    if "@" in rest:
        repo, digest = rest.split("@", 1)
        image_id = f"imageDigest={digest}"
    elif ":" in rest:
        repo, tag = rest.rsplit(":", 1)
        image_id = f"imageTag={tag}"
    else:
        repo, image_id = rest, "imageTag=latest"
    res = run(
        [
            "aws",
            "ecr",
            "describe-images",
            "--repository-name",
            repo,
            "--image-ids",
            image_id,
            "--region",
            region,
            "--output",
            "json",
        ],
        capture=True,
        quiet=True,
        check=False,
        timeout=60,
    )
    if res.returncode == 0:
        return "found in ECR"
    err = res.stderr.strip() or res.stdout.strip()
    if "ImageNotFoundException" in err or "RepositoryNotFoundException" in err:
        raise CheckFailed(
            f"image {image_ref} does not exist in ECR",
            hint="run without --skip-build to build and push it, or pass an "
            "existing tag via --image/--version",
        )
    warn(f"could not verify {image_ref} in ECR ({err[:200]}) — proceeding")
    return "UNVERIFIED (ECR probe failed)"


def _probe_manifest(image_ref: str) -> str | None:
    res = run(
        ["docker", "manifest", "inspect", image_ref],
        capture=True,
        quiet=True,
        check=False,
        timeout=120,
    )
    if res.returncode == 0:
        return "manifest found in registry"
    err = res.stderr.strip() or res.stdout.strip()
    lowered = err.lower()
    if (
        "manifest unknown" in lowered
        or "no such manifest" in lowered
        or "not found" in lowered
        or "name unknown" in lowered
    ):
        raise CheckFailed(
            f"image {image_ref} does not exist in the registry",
            hint="run without --skip-build to build and push it, or pass an "
            "existing tag via --image/--version",
        )
    warn(
        f"could not verify {image_ref} exists ({err[:200]}) — proceeding; "
        "if it is missing, the rollout will fail with ImagePullBackOff"
    )
    return "UNVERIFIED (manifest probe failed)"


def _ecr_checks(cfg: Config) -> list[Check]:
    region = cfg.image.ecr_region or ""

    def aws_cli() -> str | None:
        _which("aws", "install the AWS CLI v2")
        return None

    def aws_credentials() -> str | None:
        res = run(
            ["aws", "sts", "get-caller-identity", "--output", "json"],
            capture=True,
            quiet=True,
            check=False,
            timeout=60,
        )
        if res.returncode != 0:
            raise CheckFailed(
                f"AWS credentials are not usable: {(res.stderr.strip() or res.stdout.strip())[:300]}",
                hint="export AWS_ACCESS_KEY_ID/AWS_SECRET_ACCESS_KEY (or "
                "AWS_PROFILE, or run 'aws sso login') for an identity that "
                "may push to ECR",
            )
        try:
            arn = json.loads(res.stdout).get("Arn", "")
        except json.JSONDecodeError:
            arn = ""
        return arn or None

    def ecr_token() -> str | None:
        # Actually probe that an ECR auth token can be minted (this is what
        # push will use — a fresh token per run, so it cannot be expired).
        res = run(
            ["aws", "ecr", "get-login-password", "--region", region],
            capture=True,
            quiet=True,
            check=False,
            timeout=60,
            secret_output=True,
        )
        if res.returncode != 0:
            raise CheckFailed(
                f"could not obtain an ECR auth token for region {region}: {res.stderr.strip()[:300]}",
                hint="check the region and that the identity has "
                "ecr:GetAuthorizationToken",
            )
        return f"token ok for {region}"

    def ecr_repository() -> str | None:
        res = run(
            [
                "aws",
                "ecr",
                "describe-repositories",
                "--repository-names",
                cfg.image.repository,
                "--region",
                region,
                "--output",
                "json",
            ],
            capture=True,
            quiet=True,
            check=False,
            timeout=60,
        )
        if res.returncode != 0:
            if "RepositoryNotFoundException" in (res.stderr + res.stdout):
                warn(
                    f"ECR repository {cfg.image.repository!r} does not exist yet — it will be "
                    "created before push"
                )
                return "will create on push"
            raise CheckFailed(
                f"could not describe ECR repository {cfg.image.repository!r}: {res.stderr.strip()[:300]}",
                hint="check ecr:DescribeRepositories permission and the "
                "repository name",
            )
        return "repository exists"

    return [
        ("registry.aws-cli", aws_cli),
        ("registry.aws-credentials", aws_credentials),
        ("registry.ecr-token", ecr_token),
        ("registry.ecr-repository", ecr_repository),
    ]


def _generic_registry_checks(cfg: Config) -> list[Check]:
    def docker_auth() -> str | None:
        host = cfg.image.registry or "docker.io"
        config_file = Path.home() / ".docker" / "config.json"
        if not config_file.is_file():
            raise CheckFailed(
                f"no docker credentials found ({config_file} missing) for {host}",
                hint=f"run: docker login {host}",
            )
        try:
            data = json.loads(config_file.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            raise CheckFailed(f"could not read {config_file}: {exc}")
        auths = data.get("auths", {}) or {}
        helpers = data.get("credHelpers", {}) or {}
        lookup = host if host != "docker.io" else "https://index.docker.io/v1/"
        if lookup in auths or host in auths or host in helpers:
            return f"credentials configured for {host}"
        if data.get("credsStore"):
            warn(
                "docker uses a credential store ({!r}) — cannot verify {} auth "
                "ahead of time; push will fail if you are not logged in".format(
                    data["credsStore"], host
                )
            )
            return "credential store in use"
        raise CheckFailed(
            f"no stored docker credentials for {host}",
            hint=f"run: docker login {host}",
        )

    return [("registry.docker-auth", docker_auth)]


